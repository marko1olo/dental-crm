/**
 * Форматирует и выводит в консоль развёрнутый архитектурный манифест падения.
 *
 * @param {string} gateKey - Ключ шлюза из FAILURE_MANIFESTOS
 * @param {object} [extra] - Дополнительные данные контекста (файл, ошибка, количество дефектов)
 */
export function printFailureManifesto(gateKey, extra = {}) {
	const manifesto = FAILURE_MANIFESTOS[gateKey] || {
		title: `МАШИННЫЙ БАРЬЕР КАЧЕСТВА: ${gateKey}`,
		summary: "Обнаружено критическое нарушение архитектурных или клинических стандартов DENTE CRM.",
		clinicalDanger: "Нарушение ставит под угрозу стабильность работы клиники, целостность медицинских или финансовых данных.",
		rottenPatchWarning: "Запрещены любые поверхностные косметические заплатки. Исправление ведётся по Первым Принципам.",
		remediationSteps: ["Изучи детали ошибки выше и устрани первопричину в коде."],
	};

	const red = (s) => `\x1b[31m${s}\x1b[0m`;
	const bold = (s) => `\x1b[1m${s}\x1b[0m`;
	const yellow = (s) => `\x1b[33m${s}\x1b[0m`;
	const cyan = (s) => `\x1b[36m${s}\x1b[0m`;
	const dim = (s) => `\x1b[2m${s}\x1b[0m`;

	const separator = "=".repeat(80);

	console.error("\n" + red(separator));
	console.error(bold(red(`🚨 СТОП! АРХИТЕКТУРНЫЙ БРАК! ЧУВАЧОК, ДАВАЙ-КА РАБОТАЙ — ЧИНИ ПОЛНОЦЕННО!`)));
	console.error(red(separator));
	console.error(bold(cyan(`\n🏛️  ШЛЮЗ: ${manifesto.title}`)));
	console.error(dim(`   ${manifesto.summary}\n`));

	if (extra.details) {
		console.error(yellow(`🔍 ДЕТАЛИ СБОЯ:`));
		console.error(`   ${extra.details}\n`);
	}

	console.error(bold("⚠️  КЛИНИЧЕСКАЯ И АРХИТЕКТУРНАЯ УГРОЗА ДЛЯ КЛИНИКИ:"));
	console.error(`   ${manifesto.clinicalDanger}\n`);

	console.error(bold(red("⛔ ПОЧЕМУ ЗАПЛАТКА ИЛИ КОСТЫЛЬ — ЭТО САБОТАЖ (РОТТЕН СИД):")));
	console.error(`   ${manifesto.rottenPatchWarning}\n`);

	console.error(bold(cyan("🛠️  КАНОНИЧЕСКИЙ АЛГОРИТМ ИСПРАВЛЕНИЯ (НИКАКИХ ПРИПАРОК):")));
	for (const step of manifesto.remediationSteps) {
		console.error(`   ${step}`);
	}

	console.error("\n" + red(separator));
	console.error(bold(red(`❌ ДЕЙСТВИЕ ЗАБЛОКИРОВАНО. ИДИ И ПЕРЕДЕЛЫВАЙ НА СОВЕСТЬ ПО ПЕРВЫМ ПРИНЦИПАМ!`)));
	console.error(red(separator) + "\n");
}
