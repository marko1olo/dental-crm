/**
 * Ветка отказа сервера делегирована готовой границе, а её `message` печатает
 * человеческую причину и подставляет текст ошибки. Отступ и переносы внутри
 * тега безразличны; слова «API» в тексте нет — это ловят отдельные forbidIn.
 */
export const bootServerErrorDelegationPattern =
	/<AppLoadingState\s+message=\{`Рабочий сервер недоступен: \$\{error\}`\}/;

/**
 * Повтор загрузки сначала снимает устаревшую ошибку, потом заново грузит смену.
 * Порядок закреплён намеренно: иначе повторная загрузка идёт под всё ещё
 * показанным старым сообщением. Окно в 200 символов не даёт `setError(null)` из
 * чужого обработчика дотянуться до `loadDashboard` в следующем.
 */
export const bootRetryClearsErrorPattern =
	/setError\(null\);[\s\S]{0,200}?loadDashboard\(\)\s*\.catch/;

/**
 * Отказ ПОВТОРНОЙ загрузки проходит через operatorWorkflowFailureMessage с
 * человеческим заголовком, и пойманная ошибка обязана попасть туда же вторым
 * аргументом — иначе сотрудник видит заголовок без причины. При семи табах
 * отступа вызов занимает 93 колонки против lineWidth 80, поэтому форматтер
 * обязан разбить его на четыре строки.
 */
export const bootRetryFailureIsOperatorReadablePattern =
	/operatorWorkflowFailureMessage\(\s*"Не удалось загрузить данные клиники",\s*loadError,?\s*\)/;
