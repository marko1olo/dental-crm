import { existsSync, readFileSync } from "node:fs";

/**
 * Файлы оболочки: сам App плюс то, во что из него вынесли разметку.
 *
 * Все три проверены на импортёра 2026-08-11:
 *   AppRouter.tsx                 <- App.tsx:71  (31 граница маршрута)
 *   FullscreenOnboardingWizard.tsx <- App.tsx:70 (шаги и выбор роли)
 */
export const APP_SHELL_FILES = [
	"apps/web/src/App.tsx",
	"apps/web/src/AppRouter.tsx",
	"apps/web/src/FullscreenOnboardingWizard.tsx",
];

/**
 * Текст оболочки целиком.
 *
 * @returns {string} Склейка через перевод строки; переводы нормализованы, иначе
 *   образцы с `\s*` ведут себя по-разному на CRLF и LF.
 * @throws {Error} Если не найдено ни одного файла — молчаливая пустая строка
 *   опаснее отказа: проверка «этого нет» по пустоте проходит ВСЕГДА.
 */
export function readAppShellSourceSync() {
	const present = APP_SHELL_FILES.filter((file) => existsSync(file));
	if (present.length === 0)
		throw new Error(
			`Не найден ни один файл оболочки: ${APP_SHELL_FILES.join(", ")}. ` +
				"Проверка не может сверяться с пустотой и обязана упасть.",
		);
	return present
		.map((file) => readFileSync(file, "utf8"))
		.join("\n")
		.replace(/\r\n/g, "\n");
}
