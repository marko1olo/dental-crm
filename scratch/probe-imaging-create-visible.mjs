/** Появляется ли только что созданный снимок в ленте и в дашборде. */
import { readFileSync } from "node:fs";
import pg from "pg";
const API = process.env.DENTE_API_URL || "http://127.0.0.1:4100";
const OWNER = "e44d32ca-7777-4c00-a001-c88f01b92e21";
const envValue = (k) => { const l = readFileSync(".env","utf8").split(/\r?\n/).find(x=>x.startsWith(k+"=")); return l ? l.slice(k.length+1).trim() : null; };
const login = await fetch(`${API}/api/auth/clinic/login`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ email: "clinic@example.com", password: "dente2026" }) }).then(r => r.json());
const unlock = await fetch(`${API}/api/auth/staff/unlock`, { method: "POST", headers: { "Content-Type": "application/json", "x-dente-clinic-token": login.clinicToken }, body: JSON.stringify({ userId: OWNER, pinCode: "0000" }) }).then(r => r.json());
const H = { "Content-Type": "application/json", "x-dente-clinic-token": login.clinicToken, "x-dente-staff-token": unlock.staffToken };
const dash0 = await fetch(`${API}/api/dashboard`, { headers: H }).then(r => r.json());
const patient = dash0.patients[0];
const res = await fetch(`${API}/api/imaging/studies`, { method: "POST", headers: H, body: JSON.stringify({ patientId: patient.id, kind: "periapical", title: "Проба видимости", toothCode: "36", sourceKind: "manual_upload", sourceName: "проба" }) });
const body = await res.json().catch(() => ({}));
const id = body?.study?.id ?? body?.id ?? null;
console.log(`создание: HTTP ${res.status}, id ${id}`);
console.log(`ответ: ${JSON.stringify(body).slice(0, 200)}`);
const c = new pg.Client({ connectionString: envValue("DATABASE_URL") });
await c.connect();
const inDb = await c.query(`select id, organization_id, patient_id, title, kind from imaging_studies order by created_at desc limit 3`);
console.log(`\nв таблице imaging_studies: ${inDb.rows.length} последних`);
for (const r of inDb.rows) console.log(`   ${r.title} | орг ${r.organization_id} | пациент ${r.patient_id}`);
const list = await fetch(`${API}/api/imaging/studies`, { headers: H });
const lb = await list.json().catch(() => ({}));
const arr = Array.isArray(lb) ? lb : lb.studies || [];
console.log(`\nGET /api/imaging/studies: HTTP ${list.status}, записей ${arr.length}`);
const dash1 = await fetch(`${API}/api/dashboard`, { headers: H }).then(r => r.json());
console.log(`дашборд imagingStudies: ${(dash1.imagingStudies || []).length}`);
console.log(`организация пациента: ${inDb.rows[0]?.patient_id === patient.id ? "совпадает" : "НЕ совпадает"}`);
if (id) await c.query(`delete from imaging_studies where id = $1`, [id]).catch(()=>{});
await c.end();
