/**
 * Проверяет, какие медицинские слова textToNumbers превращает в цифры.
 *
 * Функция переводит числа, надиктованные словами, в цифры. Если точного
 * совпадения нет, она сравнивает НАЧАЛО слова с корнями числительных по
 * расстоянию Левенштейна. Из-за этого любое длинное слово, начало
 * которого похоже на числительное, становится числом:
 *   «пульпит» -> начало «пуль» против корня «нуль», расстояние 1 -> 0
 *   «периодонтит» -> начало «периодо» против «первого», расстояние 2 -> 1
 *
 * Последствия для клиники:
 *   1. Состояние зуба определяется по тексту ПОСЛЕ этой замены, поэтому
 *      слова «пульпит» и «периодонтит» до проверки не доживают, и зуб
 *      получает «запланировано» вместо «лечение».
 *   2. В текст подставляются цифры, а по этому же тексту ищутся номера
 *      зубов. Двузначное число в диапазоне 11–48 создаёт зуб, которого
 *      врач не называл.
 *
 * Скрипт печатает пострадавшие слова и отдельно те, что порождают
 * призрачный номер зуба.
 */
import { textToNumbers } from "../apps/web/src/lib/stringUtils.ts";
import { parseVisitDictationLocal } from "../apps/web/src/lib/smartVisitParser.ts";

const VOCAB = [
	// диагнозы и состояния
	"пульпит", "пульпита", "периодонтит", "периодонтита", "кариес", "гингивит",
	"пародонтит", "перикоронит", "остеомиелит", "киста", "гранулема", "абсцесс",
	"стоматит", "флюороз", "гиперестезия", "рецессия", "клиновидный",
	// вмешательства и материалы
	"пломба", "пломбирование", "реставрация", "экстракция", "имплантация",
	"коронка", "винир", "вкладка", "депульпирование", "резекция", "кюретаж",
	"анестезия", "инфильтрационная", "проводниковая", "аппликационная",
	"коффердам", "гуттаперча", "силер", "штифт", "матрица",
	// материалы и препараты
	"седация", "супрастин", "лидокаин", "артикаин", "мепивакаин",
	"хлоргексидин", "кальцийсодержащий", "фторлак",
	// анатомия и обследование
	"перкуссия", "пальпация", "зондирование", "слизистая", "десна",
	"альвеола", "фуркация", "апекс", "дентин", "пульпа", "эмаль",
	"рентген", "ортопантомограмма", "прицельный", "томограмма",
	// служебные слова диктовки
	"жалобы", "жалуется", "анамнез", "диагноз", "лечение", "план", "сделал",
	"пациент", "пришел", "успешно", "хирург", "терапевт", "ортопед",
];

const NUMBER_WORDS = [
	"ноль", "один", "одна", "два", "две", "три", "четыре", "пять", "шесть",
	"семь", "восемь", "девять", "десять", "одиннадцать", "двенадцать",
	"тринадцать", "четырнадцать", "пятнадцать", "шестнадцать", "семнадцать",
	"восемнадцать", "девятнадцать", "двадцать", "тридцать", "сорок",
	"пятьдесят", "шестьдесят", "семьдесят", "восемьдесят", "девяносто",
	"сто", "двести", "тысяча", "тысячи", "тысяч",
	// обиходные падежные формы, которые обязаны продолжать работать
	"одиннадцати", "двенадцати", "шестнадцати", "тридцати", "сорока", "пяти",
	"двадцати", "сорок", "семидесяти",
	"четырёх", "четырех", "трёх", "трех", "двух", "одного", "восьми", "девяти",
	"десяти", "ста", "тысячей", "пятнадцати", "восемнадцати", "девятнадцати",
	"шестидесяти", "восьмидесяти", "пятидесяти", "девяноста", "двухсот",
];

const damaged = [];
for (const word of VOCAB) {
	const out = textToNumbers(word).trim();
	if (out.toLowerCase() !== word.toLowerCase()) damaged.push({ word, out });
}

const broken = [];
for (const nw of NUMBER_WORDS) {
	const out = textToNumbers(nw).trim();
	if (!/\d/.test(out)) broken.push({ word: nw, out });
}

console.log(`Медицинских слов проверено: ${VOCAB.length}`);
console.log(`ИСКАЖЕНО: ${damaged.length}\n`);
for (const d of damaged) console.log(`  «${d.word}»  ->  «${d.out}»`);

console.log(`\nЧислительных проверено: ${NUMBER_WORDS.length}`);
console.log(`НЕ РАСПОЗНАНО (должны стать цифрами): ${broken.length}`);
for (const b of broken) console.log(`  «${b.word}»  ->  «${b.out}»`);

// Призрачные зубы: слово, из которого рождается номер зуба.
console.log(`\n=== Призрачные номера зубов из медицинских слов ===`);
let phantoms = 0;
for (const word of VOCAB) {
	const phrase = `${word} ${word}`;
	const parsed = parseVisitDictationLocal(phrase);
	if (parsed.toothUpdates.length > 0) {
		phantoms += 1;
		console.log(`  «${phrase}» -> зубы ${JSON.stringify(parsed.toothUpdates)}  (текст стал «${textToNumbers(phrase).trim()}»)`);
	}
}
if (!phantoms) console.log("  не найдено");

// Состояние зуба по диагнозу.
console.log(`\n=== Состояние зуба по названию диагноза ===`);
for (const [phrase, expected] of [
	["36 зуб пульпит", "treatment"],
	["45 зуб периодонтит", "treatment"],
	["11 зуб кариес", "treatment"],
	["22 зуб гранулема", "treatment"],
	["37 зуб киста", "treatment"],
]) {
	const parsed = parseVisitDictationLocal(phrase);
	const state = parsed.toothUpdates[0]?.state ?? "нет зуба";
	console.log(`  ${state === expected ? "OK  " : "СБОЙ"} «${phrase}» -> ${state}, ожидалось ${expected}`);
}
