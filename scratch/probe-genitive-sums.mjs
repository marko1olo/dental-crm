/**
 * Как разбираются суммы, надиктованные в именительном и родительном
 * падеже. Через textToNumbers идёт диктовка суммы платежа, поэтому
 * расхождение здесь — это неверная сумма в кассе.
 */
import { textToNumbers } from "../apps/web/src/lib/stringUtils.ts";

const CASES = [
	["одна тысяча", "1000"],
	["две тысячи", "2000"],
	["двух тысяч", "2000"],
	["три тысячи", "3000"],
	["трёх тысяч", "3000"],
	["пять тысяч", "5000"],
	["пяти тысяч", "5000"],
	["двадцать тысяч", "20000"],
	["двадцати тысяч", "20000"],
	["тридцать тысяч", "30000"],
	["тридцати тысяч", "30000"],
	["две тысячи пятьсот", "2500"],
	["двух тысяч пятисот", "2500"],
	["сто двадцать три", "123"],
	["восемь девятьсот шестнадцать", "8 916"],
];

let bad = 0;
for (const [input, expected] of CASES) {
	const out = textToNumbers(input).trim().replace(/\s+/g, " ");
	const ok = out === expected;
	if (!ok) bad += 1;
	console.log(`  ${ok ? "OK  " : "СБОЙ"} «${input}» -> «${out}»${ok ? "" : `, ожидалось «${expected}»`}`);
}
console.log(`\nпроверок: ${CASES.length}, сбоев ${bad}`);
process.exit(bad ? 1 : 0);
