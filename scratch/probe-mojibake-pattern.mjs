/**
 * Проверяет, что шаблон поиска мойибаки ловит оба семейства и не
 * срабатывает на живом русском тексте.
 *
 * Прежний шаблон видел только мойибаку из Latin-1 и пропускал
 * кириллическую (UTF-8, прочитанный как CP1251) — из-за чего штатная
 * проверка smoke:web-text-encoding рапортовала ok при 17 битых строках в
 * исходниках.
 *
 * Первая версия нового шаблона брала широкий диапазон «кириллическая буква
 * плюс что-нибудь из Latin-1» и дала восемь ложных срабатываний на живых
 * файлах: закрывающая кавычка законно идёт сразу за буквой — «СМС»,
 * «Актив». Поэтому здесь проверяются обе стороны: и что ловит, и что не
 * ловит лишнего.
 */
import { createMojibakePattern } from "../scripts/lib/mojibakePattern.mjs";

const pattern = createMojibakePattern();

const BAD = [
	["разделитель из U+00B7", "0 разметок В· локально 19:36"],
	["кавычки-ёлочки", "Нажмите В«Стоп записьВ», чтобы завершить."],
	["градус", "Температура 36В°"],
	["длинное тире", "Снимки вЂ” прицельные и ОПТГ"],
	["многоточие", "ЗагрузкавЂ¦"],
	["русский текст как CP1251", "РџСЂРёРІРµС‚"],
	["латинское семейство", "Ð¿Ñ€Ð¸Ð²ÐµÑ‚"],
	["символ замены", "текст � текст"],
];

const GOOD = [
	["обычный русский", "Врач принял пациента. Смена закрыта."],
	["слова на В, Р, С", "Возврат, Расписание, Смена, время, Всё"],
	["аббревиатура в кавычках", "Отправить «СМС» пациенту"],
	["слово на В перед кавычкой", "Канал «Актив» и режим «ТВ»"],
	["типографские кавычки", "Нажмите «Стоп запись», чтобы завершить."],
	["средняя точка", "0 разметок · локально 19:36 · сервер 19:36"],
	["длинное тире", "Снимки — прицельные и ОПТГ"],
	["английский", 'const label = "Patient";'],
];

let bad = 0;
console.log("должно ловиться:");
for (const [name, sample] of BAD) {
	pattern.lastIndex = 0;
	const caught = pattern.test(sample);
	if (!caught) bad += 1;
	console.log(`  ${caught ? "OK  " : "СБОЙ"} ${name}`);
}

console.log("\nне должно ловиться (живой текст):");
for (const [name, sample] of GOOD) {
	pattern.lastIndex = 0;
	const caught = pattern.test(sample);
	if (caught) bad += 1;
	console.log(`  ${caught ? "СБОЙ" : "OK  "} ${name}${caught ? ` — ложное срабатывание на «${sample}»` : ""}`);
}

console.log(`\nсбоев: ${bad}`);
process.exit(bad ? 1 : 0);
