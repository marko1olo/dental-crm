/**
 * Сравнивает старое и новое правило распознавания числительных, чтобы
 * отличить исправление от регрессии.
 *
 * Старое правило — isFuzzyRootMatch: сравнение НАЧАЛА слова длиной корня.
 * Новое — сравнение слова целиком с ограничением длины и совпадением
 * первых двух букв.
 *
 * Печатаем только расхождения: что перестало распознаваться и что
 * перестало ошибочно распознаваться.
 */
import { isFuzzyRootMatch, levenshteinDistance } from "../apps/web/src/lib/stringUtils.ts";

const ROOTS = [
	"ноль", "нуль", "один", "одна", "первый", "первого",
	"два", "две", "второй", "второго", "три", "третий", "третьего",
	"четыре", "четвертый", "четвертого", "пять", "пятый", "пятого",
	"шесть", "шестой", "шестого", "семь", "седьмой", "седьмого",
	"восемь", "восьмой", "восьмого", "девять", "девятый", "девятого",
	"десять", "десятый", "десятого", "одиннадцать", "двенадцать",
	"тринадцать", "четырнадцать", "пятнадцать", "шестнадцать",
	"семнадцать", "восемнадцать", "девятнадцать", "двадцать", "тридцать",
	"сорок", "пятьдесят", "шестьдесят", "семьдесят", "восемьдесят",
	"девяносто", "сто", "двести", "триста", "четыреста", "четреста",
	"пятьсот", "шестьсот", "семьсот", "восемьсот", "девятьсот",
	"тысяча", "тысячи", "тысяч",
];

// Новое правило — копия isFuzzyNumberWord из stringUtils.
function newRule(word, root) {
	const input = word.toLowerCase();
	const target = root.toLowerCase();
	if (input === target) return true;
	if (Math.abs(input.length - target.length) > 2) return false;
	if (input.slice(0, 2) !== target.slice(0, 2)) return false;
	const d = levenshteinDistance(input, target);
	if (target.length <= 3) return d === 0;
	if (target.length <= 5) return d <= 1;
	if (target.length <= 8) return d <= 2;
	return d <= 3;
}

function firstMatch(word, rule) {
	const sorted = [...ROOTS].sort((a, b) => b.length - a.length);
	for (const r of sorted) if (rule(word, r)) return r;
	return null;
}

const WORDS = [
	// числительные и их формы
	"ноль", "один", "одна", "одного", "два", "две", "двух", "три", "трёх", "трех",
	"четыре", "четырёх", "пять", "пяти", "шесть", "шести", "семь", "семи",
	"восемь", "восьми", "девять", "девяти", "десять", "десяти",
	"одиннадцать", "одиннадцати", "двенадцать", "двенадцати", "тринадцати",
	"четырнадцати", "пятнадцати", "шестнадцать", "шестнадцати", "семнадцати",
	"восемнадцати", "девятнадцати", "двадцать", "двадцати", "тридцать",
	"тридцати", "сорок", "сорока", "пятьдесят", "пятидесяти", "шестьдесят",
	"шестидесяти", "семьдесят", "семидесяти", "восемьдесят", "восьмидесяти",
	"девяносто", "девяноста", "сто", "ста", "двести", "двухсот", "триста",
	"тысяча", "тысячи", "тысяч", "тысячей",
	// медицинские слова
	"пульпит", "пульпита", "пульпа", "периодонтит", "периодонтита", "киста",
	"стоматит", "кариес", "гранулема", "коронка", "анестезия", "перкуссия",
	"пломба", "экстракция", "имплантация", "слизистая", "десна", "дентин",
	"седация", "резекция", "рецессия", "штифт", "силер",
];

const lost = [];
const fixed = [];
const same = [];
for (const w of WORDS) {
	const oldR = firstMatch(w, isFuzzyRootMatch);
	const newR = firstMatch(w, newRule);
	if (oldR === newR) same.push(w);
	else if (oldR && !newR) lost.push({ w, oldR });
	else if (!oldR && newR) fixed.push({ w, newR });
	else lost.push({ w, oldR, newR });
}

console.log(`Слов проверено: ${WORDS.length}, поведение не изменилось у ${same.length}\n`);
console.log(`=== ПЕРЕСТАЛО СОПОСТАВЛЯТЬСЯ (${lost.length}) — проверить, не регрессия ли ===`);
for (const l of lost) console.log(`  «${l.w}»  было -> «${l.oldR}»${l.newR ? `, стало -> «${l.newR}»` : ", стало -> ничего"}`);
console.log(`\n=== СТАЛО СОПОСТАВЛЯТЬСЯ (${fixed.length}) ===`);
for (const f of fixed) console.log(`  «${f.w}»  стало -> «${f.newR}»`);
