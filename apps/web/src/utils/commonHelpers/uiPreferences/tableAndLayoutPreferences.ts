export function saveTableColumnPreferences(
	tableKey: string,
	columns: TableColumnPreference[],
	orgId?: string | null,
): void {
	if (typeof window === "undefined") return;
	const key = organizationScopedLocalStorageKey(
		`dente_table_cols_${tableKey}`,
		orgId,
	);
	safeSetStorageItem(window.localStorage, key, JSON.stringify(columns));
}

export function loadTableColumnPreferences(
	tableKey: string,
	orgId?: string | null,
): TableColumnPreference[] | null {
	if (typeof window === "undefined") return null;
	const key = organizationScopedLocalStorageKey(
		`dente_table_cols_${tableKey}`,
		orgId,
	);
	const raw = safeGetStorageItem(window.localStorage, key);
	if (!raw) return null;
	try {
		const parsed = JSON.parse(raw);
		return Array.isArray(parsed) ? (parsed as TableColumnPreference[]) : null;
	} catch {
		return null;
	}
}

