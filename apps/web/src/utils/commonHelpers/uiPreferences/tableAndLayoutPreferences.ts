export function loadSidebarCollapsedPreference(orgId?: string | null): boolean {
	if (typeof window === "undefined") return false;
	const key = organizationScopedLocalStorageKey(
		"dente_sidebar_collapsed",
		orgId,
	);
	const raw = safeGetStorageItem(window.localStorage, key);
	if (!raw) return false;
	try {
		const parsed = JSON.parse(raw) as Partial<SidebarLayoutPreference>;
		return parsed.collapsed === true;
	} catch {
		return false;
	}
}

