import type {
	OdontogramFindingInput,
	ClinicalProtocolSoap,
	FastClinicalPreset,
} from "./protocolTypes.js";
import { getToothAnatomicalNameRu } from "./fdiAnatomy.js";

/** Генерация хирургического протокола SOAP из находки одонтограммы */
export function generateSurgerySoap(
	finding: OdontogramFindingInput,
): ClinicalProtocolSoap | null {
	const stateNorm = (finding.state || "").toLowerCase();
	const tooth = finding.toothNumber;
	const toothTitle = getToothAnatomicalNameRu(tooth);

	// 1. УДАЛЕНИЕ ЗУБА / КОРЕНЬ / РЕТЕНЦИЯ / ОТСУТСТВИЕ
	if (
		stateNorm === "extraction" ||
		stateNorm === "to_extract" ||
		stateNorm === "missing" ||
		stateNorm === "root" ||
		(stateNorm.startsWith("root_") && stateNorm !== "root_canal_treated") ||
		stateNorm === "retained" ||
		stateNorm === "impacted" ||
		stateNorm.startsWith("k08.1") ||
		stateNorm.startsWith("k08.3") ||
		stateNorm.startsWith("k01.1")
	) {
		const isRetained =
			stateNorm === "retained" ||
			stateNorm === "impacted" ||
			stateNorm.startsWith("k01.1");
		const isRoot =
			stateNorm === "root" ||
			stateNorm.startsWith("k08.3") ||
			(stateNorm.startsWith("root_") && stateNorm !== "root_canal_treated");
		const isPlannedExtraction =
			stateNorm === "extraction" || stateNorm === "to_extract";
		const icd =
			finding.icd10Override ||
			(isRetained
				? "K01.1"
				: isRoot
					? "K08.3"
					: "K08.1");
		const icdLabel = isRetained
			? "Ретинированные зубы (показание к удалению)"
			: isRoot
				? "Оставшийся корень зуба (подлежит удалению / реставрации)"
				: isPlannedExtraction
					? "Разрушение зуба, подлежащего удалению"
					: "Потеря зубов вследствие удаления или несчастного случая";

		const anamnesis = isRetained
			? `Жалобы на задержку прорезывания зуба ${toothTitle}, чувство давления на соседние зубы или бессимптомная ретенция по данным КЛКТ.`
			: isRoot
				? `Жалобы на полное разрушение коронковой части зуба ${toothTitle} до уровня десны, невозможность пережевывания пищи, травмирование слизистой оболочки рта острыми краями корня.`
				: isPlannedExtraction
					? `Жалобы на разрушение коронковой части зуба, невозможность терапевтического и ортопедического восстановления, периодические ноющие боли или подвижность.`
					: `Жалобы на отсутствие зуба, нарушение жевательной эффективности и эстетики зубного ряда. Удаление зуба в анамнезе.`;

		const statusLocalis = isRetained
			? `Зуб ${toothTitle}: В зубном ряду отсутствует. При пальпации альвеолярного гребня определяется плотный костный выступ. По данным КЛКТ: зуб ретинирован в толще челюстной кости, коронка наклонена, корни сформированы.`
			: isRoot
				? `Зуб ${toothTitle}: Коронковая часть полностью разрушена, остался корень зуба на уровне или ниже края десны. Твердые ткани пигментированы, размягчены. Зондирование безболезненно. Перкуссия слабочувствительна. На рентгенограмме: корень в альвеоле, периапикальная щель расширена.`
				: isPlannedExtraction
					? `Зуб ${toothTitle}: Полное разрушение коронковой части зуба ниже уровня десны / подвижность зуба III степени / дистопированный полуретинированный зуб. Слизистая оболочка вокруг зуба гиперемирована, отёчна. По данным визиографии: разрушение бифуркации корней, очаг деструкции костной ткани.`
					: `Зуб ${toothTitle}: Отсутствует. Слизистая оболочка альвеолярного отростка в области дефекта бледно-розовая, плотная, без признаков воспаления. Высота и толщина костного гребня достаточна для дентальной имплантации.`;

		const treatmentDescription = isRetained
			? `Инфильтрационная и проводниковая анестезия (артикаин 4% с эпинефрином 1:100 000, 1.7 мл). Разрез по гребню, отслоение слизисто-надкостничного лоскута. Формирование костного доступа бормашиной с охлаждением. Фрагментация ретинированного зуба ${tooth} бором, поэтапная элевация коронки и корней. Тщательный кюретаж лунки, сглаживание острых краев кости, антисептическая обработка (0.05% хлоргексидин). Мобилизация лоскута, наложение швов наглухо. Гемостаз.`
			: isRoot
				? `Инфильтрационная и проводниковая местная анестезия (артикаин 4% 1.7 мл). Синдесмотомия распатором на глубину 3-5 мм. Наложение корневых щипцов / элеватора, люксация, элевация, аккуратное извлечение корня зуба ${tooth} из альвеолы. Ревизия и кюретаж лунки, гемостаз, сближение краев, наложение швов. Давящий тампон на 20 минут.`
				: isPlannedExtraction
					? `Инфильтрационная и проводниковая местная анестезия амидного ряда (артикаин 4% с эпинефрином 1:100 000 1.7 мл) (infiltration anesthesia). Синдесмотомия — отслоение круговой связки зуба на глубину 3-5 мм распатором. Наложение анатомических щипцов / прямого или углового элеватора, люксация, элевация, аккуратная тракция зуба из альвеолы без повреждения костных стенок (elevator/forceps). Тщательный ревизионный кюретаж лунки острой кюретажной ложкой, удаление грануляций и костных отломков (socket curettage). Гемостаз: формирование устойчивого кровяного сгустка, гемостатическая коллагеновая губка с антисептиком (hemostasis). Сближение краев лунки, наложение узловых швов (биодеградируемый шовный материал). Давящий марлевый тампон на 20 минут.`
					: `Зуб ${tooth}: Рекомендована консультация ортопеда и имплантолога. Составлен комплексный план лечения: установка дентального имплантата с последующим протезированием.`;

		const recommendations = isRetained
			? "1. Холод на область щеки 15 мин каждые полчаса первые 3 часа.\n2. Не полоскать рот.\n3. Исключить горячую пищу, бани и физнагрузки на 5 дней.\n4. НПВС при боли (нимесулид 100 мг).\n5. Антибиотикотерапия по схеме.\n6. Снятие швов через 7-10 дней."
			: isRoot || isPlannedExtraction
				? "1. Холод на область щеки по 15 мин первые 3-4 часа.\n2. Не полоскать рот активно (сохранять сгусток).\n3. Исключить бани, сауны и спорт на 3 дня.\n4. Щадящая диета.\n5. НПВС при боли (нимесулид 100 мг).\n6. Контрольный осмотр через 7-10 дней."
				: "Плановый контрольный визит для дентальной имплантации и ортопедического восстановления.";

		return {
			toothNumber: tooth,
			toothNameRu: toothTitle,
			diagnosisIcd10: icd,
			diagnosisIcd10Label: icdLabel,
			diagnosisTooth: String(tooth),
			anamnesis,
			statusLocalis,
			treatmentDescription,
			recommendations,
		};
	}

	// 2. ИМПЛАНТАТ (Implant / Planned_Implant)
	if (stateNorm === "implant" || stateNorm.startsWith("plan")) {
		const isPlanned = stateNorm.startsWith("plan");
		const icd = finding.icd10Override || (isPlanned ? "K08.1" : "Z51.8");
		const icdLabel = isPlanned
			? "Планирование дентальной имплантации"
			: "Состояние после дентальной имплантации";

		return {
			toothNumber: tooth,
			toothNameRu: toothTitle,
			diagnosisIcd10: icd,
			diagnosisIcd10Label: icdLabel,
			diagnosisTooth: String(tooth),
			anamnesis: isPlanned
				? `Пациент обратился для планирования дентальной имплантации в области отсутствующего зуба ${toothTitle}.`
				: `Плановый осмотр после установки дентального имплантата в позиции зуба ${toothTitle}. Жалоб нет.`,
			statusLocalis: isPlanned
				? `Зуб ${toothTitle}: Альвеолярный гребень без признаков патологических процессов, толщина и плотность кости достаточна по данным 3D КЛКТ.`
				: `Зуб ${toothTitle}: Установлен дентальный имплантат. Формирователь десны стабилен, окружающая слизистая бледно-розовая, признаков периимплантита нет.`,
			treatmentDescription: isPlanned
				? `Зуб ${tooth}: 3D-планирование имплантации, выбор размера имплантата и хирургического протокола установки.`
				: `Зуб ${tooth}: Контрольный осмотр, антисептическая обработка области имплантата, контроль остеоинтеграции по визиографии.`,
			recommendations:
				"Плановый контрольный осмотр и профгигиена по графику профилактического наблюдения.",
		};
	}

	// 3. СИНУС-ЛИФТИНГ / КОСТНАЯ ПЛАСТИКА (Sinus_Lift / Bone_Graft)
	if (
		stateNorm === "sinus_lift" ||
		stateNorm === "bone_graft" ||
		stateNorm.includes("sinus") ||
		stateNorm.includes("graft")
	) {
		const icd = finding.icd10Override || "K08.8";
		return {
			toothNumber: tooth,
			toothNameRu: toothTitle,
			diagnosisIcd10: icd,
			diagnosisIcd10Label: "Атрофия альвеолярного отростка верхней/нижней челюсти",
			diagnosisTooth: String(tooth),
			anamnesis: `Обращение пациента для подготовки к дентальной имплантации в области зуба ${toothTitle}. Дефицит костной ткани по высоте/ширине.`,
			statusLocalis: `Зуб ${toothTitle}: Высота альвеолярного гребня по КЛКТ менее 5 мм до дна верхнечелюстного синуса. Слизистая пазухи без признаков утолщения, проходимость соустья сохранена.`,
			treatmentDescription: `Местная анестезия амидного ряда. Разрез по гребню, отслоение слизисто-надкостничного лоскута. Формирование костного окна, препарирование и бережное отслаивание мембраны Шнайдера кюретами для синус-лифтинга без перфорации (проба Вальсальвы отрицательная). Внесение костнопластического материала (ксенографт + аутостружка) в субантральное пространство. Перекрытие окна резорбируемой коллагеновой мембраной. Ушивание раны наглухо узловыми швами ПТФЭ/полипропилен.`,
			recommendations:
				"Исключить сморкание, чихание с закрытым ртом, авиаперелеты и ныряние на 3 недели. Сосудосуживающие капли в нос 5 дней. Антибиотикотерапия (Амоксиклав 1000 мг 2 р/д 7 дней), НПВП при боли. Контрольный осмотр и снятие швов через 12–14 дней.",
		};
	}

	return null;
}

