import type {
	OdontogramFindingInput,
	ClinicalProtocolSoap,
	FastClinicalPreset,
} from "./protocolTypes.js";
import { getToothAnatomicalNameRu } from "./fdiAnatomy.js";

/** Генерация ортопедического протокола SOAP из находки одонтограммы */
export function generateProsthoSoap(
	finding: OdontogramFindingInput,
): ClinicalProtocolSoap | null {
	const stateNorm = (finding.state || "").toLowerCase();
	const tooth = finding.toothNumber;
	const toothTitle = getToothAnatomicalNameRu(tooth);

	// 1. КОРОНКА / ОРТОПЕДИЯ (Crown / Z51.8)
	if (
		stateNorm === "crown" ||
		stateNorm.startsWith("crown_") ||
		stateNorm.startsWith("prostho") ||
		stateNorm === "veneer" ||
		stateNorm === "inlay" ||
		stateNorm === "onlay"
	) {
		const isVeneer = stateNorm === "veneer";
		const isInlay = stateNorm === "inlay" || stateNorm === "onlay";
		const icd = finding.icd10Override || "Z51.8";
		const icdLabel = isVeneer
			? "Ортопедическое лечение (керамический винир)"
			: isInlay
				? "Ортопедическое лечение (керамическая вкладка / накладка)"
				: "Ортопедическое лечение (коронка)";

		const anamnesis = isVeneer
			? `Обращение пациента с целью эстетической коррекции зуба ${toothTitle} (дисколорит, дефект формы эмали).`
			: isInlay
				? `Обращение пациента на этап восстановления зуба ${toothTitle} керамической вкладкой/накладкой. ИРОПЗ 0.5–0.7.`
				: `Плановое обращение на этап ортопедического лечения зуба ${toothTitle}. Жалобы на разрушение твердых тканей зуба более 50% (ИРОПЗ > 0.6).`;

		const statusLocalis = isVeneer
			? `Зуб ${toothTitle}: Интактен / поверхностные пломбы, изменение цвета эмали. Зубодесневой контур гармоничный.`
			: isInlay
				? `Зуб ${toothTitle}: Дефект твердых тканей окклюзионной и апроксимальной поверхностей, корневые каналы запломбированы или витален.`
				: `Зуб ${toothTitle}: Коронковая часть зуба значительно разрушена, зуб девитализирован, корневые каналы качественно обтурированы по данным рентгенографии. Десна без признаков воспаления.`;

		const treatmentDescription = isVeneer
			? `Местная анестезия (артикаин 4% 1.7 мл). Микроинвазивное препарирование вестибулярной поверхности зуба ${tooth} в пределах эмали (0.3–0.5 мм) под контролем силиконового ключа. Ретракция десны нитью 000. Прецизионный оптический/силиконовый оттиск. Фиксация временного винира Protemp.`
			: isInlay
				? `Местная анестезия. Препарирование полости зуба ${tooth} под керамическую накладку (дивергенция стенок 6–8 градусов, сглаживание внутренних углов). Ретракция десны. Получение рабочего оттиска А-силиконом. Временная пломба светового отверждения Clip/Fermit.`
				: `Зуб ${tooth}: Местная анестезия амидного ряда (артикаин 4% 1.7 мл). Препарирование культи зуба под искусственную коронку с созданием циркулярного уступа Chamfer. Ретракция десны ретракционной нитью. Получение прецизионного двухслойного силиконового оттиска (А-силиконовый оттискной материал) и оттиска антагонистов. Изготовление и фиксация провизорной пластмассовой коронки на безэвгенольный временный цемент.`;

		return {
			toothNumber: tooth,
			toothNameRu: toothTitle,
			diagnosisIcd10: icd,
			diagnosisIcd10Label: icdLabel,
			diagnosisTooth: String(tooth),
			anamnesis,
			statusLocalis,
			treatmentDescription,
			recommendations:
				"Щадящая диета, аккуратная гигиена в области временной конструкции. При расцементировке обратиться в клинику.",
		};
	}

	return null;
}

