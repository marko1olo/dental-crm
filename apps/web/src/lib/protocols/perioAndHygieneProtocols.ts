/** Генерация пародонтологического протокола SOAP из находки одонтограммы */
export function generatePerioSoap(
	finding: OdontogramFindingInput,
): ClinicalProtocolSoap | null {
	const stateNorm = (finding.state || "").toLowerCase();
	const tooth = finding.toothNumber;
	const toothTitle = getToothAnatomicalNameRu(tooth);

	// ГИНГИВИТ / ПАРОДОНТИТ / ПРОФГИГИЕНА (K05 / K05.0 / K05.1 / K05.3 / Z01.2)
	if (
		stateNorm === "gingivitis" ||
		stateNorm.startsWith("k05") ||
		stateNorm.includes("perio") ||
		stateNorm === "hygiene"
	) {
		const isPeriodontitis =
			stateNorm.includes("periodontitis") ||
			stateNorm.startsWith("k05.3") ||
			(finding.pocketDepthMm !== undefined && finding.pocketDepthMm > 3);
		const hasExplicitPocketDepth =
			finding.pocketDepthMm !== undefined && finding.pocketDepthMm > 0;
		const icd =
			finding.icd10Override ||
			(isPeriodontitis
				? "K05.3"
				: stateNorm === "gingivitis" || stateNorm.startsWith("k05.1")
					? "K05.1"
					: "K05.0");
		const icdLabel = isPeriodontitis
			? "Хронический пародонтит"
			: "Острый/хронический гингивит, зубные отложения";

		const anamnesis = isPeriodontitis
			? `Жалобы на кровоточивость десен при чистке зубов и приеме пищи в области зуба ${toothTitle}, подвижность зуба, неприятный запах изо рта, оголение шеек зубов, попадание пищи в межзубные промежутки.`
			: `Жалобы на наличие темного налета на зубах, зубной камень, кровоточивость и отечность десен при чистке зубов в области зуба ${toothTitle}, несвежее дыхание.`;

		const statusLocalis = isPeriodontitis
			? `Десна в области зуба ${toothTitle} отёчна, застойная гиперемия, цианотична. Обильные над- и поддесневые зубные отложения. ${hasExplicitPocketDepth ? `Глубина пародонтального кармана составляет ${finding.pocketDepthMm} мм` : "Определяются патологические пародонтальные карманы"} с серозно-гнойным экссудатом при компрессии. Патологическая подвижность I-II степени. На рентгенограмме: деструкция костной ткани межальвеолярных перегородок до 1/3–1/2 длины корня.`
			: `Маргинальный и папиллярный край десны в области зуба ${toothTitle} гиперемирован, отёчен, выраженная кровоточивость при зондировании десневой борозды. Зубодесневое прикрепление сохранено, патологические пародонтальные карманы отсутствуют. Обильный мягкий зубной налет и плотные минерализованные над- и поддесневые зубные отложения.`;

		const treatmentDescription = isPeriodontitis
			? `Аппликационная и инфильтрационная местная анестезия амидного ряда. Ультразвуковой скейлинг (ultrasonic scaling) и над/поддесневая обработка аппаратом Air-Flow (Air-Flow polishing). Закрытый кюретаж пародонтального кармана в области зуба ${tooth} кюретами Грейси. Антисептическая ирригация 0.05% раствором хлоргексидина биглюконата. Инстилляция антимикробного стоматологического геля (метронидазол + хлоргексидин). Обучение индивидуальной гигиене, подбор межзубных ершиков и монопучковых щеток. Контрольный осмотр через 10-14 дней.`
			: `Индикация зубного налета. Аппликационная анестезия десны. Ультразвуковой скейлинг с удалением массивных минерализованных над- и поддесневых зубных отложений (ultrasonic scaling). Снятие пигментированного налета водно-порошкоструйным аппаратом Air-Flow (порошок глицин/эритритол) (Air-Flow polishing). Полировка всех поверхностей зубов полировочной пастой и щеточками. Межзубные промежутки очищены флоссом и штрипсами. Глубокое фторирование эмали фторсодержащим лаком. Обучение гигиене, индивидуальный подбор средств ухода.`;

		return {
			toothNumber: tooth,
			toothNameRu: toothTitle,
			diagnosisIcd10: icd,
			diagnosisIcd10Label: icdLabel,
			diagnosisTooth: String(tooth),
			anamnesis,
			statusLocalis,
			treatmentDescription,
			recommendations:
				"«Белая диета» 48 часов (без кофе, чая, ягод, свеклы). Замена зубной щетки на новую. Профилактический осмотр через 6 месяцев.",
		};
	}

	return null;
}

