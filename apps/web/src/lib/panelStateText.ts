/**
 * Что видит человек, когда панель грузится, когда данных действительно нет и
 * когда прочитать их не удалось. Три РАЗНЫХ состояния и три разных текста.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Здесь нет ни React, ни fetch, ни CSS, поэтому
 * «что покажем при отказе сервера» проверяется обычным node:test, а не глазами
 * по скриншоту. Тот же приём, что в pages/analyticsDoctorMetrics.ts: экран
 * аналитики однажды напечатал пользователю английское исключение браузера
 * целиком именно потому, что решение о тексте жило внутри разметки.
 *
 * ЧТО БЫЛО СЛОМАНО И ПОЧЕМУ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ
 *
 * 1. Голый код состояния в тексте для человека. hooks/usePatientResource.ts
 *    отдавал «Сервер ответил ошибкой 500. Данные не загружены.» — и три виджета
 *    карточки пациента печатали эту строку дословно. Администратору код 500 не
 *    говорит ни что случилось, ни что делать. Номер нужен разработчику: он
 *    уходит в logger.error, а не на экран.
 *
 * 2. Отказ, выданный за пустоту. Виджеты, не забиравшие `error` из хука,
 *    показывали «Рекламации и осложнения отсутствуют» и «Нет активных задач»
 *    на карточке, где чтение упало с 401 или 500. Для журнала осложнений это
 *    не косметика: врач видит «осложнений нет» у пациента, у которого они есть.
 *
 * ПРАВИЛО ТЕКСТА. Каждое сообщение отвечает на три вопроса: что случилось,
 * почему и что делать дальше. Причина называется по существу («у смены нет
 * доступа»), а не по механизму («HTTP 403»). Придумывать причину, которой
 * сервер не сообщал, запрещено: на непонятный ответ так и говорим — непонятный.
 */

/** Состояние панели. «Пусто» и «не удалось» — разные вещи и никогда не сливаются. */
export type PanelPhase = "loading" | "empty" | "failed";

/** То же плюс «данные есть и показаны». */
export type PanelPhaseOrReady = PanelPhase | "ready";

/**
 * Какое из состояний показывать. Правило вынесено из разметки, потому что
 * ошибались именно в нём: условие было одно — `length === 0 && !isLoading` — и
 * накрывало и честную пустоту, и непрочитанный список.
 *
 * Порядок обязателен и проверяется тестом:
 *   отказ важнее пустоты (иначе непрочитанное выдаётся за отсутствующее);
 *   загрузка важнее пустоты (иначе на долю секунды утверждается «данных нет»);
 *   при уже показанных данных обновление не гасит их в «загружаем».
 */
export function resolvePanelPhase(input: {
	readonly isLoading: boolean;
	readonly hasFailure: boolean;
	readonly isEmpty: boolean;
}): PanelPhaseOrReady {
	if (input.hasFailure) return "failed";
	if (input.isLoading && input.isEmpty) return "loading";
	if (input.isEmpty) return "empty";
	return "ready";
}

export type PanelState =
	| { readonly phase: "loading" }
	| { readonly phase: "empty" }
	/** `status` — код ответа сервера; `null` означает, что до сервера не дошли вовсе. */
	| { readonly phase: "failed"; readonly status: number | null };

/**
 * Как называется содержимое конкретной панели. Собирается рядом с самой
 * панелью: «задачи по пациенту» знает виджет задач, а не этот модуль.
 */
export interface PanelSubject {
	/**
	 * Первая часть предложения об отказе, целиком и с согласованием:
	 * «Задачи по пациенту не загружены», «Статус блокировки не прочитан».
	 *
	 * ЗАЧЕМ ЦЕЛОЙ СТРОКОЙ. Здесь стояло `title` («Задачи по пациенту»), а модуль
	 * дописывал «не загружены» сам. Для трёх сегодняшних панелей форма совпала
	 * случайно: все три названия — множественного числа. Любое название в
	 * единственном («Статус») дало бы «Статус не загружены». Согласование живёт
	 * рядом с существительным, поэтому ошибиться в нём больше негде.
	 */
	readonly notLoadedTitle: string;
	/** Винительный падеж, строчными: «задачи по пациенту» — встанет после «Загружаем …». */
	readonly accusative: string;
	/** Заголовок честной пустоты: «Задач по пациенту пока нет». */
	readonly emptyTitle: string;
	/** Что делать дальше, когда пусто. Пустота без подсказки — тупик. */
	readonly emptyHint: string;
	/**
	 * Чем отказ опасен именно здесь. Показывается после причины отказа.
	 * Например: «Не считайте, что осложнений нет: список не прочитан.»
	 */
	readonly failureConsequence: string;
}

export interface PanelText {
	readonly phase: PanelPhase;
	readonly title: string;
	readonly hint: string;
	/**
	 * Подпись кнопки повтора, либо `null` — если повторять тот же запрос
	 * бессмысленно.
	 *
	 * БЫЛО: `retryable: boolean`, всегда `true` при отказе, и его никто не читал —
	 * `PanelLoadFailure` рисовал «Повторить» по одному факту наличия `onRetry`.
	 * Кнопка предлагала повтор рядом с текстом «сервер не знает такого раздела —
	 * сообщите администратору», где повтор не поможет никогда. Теперь решение
	 * одно, читается разметкой и проверяется тестом.
	 */
	readonly retryLabel: string | null;
}

/** До сервера не дошли: сеть, выключенный сервер клиники, обрыв. */
export const NO_RESPONSE_CAUSE =
	"сервер клиники не ответил — проверьте, что программа клиники запущена и есть сеть, и повторите";

/**
 * Причина отказа человеческими словами. Всегда строчными и всегда с действием:
 * строка склеивается в предложение вида «<Что> не загружены: <причина>.».
 *
 * Кода состояния в результате нет ни в одной ветке — включая ветку «иначе».
 * Прежний `сервер вернул код ${status}` был именно такой утечкой.
 */
export function requestFailureCause(status: number | null): string {
	if (status === null || status === 0) return NO_RESPONSE_CAUSE;
	if (status === 401 || status === 403) {
		return "у вашей смены нет доступа к этим данным — войдите в смену заново или попросите администратора открыть доступ";
	}
	if (status === 404) {
		return "сервер не знает такого раздела — скорее всего программа клиники обновлена не полностью, сообщите администратору";
	}
	if (status === 409)
		return "данные успел изменить кто-то другой — обновите страницу, чтобы увидеть свежие";
	if (status === 413)
		return "запрос оказался слишком большим для сервера — уменьшите объём и повторите";
	if (status === 429)
		return "запросов подряд было слишком много — подождите полминуты и повторите";
	// БЫЛО: «сервер не принял запрос — обновите страницу и повторите». Обновление
	// страницы соберёт ровно тот же запрос и получит ровно тот же отказ: 400 и 422
	// означают, что запрос не подходит серверу, а не что серверу сейчас плохо.
	// Обещание, которое не может сработать, — тот же дефект, что голый код ответа.
	if (status === 400 || status === 422) {
		return "сервер не принял такой запрос — повторение не поможет, сообщите администратору";
	}
	if (status >= 500) {
		return "сервер не смог выполнить запрос — повторите через минуту, а если повторится, сообщите администратору";
	}
	return "ответ сервера непонятен — повторите, а если повторится, сообщите администратору";
}

/**
 * Подпись кнопки повтора — или `null`, если повторять нечего.
 *
 * Правило одно: кнопка живёт только там, где ТОТ ЖЕ запрос может однажды
 * ответить иначе. Отсутствующий раздел (404) и не подходящий серверу запрос
 * (400/422/413) так не отвечают никогда, поэтому кнопки там нет вовсе. После
 * отказа по доступу (401/403) повтор осмыслен, но лишь после входа — об этом и
 * говорит подпись, иначе кнопка выглядит альтернативой входу.
 */
export function panelRetryLabel(status: number | null): string | null {
	if (status === null || status === 0) return "Повторить";
	if (status === 401 || status === 403) return "Я вошёл — прочитать снова";
	if (status === 404) return null;
	if (status === 400 || status === 422 || status === 413) return null;
	if (status === 409) return "Обновить";
	return "Повторить";
}

/**
 * Причина отказа для панели, которая печатает её после своего заголовка:
 * «Статус не загружен: <это>.» Отдельная функция не нужна — но отдельное имя
 * нужно, чтобы на вызове было видно, что строка идёт человеку, а не в лог.
 */
export function panelFailureCause(status: number | null): string {
	return requestFailureCause(status);
}

/**
 * Текст панели для её текущего состояния.
 *
 * Три состояния дают три разных заголовка, и ни один из них не содержит ни
 * английского текста исключения, ни кода ответа.
 */
export function panelStateText(
	subject: PanelSubject,
	state: PanelState,
): PanelText {
	if (state.phase === "loading") {
		return {
			phase: "loading",
			title: `Загружаем ${subject.accusative}…`,
			hint: "Это займёт пару секунд.",
			retryLabel: null,
		};
	}
	if (state.phase === "empty") {
		return {
			phase: "empty",
			title: subject.emptyTitle,
			hint: subject.emptyHint,
			retryLabel: null,
		};
	}
	return {
		phase: "failed",
		title: `${subject.notLoadedTitle}: ${requestFailureCause(state.status)}.`,
		hint: subject.failureConsequence,
		retryLabel: panelRetryLabel(state.status),
	};
}

/**
 * Сообщение о неудавшемся ДЕЙСТВИИ (сохранение, удаление, смена статуса) —
 * для всплывающего уведомления.
 *
 * `action` — что не получилось, в прошедшем времени и по существу:
 * «Задача не создана», «Рекламация не удалена». Прежние «Ошибка сети» и
 * «Ошибка при удалении» не говорили ни что не сохранилось, ни что делать.
 */
export function actionFailureToast(
	action: string,
	status: number | null,
): string {
	return `${action}: ${requestFailureCause(status)}.`;
}

/**
 * То же для случая, когда сервер ответил успешно, но не подтвердил результат.
 * Отдельная формулировка: тут «повторить» опаснее, чем «проверить».
 */
export function unconfirmedActionToast(action: string): string {
	return `${action}: сервер принял запрос, но не подтвердил результат — обновите страницу и проверьте, как всё сохранилось.`;
}

