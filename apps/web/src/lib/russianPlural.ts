/**
 * Согласование числа с существительным по-русски: «1 сообщение», «2 сообщения»,
 * «5 сообщений».
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ЛИСТОВОЙ МОДУЛЬ, А НЕ МЕСТО В AppHelpers. Функция чистая и не
 * зависит ни от чего, но жила в AppHelpers.tsx — файле на 6066 строк, который по
 * цепочке импортов тянет компоненты и таблицы стилей. Любой модуль ЛОГИКИ,
 * попросивший у него это согласование, становился незапускаемым в node:test:
 * прогон падал на `ERR_UNKNOWN_FILE_EXTENSION` для
 * `components/workspaceActions/workspaceActions.css`, даже не дойдя до первого
 * утверждения.
 *
 * Именно так и случилось: модуль отчёта о рассылке вынесли из компонента, чтобы
 * его можно было проверять без React, — и одна строка `import { countLabel } from
 * "../../AppHelpers.js"` весь этот вынос обнулила. Тест не падал по существу, он
 * не загружался вовсе.
 *
 * Копию заводить нельзя: правило согласования одно, а второй владелец такого
 * правила — это два разных ответа на один вопрос через полгода. Поэтому функция
 * переехала сюда, а AppHelpers её РЕЭКСПОРТИРУЕТ: восемь существующих
 * потребителей не тронуты ни одной строкой.
 *
 * Здесь не должно появиться ни одного импорта, кроме типов. Как только появится,
 * модуль перестанет быть листовым и снова утащит с собой стили.
 */
export function countLabel(
	count: number,
	one: string,
	few: string,
	many: string,
): string {
	const lastTwo = count % 100;
	const last = count % 10;
	// 11–14 всегда множественное: «11 сообщений», а не «11 сообщение».
	if (lastTwo >= 11 && lastTwo <= 14) return `${count} ${many}`;
	if (last === 1) return `${count} ${one}`;
	if (last >= 2 && last <= 4) return `${count} ${few}`;
	return `${count} ${many}`;
}
