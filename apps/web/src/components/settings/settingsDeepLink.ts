/**
 * Переход между вкладками настроек по адресу — одной типизированной функцией.
 *
 * ЗАЧЕМ. У раздела «Настройки» уже была системная болезнь: «списки, которые
 * обязаны совпадать и не совпадают». Панели были смонтированы под
 * идентификаторы, которых нет в `settingsTabs`, и попасть в них было нельзя
 * ниоткуда; кнопка настроек Telegram существовала, а нажать её было негде.
 * Разбор — в AppHelpers.tsx над объявлением `settingsTabs`.
 *
 * Обратная сторона той же болезни — ссылка в идентификатор, которого в списке
 * нет. Она НЕ сообщает об ошибке: `settingsTabFromHash` пропускает только
 * перечисленное в `settingsTabs`, а всё остальное тихо превращает в «clinic».
 * Человек нажимает «Перейти к настройке отзывов», попадает на «Клинику» и
 * решает, что промахнулся мимо кнопки.
 *
 * Поэтому цель перехода здесь — не строка, а `SettingsTab`. Опечатка в
 * идентификаторе становится ошибкой сборки, а не молчаливым переходом не туда.
 * Разметке остаётся только назвать вкладку.
 *
 * ПОЧЕМУ АДРЕС, А НЕ ОБРАБОТЧИК ИЗ ПРОПСОВ. Так переключает вкладки само меню
 * настроек (`SettingsView.selectSettingsTab`), а на `hashchange` подписан
 * `useAppLogic` и вызывает `setSettingsTab(settingsTabFromHash())`. Одного
 * адреса достаточно, и второй источник состояния вкладки не появляется — а
 * именно два источника одного решения в этом разделе и расходились.
 */

import { settingsTabs, type SettingsTab } from "../../AppHelpers";

/** Часть адреса после `#`: `settings/telegram`. */
export function settingsTabHash(tab: SettingsTab): string {
	return `settings/${tab}`;
}

/**
 * Подпись вкладки — из того же списка, из которого рисуется левое меню.
 *
 * Нужна, чтобы кнопка «Перейти в «Мессенджеры»» и сама кнопка меню назывались
 * одинаково. Переименуют вкладку — подписи не разойдутся, а расхождение подписи
 * и цели перехода человек читает как ошибку в своей голове, а не в программе.
 */
export function settingsTabTitle(tab: SettingsTab): string {
	return settingsTabs.find((item) => item.id === tab)?.title ?? "Настройки";
}

/** Открыть вкладку настроек. В окружении без браузера ничего не делает. */
export function openSettingsTab(tab: SettingsTab): void {
	if (typeof window === "undefined") return;
	window.location.hash = settingsTabHash(tab);
}

/**
 * Вкладка, где по-настоящему сохраняются настройки бота: ссылка на отзыв,
 * задержка просьбы оценить клинику, напоминания.
 *
 * Идентификатор остался историческим («telegram»), а подпись у вкладки давно
 * «Мессенджеры» — за ней живут ещё WhatsApp и MAX. Поэтому в разметке нельзя
 * писать ни то, ни другое руками: подпись берётся из списка вкладок, а
 * идентификатор — отсюда.
 */
export const MESSENGERS_SETTINGS_TAB: SettingsTab = "telegram";
