/**
 * ЧЕЙ РАЗБОР ПОКАЗАН В ПАНЕЛИ «АССИСТЕНТ ОБРАБОТКИ ПРИЕМА».
 *
 * БЫЛО: результат разбора приёма (`visitFlowResult`) живёт в общем хранилище
 * визита (store/visitStore.ts) и записывается РОВНО В ОДНОМ месте — после
 * удачного ответа /api/ai/visit-flow в buildDraft. Обнулять его не умеет никто:
 * ни смена пациента, ни смена приёма, ни сохранение записи приёма
 * (acceptDraftToVisit делает setDraft(null), а visitFlowResult не трогает), ни
 * очистка диктовки. Проверено поиском по всему дереву: setVisitFlowResult
 * вызывается один раз и никогда с null.
 *
 * Что видел врач: разобрал приём пациента А — под шапкой ЭМК появилась панель
 * «Ассистент обработки приема» с диагнозом ДЛЯ ПАЦИЕНТА («Диагноз (пациенту):
 * …»), рекомендациями после процедуры, временными ограничениями и списком
 * предложенных документов. Затем начал приём пациента Б — панель осталась на
 * месте, с теми же строками. Разбор чужого приёма выглядел как разбор текущего:
 * рекомендации после удаления зуба одного человека читались у кресла другому, а
 * предложенные документы уводили в чужую подготовку.
 *
 * ПОЧЕМУ ПРИВЯЗКА ЖИВЁТ В МОДУЛЕ, А НЕ В СОСТОЯНИИ КОМПОНЕНТА. Сам ответ
 * сервера не несёт ни пациента, ни приёма (visitFlowResultSchema в
 * packages/shared — четыре шага и общий статус, и всё), поэтому владельца
 * приходится запоминать на клиенте в момент появления результата. Держать его в
 * useRef нельзя: вкладка «ЭМК и Диктовка» размонтируется при уходе на «Зубную
 * формулу», и ref вместе с ней — вернувшись, панель снова считала бы чужой
 * разбор своим. Область видимости модуля живёт столько же, сколько само
 * хранилище визита, поэтому привязка переживает переключение вкладок и гаснет
 * только вместе с перезагрузкой страницы, когда обнуляется и хранилище.
 */

/** Результат, для которого владелец уже записан (сравнение по ссылке). */
let ownedResult: object | null = null;
/** Пациент и приём, которым принадлежит `ownedResult`. */
let ownerKey: string | null = null;

/**
 * Ключ владельца разбора: пациент плюс приём. Приём входит в ключ потому, что
 * второй приём того же человека — это другой разбор, и рекомендации первого
 * приёма во втором показывать нельзя.
 */
export function visitFlowOwnerKey(
	patientId: unknown,
	visitId: unknown,
): string {
	const patient = typeof patientId === "string" && patientId.trim() ? patientId.trim() : "нет-пациента";
	const visit = typeof visitId === "string" && visitId.trim() ? visitId.trim() : "нет-приёма";
	return `${patient}|${visit}`;
}

/**
 * Запомнить, кому принадлежит показанный разбор. Повторный вызов с тем же
 * объектом владельца НЕ меняет: иначе разбор пациента А переписался бы на
 * пациента Б ровно тем действием, которое обязано его скрыть.
 */
export function rememberVisitFlowResultOwner(result: unknown, owner: string): void {
	if (!result || typeof result !== "object") {
		forgetVisitFlowResultOwner();
		return;
	}
	if (ownedResult !== result) {
		ownedResult = result as object;
		ownerKey = owner;
	}
}

/**
 * Разбор принадлежит другому пациенту или другому приёму — показывать его
 * нельзя. Неизвестный (ещё не привязанный) разбор чужим не считается: его
 * только что получил текущий приём, привязка появится тем же рендером.
 */
export function visitFlowResultIsForeign(result: unknown, owner: string): boolean {
	if (!result || typeof result !== "object") return false;
	if (ownedResult !== result) return false;
	return ownerKey !== owner;
}

/** Забыть привязку — после того, как чужой разбор убран из хранилища. */
export function forgetVisitFlowResultOwner(): void {
	ownedResult = null;
	ownerKey = null;
}
