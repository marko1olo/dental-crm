/**
 * Сбрасывать ли черновик карточки пациента и состояние сохранения.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ МОДУЛЕМ. Решение живёт в двух эффектах `usePatientLogic`, и
 * оба стоят на зависимостях `[selectedPatient?.id, selectedPatient?.updatedAt]`.
 * Внутри React его не проверить прогоном без браузера, а именно на нём сломалось
 * подтверждение записи. Чистая функция проверяется `node:test` напрямую — приём в
 * проекте уже принят (`components/auth/staffUnlockState.ts`,
 * `components/patients/patientCardSavePill.tsx`).
 *
 * ЧТО БЫЛО СЛОМАНО. Зависимость от `updatedAt` нужна: если карточку поправили в
 * другом месте — на другом экране, другим сотрудником, — черновик обязан
 * подхватить свежие данные, иначе регистратор допишет телефон поверх устаревшей
 * записи и затрёт чужую правку.
 *
 * Но `updatedAt` меняет и НАШЕ СОБСТВЕННОЕ сохранение: сервер возвращает
 * обновлённую строку, она кладётся в общее состояние, `selectedPatient`
 * пересчитывается из него, эффект срабатывает на только что состоявшемся
 * сохранении и возвращает состояние в «idle». Выставленное строкой выше
 * «Сохранено» гасло в том же кадре, и подтверждение записи не показывалось
 * НИКОГДА: регистратор жал «Сохранить» и не получал ни одного признака, что
 * карточка записана. Дефект нашла приёмка участка, прочитав цепочку из пяти
 * звеньев целиком.
 *
 * ПОЧЕМУ СРАВНЕНИЕ ПО ОТМЕТКЕ, А НЕ ФЛАГ «Я СЕЙЧАС СОХРАНЯЮ». Флаг пришлось бы
 * снимать по времени или в том же эффекте, и он разъехался бы с настоящим
 * порядком обновлений. Отметка времени, вернувшаяся ОТ СЕРВЕРА, однозначно
 * называет ту самую запись: чужое изменение придёт с другой отметкой и сброс
 * произойдёт, как и раньше.
 */

export type PatientDraftResetInput = {
	/** `updatedAt` пациента, на котором сработал эффект. */
	incomingUpdatedAt: string | null | undefined;
	/** `updatedAt`, вернувшийся от НАШЕГО сохранения на этом экране. */
	savedByThisScreenUpdatedAt: string | null;
};

/**
 * `true` — черновик и состояние сохранения сбрасываются (смена пациента либо
 * чужое изменение). `false` — это отклик нашего собственного сохранения, и
 * гасить подтверждение записи нельзя.
 */
export function shouldResetPatientDraftState({
	incomingUpdatedAt,
	savedByThisScreenUpdatedAt,
}: PatientDraftResetInput): boolean {
	// Отметки нет вовсе — сравнивать не с чем, ведём себя как раньше.
	if (!incomingUpdatedAt) return true;
	// Ничего своего ещё не сохраняли: любое изменение — чужое.
	if (!savedByThisScreenUpdatedAt) return true;
	return incomingUpdatedAt !== savedByThisScreenUpdatedAt;
}
