/** Выданный ключ вместе с подписью операции, для которой он выдан. */
export interface MutationTicket {
	/** Подпись операции: денежные поля тела запроса. */
	requestKey: string;
	/** Сам ключ идемпотентности, уходящий на сервер. */
	mutationId: string;
}

/**
 * Хранилище ключа между попытками.
 *
 * Объявлено своим интерфейсом, а не типом React: `useRef` подходит под него по
 * форме, а модуль остаётся без импортов и запускается в тесте.
 */
export interface MutationTicketRef {
	current: MutationTicket | null;
}

/*
 * Разделитель, которого не может быть внутри значений: идентификаторы —
 * uuid (только шестнадцатеричные цифры и дефисы), сумма — число, способ оплаты —
 * латинское слово из перечисления. Поэтому склейка через «|» не даёт двум разным
 * операциям одну подпись.
 */
const FIELD_SEPARATOR = "|";

/**
 * Подпись списания с семейного счёта: ровно те поля тела запроса, которые
 * двигают деньги. Сумма — числом, потому что «1000» и «1000.0» — одна операция.
 */
export function familyPayRequestKey(
	patientId: string,
	familyGroupId: string,
	amountRub: number,
): string {
	return ["pay", patientId, familyGroupId, amountRub].join(FIELD_SEPARATOR);
}

/**
 * Подпись пополнения. Способ входит наравне с суммой: он попадает в журнал
 * платежей и в вечернюю сверку кассы, поэтому «те же 5 000 ₽, но картой» — другая
 * операция, и зачесть её как повтор нельзя.
 */
export function familyTopupRequestKey(
	patientId: string,
	familyGroupId: string,
	amountRub: number,
	method: string,
): string {
	return ["topup", patientId, familyGroupId, amountRub, method].join(FIELD_SEPARATOR);
}

/**
 * Выдать ключ идемпотентности для операции с такой подписью.
 *
 * Подпись совпала с сохранённой — это повтор той же попытки, ключ возвращается
 * тот же: сервер узнает его и второй раз денег не тронет. Подпись другая — это
 * другая операция, и она получает свой ключ.
 *
 * После успеха вызывающий обнуляет `ref.current`: следующая такая же по составу
 * операция (тот же пациент, та же сумма — пациент платит столько же второй раз)
 * должна пройти как новая, а не быть отвергнутой как повтор.
 */
export function familyMutationId(
	ref: MutationTicketRef,
	prefix: string,
	requestKey: string,
	newMutationId: () => string = () => crypto.randomUUID(),
): string {
	if (ref.current?.requestKey !== requestKey) {
		ref.current = { requestKey, mutationId: `${prefix}-${newMutationId()}` };
	}
	return ref.current.mutationId;
}
