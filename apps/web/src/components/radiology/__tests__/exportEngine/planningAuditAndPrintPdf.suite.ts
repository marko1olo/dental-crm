import assert from "node:assert/strict";
import { it } from "node:test";
import {
	buildCbctReportData,
	export300DpiViewportSnapshot,
	generateSynchronizedReportSnapshots,
	renderCbctReportHtml,
} from "../../cbctExportEngine";
import {
	performCbctPlanningAudit,
	type MandibularCanalCrossSection,
} from "../../implantSafetyEngine";
import { createExportEngineFixtures } from "./exportFixtures";

export function runPlanningAuditAndPrintPdfTests() {
	const {
		mockPose,
		mockHuSampling,
		mockMischResult,
		mockContainment,
		mockNerveSafety,
	} = createExportEngineFixtures();

	it("11. performCbctPlanningAudit outputs exact template with patient and clinic names without typo", () => {
		const mockCanal: MandibularCanalCrossSection = {
			center: { x: 2.0, y: 16.5 },
			radiusMm: 1.5,
			safetyMarginMm: 2.0,
		};
		const mockEnvelope = {
			crestPoint: { x: 0, y: 2.0 },
			basePoint: { x: 0, y: 20.0 },
			buccalCrestPoint: { x: -4.0, y: 2.0 },
			lingualCrestPoint: { x: 4.5, y: 2.0 },
			ridgeWidthMm: 8.5,
			ridgeHeightMm: 18.0,
		};

		// Default fallback
		const defaultAudit = performCbctPlanningAudit({
			toothFdi: 46,
			implantPose: mockPose,
			canal: mockCanal,
			envelope: mockEnvelope,
			huSampling: mockHuSampling,
		});

		assert.ok(defaultAudit.form043DiaryText.includes("Пациент: Пациент | Клиника: Стоматологический центр DENTE"));
		assert.ok(!defaultAudit.form043DiaryText.includes("Барабаш клиники"));

		// Custom names
		const customAudit = performCbctPlanningAudit({
			toothFdi: 46,
			implantPose: mockPose,
			canal: mockCanal,
			envelope: mockEnvelope,
			huSampling: mockHuSampling,
			patientName: "Иванов И.И.",
			clinicName: "Клиника ДЕНТЕ ПЛЮС",
		});

		assert.ok(customAudit.form043DiaryText.includes("Пациент: Иванов И.И. | Клиника: Клиника ДЕНТЕ ПЛЮС | Зуб: FDI #46"));
	});

	it("12. DEF-19.1: Enforces guaranteed 1-page A4 print layout rules and 105px MPR height", () => {
		const reportData = buildCbctReportData({
			patientName: "Барабаш С.В.",
			targetToothFdi: 46,
			implantPose: mockPose,
			mischResult: mockMischResult,
			huSampling: mockHuSampling,
			containment: mockContainment,
			nerveSafety: mockNerveSafety,
		});

		const html = renderCbctReportHtml(reportData);

		// A4 print page geometry: margin 5mm 8mm
		assert.ok(html.includes("size: A4 portrait;"));
		assert.ok(html.includes("margin: 5mm 8mm;"));

		// Single-page containment CSS
		assert.ok(html.includes(".cbct-report-page"));
		assert.ok(html.includes("max-height: 275mm"));
		assert.ok(html.includes("page-break-inside: avoid"));

		// @media print block
		assert.ok(html.includes("@media print"));

		// MPR card height fixed at 105px
		assert.ok(html.includes("height: 105px;"));
		assert.ok(html.includes("max-height: 105px;"));
		assert.ok(!html.includes("height: 140px;"));

		// Compact table padding: 2px 4px
		assert.ok(html.includes("padding: 2px 4px;"));

		// Wrapper element has cbct-report-page class
		assert.ok(html.includes('<div class="page cbct-report-page">'));
	});

	it("13. DEF-19.2: Strict medical blank without informal emojis or technical toner badges", () => {
		const audit = performCbctPlanningAudit({
			toothFdi: 46,
			implantPose: mockPose,
			canal: { center: { x: 0, y: 17.0 }, radiusMm: 1.5, safetyMarginMm: 2.0 }, // warning proximity
			envelope: { crestPoint: { x: 0, y: 2 }, basePoint: { x: 0, y: 20 }, buccalCrestPoint: { x: -4, y: 2 }, lingualCrestPoint: { x: 4, y: 2 }, ridgeWidthMm: 8, ridgeHeightMm: 18 },
			huSampling: mockHuSampling,
		});

		// Diary generated by performCbctPlanningAudit must be clean of emojis
		assert.ok(!audit.form043DiaryText.includes("🏥"));
		assert.ok(!audit.form043DiaryText.includes("⚠️"));
		assert.ok(!audit.form043DiaryText.includes("⛔"));
		assert.ok(!audit.form043DiaryText.includes("✅"));
		assert.ok(audit.form043DiaryText.includes("ПРОТОКОЛ ОПЕРАЦИИ ДЕНТАЛЬНОЙ ИМПЛАНТАЦИИ (ФОРМА 043/У)"));
		assert.ok(audit.form043DiaryText.includes("Дистанция"));

		// Verify renderStructuredDiary043 cleans legacy emoji strings into canonical warning
		const legacyDiaryWithEmoji = "⚠️ ПРИБЛИЖЕНИЕ к нижнечелюстному каналу\nДистанция 1.0 мм";
		const reportWithLegacyDiary = buildCbctReportData({
			patientName: "Барабаш С.В.",
			targetToothFdi: 46,
			implantPose: mockPose,
			mischResult: mockMischResult,
			huSampling: mockHuSampling,
			diary043Text: legacyDiaryWithEmoji,
		});
		const htmlWithLegacy = renderCbctReportHtml(reportWithLegacyDiary);
		assert.ok(htmlWithLegacy.includes("ВНИМАНИЕ: ЗОНА ПРИБЛИЖЕНИЯ К НЕРВУ"));

		const reportData = buildCbctReportData({
			patientName: "Барабаш С.В.",
			targetToothFdi: 46,
			implantPose: mockPose,
			mischResult: mockMischResult,
			huSampling: mockHuSampling,
			containment: mockContainment,
			nerveSafety: mockNerveSafety,
			diary043Text: audit.form043DiaryText,
			tonerSaving: true,
		});

		const html = renderCbctReportHtml(reportData, { tonerSaving: true });

		// Purge technical English badge from header
		assert.ok(!html.includes("Smart White Paper Inversion"));
		assert.ok(!html.includes("Экономия тонера (Smart White Paper Inversion)"));
		assert.ok(!html.includes("🌱"));

		// Title & Warning: clean text
		assert.ok(!html.includes("🏥"));
		assert.ok(!html.includes("⚠️"));
		assert.ok(!html.includes("⛔"));
		assert.ok(!html.includes("✅"));
		assert.ok(!html.includes("🚀"));
		assert.ok(!html.includes("🌟"));
	});

	it("14. DEF-19.3: Unifies torque units to canonical Russian Н·см (GOST 8.417-2002)", () => {
		const reportData = buildCbctReportData({
			patientName: "Барабаш С.В.",
			targetToothFdi: 46,
			implantPose: mockPose,
			mischResult: mockMischResult,
			huSampling: mockHuSampling,
			containment: mockContainment,
			nerveSafety: mockNerveSafety,
		});

		const html = renderCbctReportHtml(reportData);

		// Russian unit is present
		assert.ok(html.includes("40 Н·см"));

		// English unit N·cm is strictly absent from generated protocol
		assert.ok(!html.includes("N·cm"));
	});

	it("15. DEF-19.4: Outputs operating surgeon name and clinical title in footer", () => {
		// Case A: Default surgeon name
		const defaultReport = buildCbctReportData({
			patientName: "Барабаш С.В.",
			targetToothFdi: 46,
			implantPose: mockPose,
			mischResult: mockMischResult,
			huSampling: mockHuSampling,
			containment: mockContainment,
			nerveSafety: mockNerveSafety,
		});

		const defaultHtml = renderCbctReportHtml(defaultReport);
		assert.ok(defaultHtml.includes("Врач-стоматолог-хирург-имплантолог"));

		// Case B: Custom doctorName passed in props
		const customReport = buildCbctReportData({
			patientName: "Сидоров К.М.",
			doctorName: "Д-р Иванов А.И.",
			targetToothFdi: 46,
			implantPose: mockPose,
			mischResult: mockMischResult,
			huSampling: mockHuSampling,
			containment: mockContainment,
			nerveSafety: mockNerveSafety,
		});

		const customHtml = renderCbctReportHtml(customReport);
		assert.ok(customHtml.includes("Врач-стоматолог-хирург-имплантолог: Д-р Иванов А.И."));
	});

	it("16. DEF-R2-04: Eliminates duplicate 'Врач: Врач-...' in report header info-bar", () => {
		// Case 1: Default / undefined doctorName
		const defaultReport = buildCbctReportData({
			patientName: "Барабаш С.В.",
			targetToothFdi: 46,
			implantPose: mockPose,
			mischResult: mockMischResult,
			huSampling: mockHuSampling,
			containment: mockContainment,
			nerveSafety: mockNerveSafety,
		});
		const defaultHtml = renderCbctReportHtml(defaultReport);
		assert.ok(!defaultHtml.includes("Врач: <b>Врач"));
		assert.ok(defaultHtml.includes("Врач: <b>стоматолог-хирург-имплантолог</b>"));

		// Case 2: doctorName starting with 'Врач-стоматолог-хирург: Барабаш С.В.'
		const reportWithDoctorTitle = buildCbctReportData({
			patientName: "Петров П.П.",
			doctorName: "Врач-стоматолог-хирург-имплантолог: Барабаш С.В.",
			targetToothFdi: 46,
			implantPose: mockPose,
			mischResult: mockMischResult,
			huSampling: mockHuSampling,
			containment: mockContainment,
			nerveSafety: mockNerveSafety,
		});
		const htmlWithTitle = renderCbctReportHtml(reportWithDoctorTitle);
		assert.ok(!htmlWithTitle.includes("Врач: <b>Врач"));
		assert.ok(htmlWithTitle.includes("Врач: <b>стоматолог-хирург-имплантолог: Барабаш С.В.</b>"));

		// Case 3: Plain doctor name without prefix
		const reportPlain = buildCbctReportData({
			patientName: "Иванов И.И.",
			doctorName: "Иванов И.И.",
			targetToothFdi: 46,
			implantPose: mockPose,
			mischResult: mockMischResult,
			huSampling: mockHuSampling,
			containment: mockContainment,
			nerveSafety: mockNerveSafety,
		});
		const htmlPlain = renderCbctReportHtml(reportPlain);
		assert.ok(!htmlPlain.includes("Врач: <b>Врач"));
		assert.ok(htmlPlain.includes("Врач: <b>Иванов И.И.</b>"));
	});

	it("17. DEF-R2-04: Unifies diary 043/u torque string variants to canonical '20 Н·см' (GOST)", () => {
		const diaryWithVariants = [
			"============================================================",
			"ПРОТОКОЛ ОПЕРАЦИИ ДЕНТАЛЬНОЙ ИМПЛАНТАЦИИ (ФОРМА 043/У)",
			"Пациент: Тестовый Т.Т. | Клиника: DENTE | Зуб: FDI #46",
			"============================================================",
			"1. ВЫБОР И ХАРАКТЕРИСТИКИ ИМПЛАНТАТА:",
			"- Прогноз первичного торка: 20 Ncm (ISQ ~72)",
			"- Альтернативный торк: 25 Нсм",
			"- Дополнительный торк: 30 Н*см",
			"- Предельный торк: 35 N·cm",
			"- Торк с пробелом: 40 Н см",
		].join("\n");

		const report = buildCbctReportData({
			patientName: "Тестовый Т.Т.",
			targetToothFdi: 46,
			implantPose: mockPose,
			mischResult: mockMischResult,
			huSampling: mockHuSampling,
			containment: mockContainment,
			nerveSafety: mockNerveSafety,
			diary043Text: diaryWithVariants,
		});

		const html = renderCbctReportHtml(report, { includeForm043Diary: true });
		assert.ok(html.includes("20 Н·см"));
		assert.ok(html.includes("25 Н·см"));
		assert.ok(html.includes("30 Н·см"));
		assert.ok(html.includes("35 Н·см"));
		assert.ok(html.includes("40 Н·см"));
		assert.ok(!html.includes("20 Ncm"));
		assert.ok(!html.includes("25 Нсм"));
		assert.ok(!html.includes("30 Н*см"));
		assert.ok(!html.includes("35 N·cm"));
	});

	it("18. DEF-R2-05: Eliminates blinding white fill in MPR matrix and guarantees all 4 slice views", () => {
		const reportData = buildCbctReportData({
			patientName: "Кузнецов В.С.",
			doctorName: "Д-р Барабаш С.В.",
			studyDate: "30.08.2026",
			targetToothFdi: 46,
			implantPose: mockPose,
			mischResult: mockMischResult,
			huSampling: mockHuSampling,
			containment: mockContainment,
			nerveSafety: mockNerveSafety,
			snapshots: {
				axial: { title: "Аксиальный срез", dataUrl: "data:image/png;base64,axial_data" },
				panoramic: { title: "Панорамная реконструкция (ОПТГ)", dataUrl: "data:image/png;base64,pano_data" },
				crossSection: { title: "Кросс-секция", dataUrl: "data:image/png;base64,cs_data" },
				sagittal: { title: "Сагиттальный срез", dataUrl: "data:image/png;base64,sag_data" },
			},
		});

		const html = renderCbctReportHtml(reportData);

		// MPR card dark background (#090d16) and border (#334155) to prevent blinding white fill
		assert.ok(html.includes("background: #090d16;"));
		assert.ok(html.includes("border: 1px solid #334155;"));

		// All 4 slices are present in 2x2 matrix
		assert.ok(html.includes("1. Аксиальный срез (Z)"));
		assert.ok(html.includes("2. Панорамная реконструкция (ОПТГ)"));
		assert.ok(html.includes("3. Кросс-секция ложа FDI #46"));
		assert.ok(html.includes("4. Косой сагиттальный срез"));

		assert.ok(html.includes("data:image/png;base64,axial_data"));
		assert.ok(html.includes("data:image/png;base64,pano_data"));
		assert.ok(html.includes("data:image/png;base64,cs_data"));
		assert.ok(html.includes("data:image/png;base64,sag_data"));
	});

	it("19. True 300 DPI high-resolution export with calibrated scale ruler and sub-millimeter ticks", async () => {
		const mockCanvas = {
			width: 512,
			height: 512,
			getContext: () => null,
			toDataURL: (type: string) => `data:${type};base64,mock300dpi`,
		} as unknown as HTMLCanvasElement;

		const snap300 = await export300DpiViewportSnapshot(mockCanvas, "Аксиальный срез 300 DPI", 0.25, {
			patientName: "Петров И.В.",
			studyDate: "30.08.2026",
			targetToothFdi: 36,
		});
		assert.ok(typeof snap300 === "string");
		assert.ok(snap300.startsWith("data:image/png;base64,"));
	});

	it("20. 1-Click 152-FZ patient anonymization toggle for clinical consilium and scientific publication", () => {
		const anonReport = buildCbctReportData({
			patientName: "Сидорова Анна Сергеевна",
			targetToothFdi: 46,
			implantPose: mockPose,
			mischResult: mockMischResult,
			huSampling: mockHuSampling,
			isAnonymized: true,
		});

		assert.equal(anonReport.patient.patientName, "АНОНИМИЗИРОВАН (152-ФЗ / КОНСИЛИУМ)");
		assert.equal(anonReport.patient.cardRecordNumber, "043/у-[СКРЫТО]");
		assert.equal(anonReport.patient.studyDate, "[СКРЫТО]");
		assert.equal(anonReport.patient.isAnonymized, true);

		const anonHtml = renderCbctReportHtml(anonReport);
		assert.ok(anonHtml.includes("152-ФЗ: Деперсонализировано"));
		assert.ok(anonHtml.includes("АНОНИМИЗИРОВАН (152-ФЗ / КОНСИЛИУМ)"));
		assert.ok(!anonHtml.includes("Сидорова Анна Сергеевна"));
	});

	it("21. Clinical report header: Vector clinic logo SVG, FOV scan area, Window/Level HU telemetry", () => {
		const telemetryReport = buildCbctReportData({
			patientName: "Ковалев Н.Д.",
			targetToothFdi: 16,
			implantPose: mockPose,
			mischResult: mockMischResult,
			huSampling: mockHuSampling,
			fov: "12×10 см (Ø120×H100 мм)",
			windowWidth: 3800,
			windowLevel: 1200,
		});
		const telemetryHtml = renderCbctReportHtml(telemetryReport);

		// Vector logo in header
		assert.ok(telemetryHtml.includes("<svg") && telemetryHtml.includes("viewBox="));
		// FOV and W/L HU values in info-bar
		assert.ok(telemetryHtml.includes("12×10 см"));
		assert.ok(telemetryHtml.includes("W:3800 L:1200 HU"));
	});

	it("22. Multi-slice A4 consultation protocol: Axial + Coronal + Sagittal + 3D/Panorama with millimeter rulers", () => {
		const multiSliceReport = buildCbctReportData({
			patientName: "Иванов С.П.",
			targetToothFdi: 46,
			implantPose: mockPose,
			mischResult: mockMischResult,
			huSampling: mockHuSampling,
			snapshots: {
				axial: { title: "Аксиальный срез", dataUrl: "data:image/png;base64,axial_4s" },
				coronal: { title: "Корональный срез", dataUrl: "data:image/png;base64,coronal_4s" },
				sagittal: { title: "Сагиттальный срез", dataUrl: "data:image/png;base64,sagittal_4s" },
				panoramic: { title: "Панорама 3D", dataUrl: "data:image/png;base64,pano_4s" },
			},
		});
		const multiSliceHtml = renderCbctReportHtml(multiSliceReport);

		assert.ok(multiSliceHtml.includes("1. Аксиальный срез (Z)"));
		assert.ok(multiSliceHtml.includes("2. Корональный срез (Y)"));
		assert.ok(multiSliceHtml.includes("3. Сагиттальный срез (X)"));
		assert.ok(multiSliceHtml.includes("4. 3D-реконструкция / Панорама"));
		assert.ok(multiSliceHtml.includes("10 мм • 1 мм/дел"));
		assert.ok(multiSliceHtml.includes("data:image/png;base64,coronal_4s"));
	});

	it("23. Strict Mandate 8d verification: Zero informal emojis across all clinical print documents", () => {
		const multiSliceReport = buildCbctReportData({
			patientName: "Иванов С.П.",
			targetToothFdi: 46,
			implantPose: mockPose,
			mischResult: mockMischResult,
			huSampling: mockHuSampling,
			snapshots: {
				axial: { title: "Аксиальный срез", dataUrl: "data:image/png;base64,axial_4s" },
				coronal: { title: "Корональный срез", dataUrl: "data:image/png;base64,coronal_4s" },
				sagittal: { title: "Сагиттальный срез", dataUrl: "data:image/png;base64,sagittal_4s" },
				panoramic: { title: "Панорама 3D", dataUrl: "data:image/png;base64,pano_4s" },
			},
		});
		const html = renderCbctReportHtml(multiSliceReport);
		const emojiRe = /\p{Extended_Pictographic}/u;
		assert.ok(!emojiRe.test(html), "Report must not contain informal emojis");
	});

	it("24. generateSynchronizedReportSnapshots produces all 5 slices including coronal with 300 DPI support", async () => {
		const mockVolume = {
			dimensions: { width: 32, height: 32, depth: 32 },
			spacingMm: { x: 0.4, y: 0.4, z: 0.4 },
			originMm: { x: 0, y: 0, z: 0 },
			physicalSizeMm: { x: 12.8, y: 12.8, z: 12.8 },
			voxels: new Int16Array(32 * 32 * 32),
			dataRange: { min: -1000, max: 3000 },
			metadata: { patientName: "Test" },
		};
		const snapshots = await generateSynchronizedReportSnapshots({
			volume: mockVolume as any,
			crosshairMm: { x: 6.4, y: 6.4, z: 6.4 },
			targetToothFdi: 46,
			isAnonymized: true,
			targetDpi: 300,
		});
		assert.ok(snapshots.axial);
		assert.ok(snapshots.coronal);
		assert.ok(snapshots.sagittal);
		assert.ok(snapshots.panoramic);
		assert.ok(snapshots.crossSection);
		assert.equal(snapshots.coronal.orientationLabel, "CORONAL");
		assert.equal(snapshots.axial.orientationLabel, "AXIAL");
	});
}
