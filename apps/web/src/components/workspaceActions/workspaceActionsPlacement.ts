/**
 * РАСКЛАДКА ГРУППЫ ДЕЙСТВИЙ РАБОЧЕЙ ОБЛАСТИ — порядок и место, без геометрии.
 *
 * ЧТО ЗДЕСЬ БЫЛО РАНЬШЕ И ПОЧЕМУ ЭТОГО БОЛЬШЕ НЕТ.
 * Предыдущий вариант (`floatingCorner/cornerDockLayout.ts`) держал в правом
 * нижнем углу плавающую панель поверх страницы и пытался «уступать» контенту:
 * пять раз за проход вызывал `document.elementsFromPoint`, собирал список
 * «помех», считал площадь перекрытия и поднимался, если накрыл мишень не менее
 * чем на `CORNER_OBSTACLE_BLOCK_SHARE = 0.5` её площади.
 *
 * Порог 0.5 недостижим арифметически, и это не мнение. При равной высоте
 * накрытая доля равна `ширина панели / ширина мишени`. Панель шириной 168px
 * (окно 390x844) не может накрыть половину ничего шире 336px, панель 278px
 * (окно 1600x1100) — ничего шире 556px. Главная кнопка продукта
 * `button.primary-button` «Запись» имеет размер 364x44 на четырёх маршрутах из
 * пяти, то есть максимум 168·44 / (364·44) = 0.4615: панель не могла уступить
 * ей НИКОГДА. Тост входящего звонка (`IncomingCallToast.tsx`, 384px шириной и
 * выше 120px) давал долю 0.089-0.155 — чтобы он сработал, он должен был бы быть
 * не выше 69px. Замерено ревьюером в живом браузере: подъём остался 0.
 * Итог: механизм «уступи кнопке» не срабатывал на кнопках, зато сам садился на
 * `<label>Email</label>` формы пациента (доля 0.443, подъёма нет), и
 * `document.elementFromPoint` в центре подписи возвращал кнопку поиска дока.
 *
 * Никакое значение порога это не лечит — геометрия запрещает. Поэтому панель
 * больше не плавает над контентом ВООБЩЕ: её действия живут в существующей
 * фурнитуре экрана, в обычном потоке. Раз ничто не висит над страницей —
 * не нужны ни выборка помех, ни подъём, ни резерв пустого низа.
 *
 * Здесь остаётся то, что после переезда действительно является логикой: КУДА
 * группа садится и В КАКОМ ПОРЯДКЕ стоят её кнопки. Чистые функции — их
 * проверяет `workspaceActionsPlacement.test.ts`, а не профилировщик.
 */

/**
 * Все слоты в порядке разметки хоста. `notice` идёт первым: это временная
 * накладка (расшифровка речи, справка, чип выполненной команды), она обязана
 * стоять выше строки кнопок в обеих раскладках.
 *
 * ЭТО ЕДИНСТВЕННЫЙ СПИСОК СЛОТОВ В ПРОЕКТЕ. Тип, состав строки кнопок и оба
 * порядка вывода выведены из него ниже, а не переписаны рядом: скопированный
 * руками союз в этом проекте уже разъезжался с источником и ломал сборку.
 */
export const WORKSPACE_ACTION_SLOTS = [
	"notice",
	"search",
	"voice",
	"help",
] as const;

/** Слоты группы действий. Других слотов не существует. */
export type WorkspaceActionSlotId = (typeof WORKSPACE_ACTION_SLOTS)[number];

/** Слот строки кнопок: всё, кроме временной накладки. */
export type WorkspaceActionBarSlotId = Exclude<WorkspaceActionSlotId, "notice">;

/**
 * Где живёт группа.
 * `header` — строка действий топбара (широкие экраны).
 * `nav` — нижняя мобильная навигация (узкие экраны).
 */
export type WorkspaceActionPlacement = "header" | "nav";

/**
 * Селектор нижней навигации. Это контракт разметки оболочки (`App.tsx`
 * рендерит `<nav className="dnt-bottom-nav">`), а не настройка.
 */
export const WORKSPACE_ACTION_NAV_SELECTOR = ".dnt-bottom-nav";

/** Идентификатор хоста группы: он один на весь документ. */
export const WORKSPACE_ACTION_HOST_ID = "dnt-workspace-actions";

/** Слоты строки кнопок. Накладка в строку не входит. */
export const WORKSPACE_ACTION_BAR_SLOTS: readonly WorkspaceActionBarSlotId[] =
	WORKSPACE_ACTION_SLOTS.filter(
		(slot): slot is WorkspaceActionBarSlotId => slot !== "notice",
	);

/**
 * Главное действие группы. Ради него человек и открывает панель на телефоне,
 * поэтому в узкой раскладке оно стоит первым.
 */
export const WORKSPACE_ACTION_PRIMARY: WorkspaceActionBarSlotId = "voice";

/**
 * Куда садится группа.
 *
 * Единственный источник истины о пороге ширины — CSS: нижняя навигация
 * появляется на `max-width: 840px` правилом `.dnt-bottom-nav`. Здесь этот порог
 * НЕ дублируется числом (продублированный порог уже разъезжался в этом проекте:
 * `52.5rem` против `840px`). Вызывающий сообщает только одно: отрисована ли
 * навигация сейчас. Нет навигации в разметке — группа идёт в топбар, это
 * безопасное значение по умолчанию: топбар есть на всех ширинах.
 */
export function resolveWorkspaceActionPlacement(input: {
	readonly bottomNavDisplayed: boolean;
}): WorkspaceActionPlacement {
	return input.bottomNavDisplayed ? "nav" : "header";
}

/**
 * Порядок кнопок в строке. Он разный, и это не украшение.
 *
 * `header` — горизонтальная группа в топбаре, читается слева направо в порядке
 * объявления слотов: поиск (самое частое), голос (главное действие, выделено),
 * справка (реже всего).
 *
 * `nav` — вертикальный список в панели над нижней навигацией, на телефоне.
 * Первым идёт главное действие: панель открывается кнопкой «Голос», и то, за чем
 * человек пришёл, обязано быть под большим пальцем, а не третьим сверху.
 *
 * Оба порядка ВЫВЕДЕНЫ из `WORKSPACE_ACTION_SLOTS`, поэтому новый слот попадает
 * в обе раскладки сам и не может потеряться в одной из них.
 */
export function workspaceActionBarOrder(
	placement: WorkspaceActionPlacement,
): readonly WorkspaceActionBarSlotId[] {
	if (placement !== "nav") return WORKSPACE_ACTION_BAR_SLOTS;
	return [
		WORKSPACE_ACTION_PRIMARY,
		...WORKSPACE_ACTION_BAR_SLOTS.filter(
			(slot) => slot !== WORKSPACE_ACTION_PRIMARY,
		),
	];
}
