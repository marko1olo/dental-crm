import type { IntakeRequisitesContext } from "./types";

export function renderPersonalDataSheet(ctx: IntakeRequisitesContext): string {
	const {
		clinicName, clinicInn, clinicAddress, hasRep, repFullName, repRelation, repBasis,
		repPassport, ptAddress, repPhone, ptName, ptBirthDate, ptSnils, ptPassport, ptPhone,
		ptSignatureDecoding, todayFormatted,
	} = ctx;

	return `  <div class="print-sheet">
    <div>
      <div class="sheet-header">
        <div class="clinic-top-row">
          <div>
            <strong>${clinicName}</strong> · Оператор персональных данных
          </div>
          <div style="text-align: right;">
            <span class="statutory-badge">Федеральный закон от 27.07.2006 № 152-ФЗ ст. 6, 9, 10</span>
          </div>
        </div>
        <h1>СОГЛАСИЕ НА ОБРАБОТКУ ПЕРСОНАЛЬНЫХ ДАННЫХ</h1>
        <div class="sheet-subtitle">включая специальные категории данных о состоянии здоровья и передачу в ЕГИСЗ</div>
      </div>

      <div class="parties-block">
        ${
					hasRep
						? `Я, <strong>${repFullName}</strong> (${repRelation}, основание: ${repBasis}), паспорт: ${repPassport}, проживающий(-ая) по адресу: ${ptAddress}, тел.: ${repPhone}, являясь законным представителем несовершеннолетнего субъекта персональных данных: <strong>${ptName}</strong>, дата рождения: ${ptBirthDate}, документ: ${ptPassport}, СНИЛС: ${ptSnils}, свободно, своей волей и в интересах подопечного даю согласие Оператору — <strong>${clinicName}</strong> (ИНН: ${clinicInn}, адрес: ${clinicAddress}), на обработку персональных данных на следующих условиях:`
						: `Субъект персональных данных: <strong>${ptName}</strong>, дата рождения: ${ptBirthDate}, паспорт: ${ptPassport}, СНИЛС: ${ptSnils}, адрес: ${ptAddress}, телефон: ${ctx.ptPhone}, свободно, своей волей и в своем интересе дает согласие Оператору — <strong>${clinicName}</strong> (ИНН: ${clinicInn}, адрес: ${clinicAddress}), на обработку своих персональных данных на следующих условиях:`
				}
      </div>

      <div class="section-title">1. Цели обработки персональных данных</div>
      <p>1.1. Оказание первичной медико-санитарной и специализированной стоматологической помощи, постановка диагноза, составление и исполнение планов лечения.</p>
      <p>1.2. Ведение медицинской документации (включая электронную медицинскую карту приёма) и исполнение требований Федерального закона № 323-ФЗ и Постановления Правительства РФ № 140 по передаче сведений в Единую государственную информационную систему в сфере здравоохранения (ЕГИСЗ Минздрава РФ: РЭМД/ФРЭМД) и личный кабинет «Мое здоровье» на Едином портале государственных услуг (Госуслуги).</p>
      <p>1.3. Информирование о времени приёма, напоминание о визитах, готовности лабораторных изделий и профилактических осмотрах посредством телефонных звонков, SMS и мессенджеров.</p>

      <div class="section-title">2. Перечень обрабатываемых персональных данных</div>
      <p>2.1. <strong>Общие персональные данные:</strong> фамилия, имя, отчество; пол; дата и место рождения; данные документа, удостоверяющего личность; адрес регистрации и фактического проживания; номер контактного телефона; СНИЛС; реквизиты полиса ОМС/ДМС.</p>
      <p>2.2. <strong>Специальные категории (данные о состоянии здоровья):</strong> сведения о стоматологическом статусе, анамнезе, сопутствующих соматических заболеваниях, аллергиях, диагнозах, результатах рентгенологических и томографических исследований, выполненных манипуляциях и медикаментозных назначениях.</p>
      <p>2.3. <strong>Биометрические персональные данные (ст. 11 152-ФЗ):</strong> дентальный фотопротокол лица и полости рта, цифровые рентгенограммы (RVG, ОПТГ, ТРГ), данные трехмерной компьютерной томографии (3D КЛКТ), интраоральное 3D-сканирование челюстей — исключительно в целях диагностики, составления и согласования плана лечения, идентификации пациента и объективного контроля качества оказанной медицинской помощи.</p>

      <div class="section-title">3. Перечень действий и срок обработки</div>
      <p>3.1. Оператор осуществляет смешанную (автоматизированную и неавтоматизированную) обработку персональных данных: сбор, запись, систематизацию, накопление, хранение, уточнение, извлечение, использование, передачу (в рамках требований законодательства РФ) и уничтожение.</p>
      <p>3.2. Согласие действует с момента подписания бессрочно либо до его отзыва. Согласие может быть отозвано письменным заявлением субъекта. В случае отзыва согласия Оператор вправе продолжить хранение медицинской документации в силу ч. 2 ст. 10 152-ФЗ и законодательства об охране здоровья граждан (срок хранения медкарты — 25 лет).</p>
    </div>

    <div class="signatures-row">
      <div class="sign-box" style="grid-column: span 2;">
        ${hasRep ? `Законный представитель (${repRelation}) в интересах несовершеннолетнего:` : "Субъект персональных данных (Пациент / Законный представитель):"}<br>
        <strong>${hasRep ? repFullName : ptName}</strong>${hasRep ? ` (в интересах: ${ptName})` : ""} · Паспорт: ${hasRep ? repPassport : ptPassport}<br>
        Личная подпись: ________________________${hasRep ? ` / ${repFullName} /` : ptSignatureDecoding}<br>
        <div class="sign-line"></div>
        <div class="sign-hint">(${hasRep ? "подпись законного представителя" : "подпись гражданина"} / дата: ${todayFormatted})</div>
      </div>
    </div>
  </div>`;
}
