/**
 * Реквизиты оператора персональных данных: чего не хватает согласию на ПДн.
 *
 * ЧТО ВИДЕЛ АДМИНИСТРАТОР. Раздел «Документы», вид «Согласие на ПДн». Три
 * верхних поля — «Оператор», «ИНН оператора», «Адрес оператора» — форма только
 * ПОКАЗЫВАЕТ, вписать в них нельзя: они приходят из профиля клиники. На новой
 * клинике профиль пуст, и все три поля рисуются пустыми серыми рамками. Ни
 * пометки «обязательно», ни слова о том, что без них согласие не создастся.
 * Ровно так же они выглядят, когда реквизиты просто не доехали с сервера:
 * отказ запроса и незаполненный профиль на экране неотличимы, и то и другое —
 * пустота.
 *
 * Нажатие «Создать выбранный документ» отвечало по одной позиции за раз, потому
 * что validatePersonalDataProcessingConsent (documentValidators.ts:1602) — это
 * цепочка `??`: сначала «Заполните поле: ПДн, оператор клиники.», после правки
 * «ИНН оператора ПДн должен содержать 10 или 12 цифр.», потом «Заполните поле:
 * ПДн, адрес оператора.». Подпись в отказе — служебная («ПДн, оператор
 * клиники»), и куда идти заполнять, отказ не говорил вовсе. Поле правке не
 * поддаётся, так что подсказка была тупиковой: человек упирался в серую рамку.
 *
 * ЧТО ЗДЕСЬ. Тот же разбор реквизитов оператора, но целиком и ДО нажатия, с
 * названием экрана, на котором их заполняют. Пустой ИНН и ИНН неверной длины
 * различаются: это разные действия человека.
 *
 * ПОЧЕМУ КОПИЯ ПРАВИЛА, А НЕ ВЫЗОВ ВАЛИДАТОРА. Валидатор физически не умеет
 * отдать больше одной позиции (`a ?? b ?? c` останавливается на первой
 * непустой) и требует весь DocumentState, которого у формы нет — ей передают
 * только черновик профиля клиники.
 *
 * НЕЗАКРЫТЫЙ ДОЛГ, ЧЕСТНО. У договора платных услуг такую же копию правила
 * сторожит tests/paidContractRequiredFields.test.ts — он заполняет позиции из
 * копии и требует, чтобы валидатор замолчал. Здесь такого сторожа НЕТ: правка
 * ограничена каталогом components/documents, а тесты живут в src/tests. Если
 * список принимаемых длин ИНН или состав реквизитов в
 * validatePersonalDataProcessingConsent изменят, этот разбор разойдётся с ним
 * молча. Сторож заявлен долгом в отчёте пакета.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Остальные обязательные позиции согласия (цели, категории,
 * действия, передача, срок хранения, порядок отзыва, дата и две отметки) лежат
 * в самой форме, человек их видит и правит руками. Здесь только то, что из
 * формы недостижимо.
 */

/** Одна незаполненная или неверная позиция реквизитов оператора. */
export interface PersonalDataOperatorProblem {
	/** Ключ поля профиля клиники: устойчив к переименованию подписи. */
	field: string;
	/** Подпись ровно как в форме выше — человек ищет её глазами. */
	label: string;
	/** Что именно сделать. Тупиковых подсказок быть не должно. */
	hint: string;
}

export interface PersonalDataOperatorReview {
	/** Сколько реквизитов оператора требует проверка согласия. */
	requiredCount: number;
	/** Незаполненные и неверные, в том же порядке, в каком о них ругается проверка. */
	problems: PersonalDataOperatorProblem[];
}

/** Реквизиты оператора, которые читает согласие на ПДн. */
export interface PersonalDataOperatorInput {
	/** Юридическое название. Пустое — берётся название клиники. */
	legalName: string;
	clinicName: string;
	inn: string;
	address: string;
}

/** Экран, на котором эти реквизиты заполняют. Название взято из живых вкладок. */
export const CLINIC_REQUISITES_LOCATION =
	"Настройки → Клиника → Юридический профиль клиники";

/**
 * Длины ИНН, которые принимает проверка согласия: 10 у организации, 12 у
 * индивидуального предпринимателя. Дословно повторяет условие в
 * validatePersonalDataProcessingConsent.
 */
export const OPERATOR_INN_LENGTHS = [10, 12] as const;

function digitsOf(value: string): string {
	return String(value ?? "").replace(/[^\d]/g, "");
}

function innProblemHint(inn: string): string | null {
	const digits = digitsOf(inn);
	if (digits.length === 0) {
		return `в профиле клиники не заполнен ИНН — впишите его в «${CLINIC_REQUISITES_LOCATION}»`;
	}
	if (OPERATOR_INN_LENGTHS.includes(digits.length as 10 | 12)) return null;
	return `в профиле клиники ИНН из ${digits.length} цифр, а нужно 10 у организации или 12 у ИП — проверьте его в «${CLINIC_REQUISITES_LOCATION}»`;
}

export function personalDataOperatorRequisitesReview(
	input: PersonalDataOperatorInput,
): PersonalDataOperatorReview {
	const operatorName =
		String(input.legalName ?? "").trim() ||
		String(input.clinicName ?? "").trim();
	const address = String(input.address ?? "").trim();
	const innHint = innProblemHint(input.inn);

	const problems: PersonalDataOperatorProblem[] = [];

	if (operatorName === "") {
		problems.push({
			field: "legalName",
			label: "Оператор",
			hint: `в профиле клиники нет ни юридического названия, ни названия клиники — впишите юридическое название в «${CLINIC_REQUISITES_LOCATION}»`,
		});
	}
	if (innHint) {
		problems.push({ field: "inn", label: "ИНН оператора", hint: innHint });
	}
	if (address === "") {
		problems.push({
			field: "address",
			label: "Адрес оператора",
			hint: `в профиле клиники не заполнен адрес — впишите его в «${CLINIC_REQUISITES_LOCATION}»`,
		});
	}

	return { requiredCount: 3, problems };
}
