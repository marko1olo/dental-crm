export function isSupportedToothFdi(code: unknown): boolean {
	if (typeof code !== "string") return false;
	const trimmed = code.trim();
	return (
		PERMANENT_TEETH_FDI.includes(trimmed as any) ||
		PRIMARY_TEETH_FDI.includes(trimmed as any)
	);
}

export function getToothNameRu(code: string): string {
	return TOOTH_NAMES_MAP[code.trim()] || `Зуб ${code}`;
}

export function formatToothSelectionLabel(code?: string | null): string {
	if (!code) return "Привязать зуб";
	return `Зуб #${code}`;
}
