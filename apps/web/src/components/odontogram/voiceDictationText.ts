/**
 * Что человек читает в окне диктовки, когда распознавание речи не работает.
 *
 * ЧТО БЫЛО СЛОМАНО. Обработчик ошибки распознавания делал только
 * `logger.error("Speech recognition error", event.error); setIsListening(false)`.
 * На экране это выглядело так: окно диктовки открыто, полоски замерли, слов нет,
 * кнопок нет — и ни одного объяснения. Самая частая причина здесь
 * «not-allowed», то есть браузер не дал доступ к микрофону: пока врач не
 * разрешит его в браузере, диктовка не заработает никогда, а окно об этом
 * молчало.
 *
 * Код ошибки английский и человеку не показывается: он остаётся в logger.error.
 * Коды взяты из живого перечня SpeechRecognitionErrorEvent.error.
 */
export function voiceDictationErrorText(code: unknown): string {
	const normalized = typeof code === "string" ? code.trim().toLowerCase() : "";
	if (normalized === "not-allowed" || normalized === "service-not-allowed") {
		return "Браузер не дал доступ к микрофону. Разрешите микрофон для этой страницы в настройках браузера (значок замка слева от адреса) и откройте диктовку заново.";
	}
	if (normalized === "audio-capture") {
		return "Микрофон не найден. Проверьте, что он подключён и выбран в настройках звука, и откройте диктовку заново.";
	}
	if (normalized === "no-speech") {
		return "Речь не услышана. Проверьте, что говорите в микрофон, и попробуйте ещё раз.";
	}
	if (normalized === "network") {
		return "Распознавание речи не смогло связаться со своим сервером. Проверьте сеть и попробуйте ещё раз.";
	}
	if (normalized === "aborted") {
		return "Запись прервана. Откройте диктовку заново.";
	}
	return "Распознать речь не удалось. Попробуйте ещё раз, а если не выходит — закройте окно и отметьте зубы на схеме вручную.";
}

