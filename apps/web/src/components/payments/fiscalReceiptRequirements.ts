/**
 * Чего не хватает в чеке для вычета — строками для списка «осталось заполнить».
 * Пустой список означает, что чек полон.
 */
export function missingTaxDeductionSteps(fields: TaxDeductionFields): string[] {
	return taxDeductionRequirements
		.filter((requirement) => !fields[requirement.key].trim())
		.map((requirement) => `для вычета укажите ${requirement.step}`);
}

/**
 * То же самое перечислением для отказа записи оплаты.
 *
 * Обработчик записи оплаты обязан спрашивать ровно этот же список: если экран и
 * запись разойдутся, кнопка «Принять оплату» станет доступной, а сервер оплату
 * отклонит — оплата будет выглядеть принятой, не будучи принятой.
 */
export function missingTaxDeductionLabels(
	fields: TaxDeductionFields,
): string[] {
	return taxDeductionRequirements
		.filter((requirement) => !fields[requirement.key].trim())
		.map((requirement) => requirement.label);
}
