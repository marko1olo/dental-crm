import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import test from "node:test";
import { viewLabels } from "../workspaceShell.js";

/**
 * Страж панели «Звонки и сообщения» на карточке пациента.
 *
 * ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ. Только то, что ломается НЕЗАМЕТНО: экран продолжает
 * рисоваться, ошибки нет, а сказанное на нём становится неправдой. Отрисовки в
 * проекте нет (браузерных тестов нет вовсе), поэтому проверка текстовая — по
 * поставляемому исходнику, как в tests/patientsWidgetsGridColumns.test.ts.
 * Доказательством отрисовки она не является.
 *
 * 1. ИМЯ РАЗДЕЛА, КУДА ПАНЕЛЬ ОТПРАВЛЯЕТ. Панель говорит «закройте задачу в
 *    разделе ...» рядом с задачей «позвонить руками». В первой редакции там
 *    стояло «Общение» — раздела с таким названием в программе нет ни в одном
 *    режиме клиники: реестр один, workspaceShell.viewLabels, и связь называется
 *    «Связь», а «Обращения» — это другой раздел (leads, заявки до записи),
 *    который у отдельного врача из меню убран. Инструкция посылала
 *    администратора искать несуществующий пункт меню. Переименуют раздел —
 *    сломается здесь, а не на глазах у клиники.
 *
 * 2. ВОЗВРАТ ЛГУЩИХ ПУСТЫХ СОСТОЯНИЙ. Обе прежние формулировки утверждали
 *    больше, чем система знает: в communication_events попадает только то, что
 *    прошло через клинику, а звонок с личного телефона врача не попадает. «Общения
 *    не было» — это новое вранье вместо старого.
 *
 * 3. ВОЗВРАТ ССЫЛКИ НА ЗАПИСЬ РАЗГОВОРА И ВЫДУМАННЫХ ПОЛЕЙ. Поля записи в
 *    источнике нет, а единственная таблица с расшифровками связана с человеком
 *    телефоном, который у семьи общий. Кнопка «Прослушать запись» может
 *    вернуться только вместе с выдуманным полем.
 *
 * 4. ВТОРАЯ РЕАЛИЗАЦИЯ ТОЙ ЖЕ ПАНЕЛИ. Маршрут отдаёт ОБЪЕКТ с итогами, а не
 *    массив строк. Копия, читающая ответ через Array.isArray, молча покажет
 *    пустой журнал на непустой базе — ровно та подмена отказа пустотой, из-за
 *    которой панель и переписывалась. Поэтому реализация обязана быть одна.
 *
 * ПОЧЕМУ КОММЕНТАРИИ ВЫРЕЗАЮТСЯ ПЕРЕД ПРОВЕРКОЙ. Обе панели объясняют в шапке,
 * ЧЕГО в них нет и почему: там дословно стоят и «Прослушать запись», и
 * «Array.isArray», и прежние лгущие формулировки. Без вырезания страж падал бы
 * на объяснении вместо дефекта, а первое же «починим тест» стёрло бы объяснение.
 * Строковые литералы при этом не тронуты: удаляются только блочные комментарии и
 * строки, начинающиеся с `//`, — то есть проверка может стать строже, но не
 * слабее.
 */

const webSrc = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function read(relativePath: string): string {
	return readFileSync(path.join(webSrc, relativePath), "utf8");
}

/** Исходник без комментариев: остаётся то, что реально попадает на экран. */
function code(relativePath: string): string {
	return read(relativePath)
		.replace(/\/\*[\s\S]*?\*\//g, "")
		.split(/\r?\n/)
		.filter((line) => !line.trim().startsWith("//"))
		.join("\n");
}

const PANEL = "components/patients/PatientCommunicationTimelineWidget.tsx";
const WRAPPER = "components/crm/PatientCommunicationTimelinesWidget.tsx";

test("панель отправляет в раздел, который есть в реестре разделов", () => {
	const source = code(PANEL);

	const declared = /const COMMUNICATIONS_SECTION_TITLE = "([^"]+)"/.exec(source);
	assert.ok(
		declared,
		"в панели не найдено объявление COMMUNICATIONS_SECTION_TITLE — имя раздела снова вписано в разметку и разъедется с реестром",
	);
	assert.equal(
		declared?.[1],
		viewLabels.communications,
		`панель отправляет в раздел «${declared?.[1]}», а в реестре workspaceShell.viewLabels он называется «${viewLabels.communications}»`,
	);

	// Прямой возврат исходного дефекта: раздела «Общение» в программе нет.
	assert.ok(
		!source.includes("«Общение»"),
		"в панель вернулся раздел «Общение» — такого пункта меню не существует ни в одном режиме клиники",
	);
	// «Обращения» — это leads, воронка заявок до записи, а не журнал переписки.
	// У отдельного врача и одного кабинета раздел из меню убран (getVisibleRailViews).
	assert.ok(
		!source.includes(`разделе «${viewLabels.leads}»`),
		`панель отправляет в раздел «${viewLabels.leads}» — это воронка заявок до записи, и у отдельного врача её нет в меню`,
	);
});

test("пустой журнал не выдаётся за отсутствие общения", () => {
	const source = code(PANEL);
	const wrapper = code(WRAPPER);

	// Прежние формулировки обеих панелей — каждая утверждала больше, чем известно.
	for (const lie of [
		"Записи звонков и сообщений с пациентом отсутствуют",
		"Звонков и сообщений по пациенту не записано",
	]) {
		assert.ok(!source.includes(lie), `в панель вернулась формулировка «${lie}»: она читается как «с человеком не связывались»`);
		assert.ok(!wrapper.includes(lie), `в обёртку вернулась формулировка «${lie}»`);
	}

	// Пустое состояние обязано ограничить утверждение каналом и назвать, что
	// именно сюда попадает, — иначе оператор достроит вывод сам.
	assert.match(
		source,
		/Обращений через систему не записано/,
		"пустое состояние панели изменилось: оно обязано говорить «через систему не записано», а не «обращений не было»",
	);
	assert.match(
		source,
		/личного телефона врача/,
		"из пустого состояния убрана оговорка про звонок с личного телефона врача — без неё пустой журнал читается как «не звонили»",
	);
	// Отказ сервера обязан оставаться отказом, а не превращаться в пустой журнал.
	assert.match(
		source,
		/Это не значит, что общения с пациентом не было/,
		"из сообщения об отказе убрана оговорка: отказ чтения нельзя показывать как отсутствие обращений",
	);
});

test("ссылка на запись разговора не вернулась: такого поля в источнике нет", () => {
	const source = code(PANEL);
	for (const invented of ["audioRecordingUrl", "Прослушать запись", "statusColor", "eventType"]) {
		assert.ok(
			!source.includes(invented),
			`в панель вернулось поле ${invented} мёртвой таблицы patient_communication_timelines — сервер его не отдаёт, блок будет пустым`,
		);
	}
});

test("журнал на экране «Пациенты» — одна реализация, а не вторая копия", () => {
	const wrapper = code(WRAPPER);

	assert.match(
		wrapper,
		/import \{ PatientCommunicationTimelineWidget \} from "\.\.\/patients\/PatientCommunicationTimelineWidget"/,
		"обёртка перестала переиспользовать единственную реализацию журнала",
	);
	// Ответ маршрута — объект с итогами. Разбор массивом означает вторую копию,
	// которая покажет пустой журнал на непустой базе.
	assert.ok(
		!wrapper.includes("Array.isArray"),
		"в обёртке снова разбирается ответ: маршрут отдаёт объект с итогами, и Array.isArray даст пустой список на непустой базе",
	);
	assert.ok(!wrapper.includes("usePatientResource"), "обёртка снова грузит данные сама — это вторая копия панели");

	// Внешняя метка сохранена: на неё ссылается генератор снимков-доказательств.
	assert.ok(
		wrapper.includes('data-testid="patient-communication-timelines-widget"'),
		"снята метка patient-communication-timelines-widget — scripts/generate-wave15-individual-proofs.cjs перестанет находить панель",
	);
});
