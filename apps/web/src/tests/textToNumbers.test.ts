import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { textToNumbers } from "../lib/stringUtils.js";

/**
 * textToNumbers переводит надиктованные словами числа в цифры. Через неё
 * идут: сумма платежа (PaymentCapture), разбор прайса, разбор записи на
 * приём, разбор диктовки приёма и разбор карточки пациента. То есть
 * ошибка здесь — это неверная сумма в кассе или неверный номер зуба в
 * медкарте.
 *
 * Проверок у функции не было. Замеры, из которых выросли эти тесты, лежат
 * в scratch/probe-numbers-realfn.mjs и scratch/audit-text-to-numbers.mjs.
 */

function convert(input: string): string {
	return textToNumbers(input).trim().replace(/\s+/g, " ");
}

describe("textToNumbers: простые числительные", () => {
	it("переводит числительные от нуля до девятнадцати", () => {
		const expected: Array<[string, string]> = [
			["ноль", "0"],
			["один", "1"],
			["два", "2"],
			["три", "3"],
			["четыре", "4"],
			["пять", "5"],
			["шесть", "6"],
			["семь", "7"],
			["восемь", "8"],
			["девять", "9"],
			["десять", "10"],
			["одиннадцать", "11"],
			["двенадцать", "12"],
			["тринадцать", "13"],
			["четырнадцать", "14"],
			["пятнадцать", "15"],
			["шестнадцать", "16"],
			["семнадцать", "17"],
			["восемнадцать", "18"],
			["девятнадцать", "19"],
		];
		for (const [input, out] of expected) assert.equal(convert(input), out, `«${input}»`);
	});

	it("«ноль» не задваивается", () => {
		// БЫЛО: «0 0» — ветка нуля дописывала цифру, а затем общий выход
		// дописывал её второй раз.
		assert.equal(convert("ноль"), "0");
		assert.equal(convert("ноль рублей"), "0 рублей");
	});

	it("переводит десятки и сотни", () => {
		assert.equal(convert("двадцать"), "20");
		assert.equal(convert("тридцать"), "30");
		assert.equal(convert("сорок"), "40");
		assert.equal(convert("пятьдесят"), "50");
		assert.equal(convert("девяносто"), "90");
		assert.equal(convert("сто"), "100");
		assert.equal(convert("двести"), "200");
		assert.equal(convert("триста"), "300");
	});
});

describe("textToNumbers: падежные формы", () => {
	/**
	 * БЫЛО: корни перебирались от длинного к короткому, и длинный корень
	 * перехватывал форму короткого. «двадцати» превращалось в 12, а
	 * «тридцати» — в 13. Для суммы платежа это значит, что «тридцати тысяч»
	 * давало 13000 вместо 30000.
	 */
	it("десятки в родительном падеже не путаются с подростковыми числами", () => {
		assert.equal(convert("двадцати"), "20");
		assert.equal(convert("тридцати"), "30");
		assert.equal(convert("сорока"), "40");
		assert.equal(convert("пятидесяти"), "50");
		assert.equal(convert("шестидесяти"), "60");
		assert.equal(convert("семидесяти"), "70");
		assert.equal(convert("восьмидесяти"), "80");
		assert.equal(convert("девяноста"), "90");
	});

	it("подростковые числа в родительном падеже сохраняют своё значение", () => {
		assert.equal(convert("одиннадцати"), "11");
		assert.equal(convert("двенадцати"), "12");
		assert.equal(convert("тринадцати"), "13");
		assert.equal(convert("пятнадцати"), "15");
		assert.equal(convert("шестнадцати"), "16");
		assert.equal(convert("семнадцати"), "17");
		assert.equal(convert("восемнадцати"), "18");
		assert.equal(convert("девятнадцати"), "19");
	});

	it("короткие родительные формы разбираются", () => {
		assert.equal(convert("двух"), "2");
		assert.equal(convert("трёх"), "3");
		assert.equal(convert("четырёх"), "4");
		assert.equal(convert("пяти"), "5");
		assert.equal(convert("восьми"), "8");
		assert.equal(convert("ста"), "100");
		assert.equal(convert("двухсот"), "200");
	});
});

describe("textToNumbers: составные суммы", () => {
	it("собирает многозначные числа", () => {
		assert.equal(convert("двадцать пять"), "25");
		assert.equal(convert("сто двадцать три"), "123");
		assert.equal(convert("две тысячи пятьсот"), "2500");
		assert.equal(convert("восемь девятьсот шестнадцать"), "8 916");
	});

	it("родительные формы работают и в суммах", () => {
		// Именно так диктуют: «тридцати тысяч», а не «тридцать тысяч».
		assert.equal(convert("тридцати тысяч"), "30000");
		assert.equal(convert("двадцати тысяч"), "20000");
		assert.equal(convert("двух тысяч пятисот"), "2500");
	});
});

describe("textToNumbers: медицинские слова не превращаются в числа", () => {
	/**
	 * БЫЛО: если точного совпадения нет, начало слова сравнивалось с корнями
	 * числительных по расстоянию Левенштейна. Любое длинное слово с похожим
	 * началом становилось числом. Замерено на словаре из 73 слов: искажались
	 * семь.
	 *
	 * Последствие в медкарте: номер зуба и его состояние определяются по
	 * тексту ПОСЛЕ этой замены, поэтому слова «пульпит», «периодонтит» и
	 * «киста» до проверки состояния не доживали, и зуб получал
	 * «запланировано» вместо «лечение».
	 */
	const terms = [
		"пульпит",
		"пульпита",
		"пульпа",
		"периодонтит",
		"периодонтита",
		"киста",
		"стоматит",
		"кариес",
		"гранулема",
		"коронка",
		"анестезия",
		"перкуссия",
		"экстракция",
		"имплантация",
		"слизистая",
		"седация",
		"резекция",
		"рецессия",
		"штифт",
		"дентин",
	];

	it("оставляет клинические термины как есть", () => {
		for (const term of terms) {
			assert.equal(convert(term), term, `слово «${term}» было искажено`);
		}
	});

	it("в клиническом термине не появляется цифр", () => {
		for (const term of terms) {
			assert.ok(!/\d/.test(convert(term)), `в «${term}» появилась цифра: «${convert(term)}»`);
		}
	});

	it("не портит фразу, где рядом и число, и диагноз", () => {
		assert.equal(convert("36 зуб пульпит"), "36 зуб пульпит");
		assert.equal(convert("45 зуб периодонтит"), "45 зуб периодонтит");
	});
});
