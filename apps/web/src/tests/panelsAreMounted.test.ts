const CENSUS_TIME_CEILING_MS = 60_000;

function readSource(relativePath: string): string {
  return readFileSync(path.join(webSrcRoot, relativePath), "utf8");
}

/**
 * Исходник без комментариев.
 *
 * Проверять возврат мёртвого кода по сырому тексту нельзя, и это не теория:
 * разбор удаления сам называет снятые имена — в надгробном комментарии на месте
 * снятия, — и страж срабатывал бы на собственном объяснении. На этом же
 * промахнулась удалённая проверка сирот из patientCardDecomposition.test.ts: её
 * регулярное выражение совпадало на закомментированной строке.
 *
 * Снимаются блочные комментарии и строки, целиком занятые `//`; хвостовой `//`
 * после кода остаётся — он может дать только ложное СРАБАТЫВАНИЕ, которое видно,
 * а не молчаливый пропуск.
 */
function sourceWithoutComments(relativePath: string): string {
  const stripped = readSource(relativePath)
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/^[ \t]*\/\/.*$/gm, "");
  // Канарейка: если чистка съела код, страж обязан упасть, а не промолчать.
  assert.ok(
    stripped.includes("export"),
    `после снятия комментариев в ${relativePath} не осталось ни одного export — чистка сломана, ` +
      "и проверка на возврат мёртвого кода прошла бы, ничего не проверив",
  );
  return stripped;
}

/**
 * Реестр разделов читается из исходника, а не импортируется: страж обязан
 * работать и тогда, когда workspaceShell.tsx не собирается — именно в такой
 * момент в него и добавляют раздел наугад.
 */
function registeredAppViews(): string[] {
  const source = readSource("workspaceShell.tsx");
  const declaration =
    /export const appViews = \[([^\]]*)\] as const;/.exec(source)?.[1] ?? "";
  assert.ok(
    declaration,
    "В workspaceShell.tsx не найдено объявление `export const appViews = [...] as const;` — " +
      "реестр разделов переехал или переименован, и этот страж больше ничего не охраняет",
  );
  const views = [...declaration.matchAll(/"([^"]+)"/g)].map(
    (match) => match[1] as string,
  );
  assert.ok(
    views.length >= 11,
    `реестр разделов разобран неполно: ${views.length} записей`,
  );
  return views;
}

