import assert from "node:assert/strict";
import { describe, test } from "node:test";

import { transferredMoment } from "./loader.js";

/**
 * ПЕРЕНЕСЁННЫЕ ДЕНЬГИ И ПРИЁМЫ НЕ ПОЛУЧАЮТ ДАТУ ПЕРЕНОСА.
 *
 * ЧТО БЫЛО СЛОМАНО. В загрузчике переноса стояло `?? new Date()` в двух местах:
 * платёж без даты в источнике садился в ДЕНЬ ПЕРЕНОСА, приём — в ВРЕМЯ ИМПОРТА.
 *
 * Цена для клиники. Касса дня переноса раздувалась на всю перенесённую историю:
 * владелец открывал отчёт за этот день и видел выручку, которой не было. В истории
 * пациента появлялось «приём состоялся сегодня», которого сегодня не было. И
 * отличить выдумку от правды было НЕЛЬЗЯ — в базе лежала обычная метка времени.
 *
 * Выдумка на ЗАПИСИ хуже выдумки на чтении: прочитанная исчезает со следующим
 * чтением, записанная становится историей лечения и кассой навсегда.
 *
 * ПОЧЕМУ ПРОВЕРЯЕТСЯ ЧИСТАЯ ФУНКЦИЯ. Тот же приём, что у `migrationTimeZoneFrom`
 * рядом: вся политика «что делать, когда даты нет» вынесена из вставки в отдельную
 * функцию, поэтому её можно запереть тестом БЕЗ базы и без оснастки стейджинга.
 * Проверка не зависит ни от часа прогона, ни от содержимого базы.
 *
 * Что делают с «неизвестно» вызывающие — разное, и это следствие базы, а не
 * непоследовательность: `visits.signed_at` обнуляем, там пишется `null`;
 * `payments.paid_at` объявлен `NOT NULL DEFAULT now()`, и его умолчание — то же
 * «сейчас», поэтому платёж без даты уходит в карантин с названной причиной.
 */

describe("политика переноса для времени", () => {
	test("отсутствие даты — это «неизвестно», а не «сейчас»", () => {
		assert.deepEqual(transferredMoment(null), { known: false });
		assert.deepEqual(transferredMoment(undefined), { known: false });
	});

	test("нечитаемая дата — тоже «неизвестно», и она не бросает исключение", () => {
		// `Invalid Date` приходит от разборщика источника на мусорной строке, а
		// PostgreSQL законно хранит `infinity`. Прежний код на таком значении шёл
		// в `.toISOString()` и бросал `RangeError`: отказ выглядел как поломка
		// приложения, а не как одна кривая строка выгрузки.
		assert.deepEqual(transferredMoment(new Date("не дата")), { known: false });
		assert.deepEqual(transferredMoment(new Date(Number.NaN)), { known: false });
		assert.deepEqual(transferredMoment(new Date(Number.POSITIVE_INFINITY)), { known: false });
	});

	test("известная дата доезжает как есть, до миллисекунды", () => {
		const at = new Date("2019-03-12T11:30:00.000Z");
		const result = transferredMoment(at);
		assert.equal(result.known, true);
		if (!result.known) return;
		assert.equal(result.at.toISOString(), "2019-03-12T11:30:00.000Z");
	});

	test("проверка не выродилась: «известно» и «неизвестно» различимы", () => {
		// Без этого утверждения все проверки выше прошли бы и на функции, которая
		// всегда возвращает `{ known: false }` — то есть на коде, где перенос вообще
		// перестал сохранять даты. Ровно на таком вырождении в этом дереве уже
		// попадались: датчик охвата считался и не сверялся, и обвал охвата с 106
		// функций до 26 проходил при семи зелёных проверках из восьми.
		const known = transferredMoment(new Date("2020-01-01T00:00:00.000Z"));
		const unknown = transferredMoment(null);
		assert.notDeepEqual(known, unknown, "функция отвечает одинаково на дату и на её отсутствие");
	});

	test("дата переноса НЕ подставляется: результат не зависит от «сейчас»", () => {
		// Прямая проверка исходного дефекта. Прежний код на отсутствующей дате
		// возвращал текущий момент, поэтому два вызова подряд давали РАЗНЫЕ
		// значения и оба были близки к «сейчас».
		const first = transferredMoment(null);
		const second = transferredMoment(null);
		assert.deepEqual(first, second, "два вызова подряд дали разное — значит подставляется текущее время");
		assert.equal(
			"at" in first,
			false,
			"на отсутствующей дате вернулся конкретный момент: перенесённая запись сядет в день переноса",
		);
	});
});
