/**
 * patientDebt.ts — ОДИН дом для вопроса «сколько пациент должен клинике».
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ЗАЧЕМ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * До него долг считался в ДЕВЯТИ местах, и они давали разные ответы на одних и
 * тех же данных. Измерено 2026-07-29 прямым SQL к живой базе `dental_crm`,
 * клиника `d0000000-…-00000000d001`, 10 позиций лечения и 8 оплат:
 *
 *   отчёт дебиторки  (managerReports.ts, receivables)     →  53 000,00 ₽
 *   главный экран    (sampleData.ts, buildBillingSummary)  →  51 400,00 ₽
 *   картотека        (patientsQuery.ts, rowToPatient)      →       0,00 ₽
 *
 * Разница между первыми двумя — ровно 1 600,00 ₽, это две переплаты по 800,00 ₽.
 * Главный экран вычитает оплаченное из назначенного ПО ВСЕЙ КЛИНИКЕ одним
 * действием, поэтому переплата одного пациента молча гасит долг другого. Третий
 * ответ — константа `0`, не связанная с данными вообще.
 *
 * Что это значит для клиники, а не для кода: администратор открывает отчёт
 * дебиторки, звонит пациенту и называет сумму, которой нет на главном экране;
 * оператор видит два разных долга на двух экранах и не знает, какому верить; два
 * пациента, переплатившие по 800 ₽, не видны ни в одном отчёте, и клиника не
 * знает, что должна им деньги.
 *
 * Полный разбор всех девяти мест с числами, вердиктами и порядком переезда:
 * `.agents/lead/recon-debt-formula-sprawl.md`.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * ЧТО ЭТОТ ФАЙЛ НЕ ДЕЛАЕТ: ВТОРОЙ РЕАЛИЗАЦИИ ДЕНЕГ ЗДЕСЬ НЕТ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Копейки, разбор строки колонки `numeric`, сложение, умножение на количество и
 * печать суммы живут в ОДНОМ месте на весь репозиторий —
 * `packages/shared/src/utils/money.ts` — и берутся отсюда импортом. Правило это
 * не моё: оно уже записано в `apps/api/src/documents/guards.ts` словами
 * «Считать деньги здесь теперь нечем, кроме `packages/shared/src/utils/money.ts`;
 * третьей копии не создаётся», после того как вторую копию в этом дереве нашли
 * дважды и одна из них отказывала законной квитанции.
 *
 * ЧЕСТНО О СВОЕЙ ОШИБКЕ: первую версию этого файла я написал с собственным
 * разбором копеек, не найдя существующий модуль — то есть ровно та болезнь, от
 * которой лечит этот файл, и первым её носителем оказался я. Переписано до
 * коммита. Здесь остался ТОЛЬКО слой долга: чем этот слой отличается от общего,
 * сказано ниже поимённо, и каждое отличие сужает поведение, а не меняет его.
 *
 * ОТЛИЧИЕ 1. `parseKopecks` на НЕЦЕЛОМ ЧИСЛЕ округляет через `toFixed(2)` — по
 * замыслу, как «то, что записалось бы в numeric(12, 2)». Для общего разбора это
 * верно, для расчёта долга — нет: так `1500.505` молча становится `1500.51`, а
 * `4500.299999999999` (это `1500.10 * 3` в плавающей точке) молча становится
 * `4500.30`. Расчёт долга обязан УЗНАТЬ, что кто-то уже посчитал деньги в
 * плавающей точке, а не подтвердить это своей подписью. Поэтому здесь вход из
 * числа проходит через `kopecksFromRubles`, который такие значения ОТВЕРГАЕТ. На
 * чистых суммах поведение побитово совпадает с `parseKopecks`; расходятся они
 * только на грязи, и там громкий отказ честнее тихого округления.
 *
 * ОТЛИЧИЕ 2. `parseKopecks(null)` и `parseKopecks("")` законно дают 0. Здесь
 * отсутствующая цена — отказ: «сумма не пришла» и «лечение бесплатное» это разные
 * факты, а колонки `unit_price_rub`, `discount_rub` и `amount_rub` объявлены
 * `not null`, поэтому пустое значение означает поломку чтения, а не ноль.
 *
 * ОТЛИЧИЕ 3. `multiplyKopecks` разрешает количество 0. Здесь ноль — отказ:
 * позицию без объёма надо помечать статусом `cancelled`, а не выставлять счёт.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * КАКАЯ ФОРМУЛА БЫЛА КАНОНИЧЕСКОЙ И ПОЧЕМУ ОСТАЛЬНЫЕ ЕЙ НЕ РАВНЫ
 *
 * Это ЕДИНСТВЕННОЕ место в проекте, где причина записана. Не удаляй её вместе с
 * рефакторингом: без неё следующий агент выберет формулу заново, и их снова
 * станет девять.
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * КАНОН — выражение из отчёта дебиторки, `apps/api/src/services/reports/
 * managerReports.ts`, `receivables()`:
 *
 *     строка позиции = greatest(unit_price_rub * quantity - discount_rub, 0)
 *     сальдо пациента = Σ строк(status <> 'cancelled') - Σ оплат(status = 'paid')
 *     дебиторка клиники = Σ сальдо по пациентам, у которых сальдо >= порога
 *
 * Канон выбран не по вкусу, а по пяти проверяемым признакам:
 *
 *  1. Считает ПО ПАЦИЕНТУ. Долг — величина человека, а не клиники: клиника не
 *     «должна себе». Именно поэтому агрегат по всей клинике (главный экран) не
 *     может быть каноном — он теряет то, ради чего долг вообще считают, то есть
 *     кому звонить.
 *  2. Не смешивает переплату одного с долгом другого. Деньги пациента А не
 *     гасят обязательство пациента Б ни юридически, ни бухгалтерски.
 *  3. Арифметика точная: суммирование идёт в `numeric` на стороне PostgreSQL,
 *     приведение `::numeric(12,2)` стоит на уровне суммы, копейки не теряются.
 *  4. `greatest(…, 0)` на СТРОКЕ не даёт отрицательной позиции (скидка больше
 *     цены) тайно уменьшить долг по другим позициям того же пациента.
 *  5. Отчёт САМ печатает свою несходимость с главным экраном
 *     («53 000,00 − 1 600,00 = 51 400,00 ₽»), то есть его автор уже знал, что
 *     второй ответ существует, и назвал разницу. Остальные восемь мест молчат.
 *
 * ПОЧЕМУ ОСТАЛЬНЫЕ ЕМУ НЕ РАВНЫ — по одной причине на каждое:
 *
 *  • `sampleData.ts:1349` `buildBillingSummary().totalDueRub` = 51 400,00.
 *    НЕ равно, потому что считает НЕТТО ПО КЛИНИКЕ: `Σназначено − Σоплачено`
 *    одним вычитанием. Это законная бухгалтерская величина («сколько ещё не
 *    собрано»), но она отвечает на другой вопрос, а называется долгом. Здесь
 *    она называется `netUncollectedKopecks`.
 *
 *  • `sampleData_opt.ts:1087` — тот же расчёт БЕЗ единого округления. Мёртвый:
 *    ноль импортов, исключён из `apps/api/tsconfig.json` и `tsconfig.tests.json`.
 *    Опасен не тем, что работает, а тем, что `rg buildBillingSummary` находит две
 *    реализации, и половина шансов, что правку внесут в мёртвую. Подлежит
 *    удалению отдельным коммитом.
 *
 *  • `domainStateHydration.ts:546` `patient.balanceRub` = `Math.round(оплачено −
 *    назначено)`. НЕ равно по двум причинам: обратный знак и ОКРУГЛЕНИЕ ДО
 *    ЦЕЛОГО РУБЛЯ. Округление несимметрично: `Math.round(-49899.5) = -49899`, а
 *    `Math.round(49899.5) = 49900` — должнику 50 копеек прощают, переплатившему
 *    приписывают. Контракт копейки уже разрешил (`moneyRubSchema`), а этот
 *    `Math.round` остался на месте.
 *
 *  • `patientsQuery.ts:67` `balanceRub: 0`. НЕ равно, потому что это не формула,
 *    а константа: на семи живых пациентах с ненулевым сальдо отвечает `0` семь
 *    раз из семи.
 *
 *  • `sampleData.ts:1720` `patientInsight.balanceDueRub`. Формула та же, но
 *    позиции берутся БЕЗ фильтра `status !== "cancelled"` — отменённое лечение
 *    продолжает висеть на пациенте долгом ровно там, где администратор читает
 *    сумму перед звонком.
 *
 *  • `sampleData.ts:8575` `patientPaymentBalanceRub`. Формула та же, но без
 *    округления, и её результат уходит в ключ идемпотентности напоминания
 *    округлённым до рубля (`:8548`). Доплата 40 копеек ключ не меняет, значит
 *    второе напоминание не уйдёт никогда.
 *
 *  • `(цена − скидка) × количество` вместо `цена × количество − скидка`. НЕ равно
 *    на величину `скидка × (кол-во − 1)`: на живых строках со скидкой 800 ₽ при
 *    количестве 2 это 1 600,00 ₽. Скидка в этом проекте задана строкой позиции
 *    (`treatment_items.discount_rub`, `numeric(12,2)` — `db/schema.ts`), а не
 *    ценой за единицу, поэтому вычитать её надо ОДИН раз из итога строки.
 *    ФАЙЛОВ С ЭТОЙ ФОРМУЛОЙ В ДЕРЕВЕ БОЛЬШЕ НЕТ: их было два,
 *    `apps/api/src/treatment/TreatmentPlanBuilder.ts` и его дословная копия в
 *    корне репозитория `full_treatment_plan.ts`, оба с нулём импортёров, оба
 *    удалены 2026-08-05/06. Ссылаться на них здесь больше нельзя, а довод выше
 *    от их удаления не изменился: он держится на колонке, а не на файле.
 *    Сама разность закреплена прогоняемым тестом (`patientDebt.test.ts`,
 *    «расхождение равно скидка × (количество − 1) на любом количестве»), поэтому
 *    она проверяется, а не только описывается.
 *
 *  • `useAppLogic.tsx:5171` (веб) вычитает ещё и страховое покрытие под тем же
 *    именем поля `totalDueRub`. Это ШЕСТАЯ величина («к оплате пациентом после
 *    страховки»), а не шестая формула долга, и в этот модуль она не входит:
 *    сервер данных договора ДМС в сводку не отдаёт вовсе.
 *
 * ГДЕ МОЙ МОДУЛЬ СОЗНАТЕЛЬНО ОТСТУПАЛ ОТ КАНОНА — И ПОЧЕМУ ОТСТУПАТЬ БОЛЬШЕ НЕ
 * ОТ ЧЕГО. Отступление было одно: канон в SQL писал `greatest(quantity, 1)`, а
 * `domainStateHydration` ещё и `Math.round(quantity)`. Оба — тихие правки данных,
 * и здесь вместо них стоит отказ. К 2026-08-06 обе тихие правки из дерева ушли:
 * `domainStateHydration` удалён вместе со своим `Math.round`, а
 * `greatest(quantity, 1)` убран из `services/reports/managerReports.ts` (три
 * места) и из `services/communications/audience.ts` — разбор стоит в первом из
 * них. Больше того, с миграции 0162 количество не может нарушить контракт даже
 * прямым SQL: у колонки есть ограничения `quantity > 0` и
 * `quantity = trunc(quantity)`.
 *
 * Требование этого модуля не изменилось и не смягчается: количество обязано
 * прийти целым положительным, ровно как объявлено в общем контракте
 * (`packages/shared/src/index.ts:1819`, `quantity: z.number().int().positive()`),
 * иначе выбрасывается исключение. Проверка остаётся, потому что ограничение базы
 * ловит не всё: колонка `numeric(10, 2)` приводит вход к двум знакам ДО проверки,
 * поэтому `1.004` дойдёт до расчёта как `1.00`, а контракт такое число отвергает.
 * На контрактно верных данных все поведения совпадают побитово (проверено: в
 * живой базе `min(quantity) = max(quantity) = 1.00`, дробных нет).
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * КОПЕЙКИ: ПОЧЕМУ ВНУТРИ НЕТ НИ ОДНОГО РУБЛЯ В ПЛАВАЮЩЕЙ ТОЧКЕ
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Деньги приходят из колонок `numeric(12,2)` и обязаны уйти обратно теми же.
 * Плавающая точка этого не гарантирует, и это измерено, а не предположено:
 *
 *     1500.10 * 3                  → 4500.299999999999
 *     1000.00 + 1001.82 + 1489.67  → 3491.4900000000002
 *     0.1 + 0.2                    → 0.30000000000000004
 *
 * `3491.4900000000002` — это ПРОВАЛ, а не «то же самое, что 3491,49». Такая
 * сумма не проходит `moneyRubSchema` (третий знак после запятой отвергается,
 * `packages/shared/src/tests/money-contract-kopecks.test.ts`), то есть маршрут
 * ответит ошибкой на верных данных, а если и пройдёт — колонка `numeric(12,2)`
 * молча обрежет её, и на руках у пациента и в базе окажутся разные суммы.
 *
 * Поэтому здесь нет ни одного сложения рублей. Всё внутри — целые копейки
 * (`Kopecks` из общего модуля), точные до 2^53 копеек ≈ 9·10^13 ₽, что на семь
 * порядков выше предела колонки `numeric(12,2)`.
 */


