/**
 * Распознавание отказа от сообщений во входящем тексте.
 *
 * ЗАЧЕМ: пациент отвечает «СТОП», и на этом обязанность клиники прекратить
 * рассылку возникает сразу. В проекте входящие сообщения вообще не читались:
 * services/messengerIngestion.ts ниоткуда не вызывался, а таблица согласий
 * заполнялась только руками администратора. То есть отказаться от рассылки
 * пациент не мог никак, кроме звонка в клинику.
 *
 * ЦЕНА ОШИБКИ В ОБЕ СТОРОНЫ
 *   • пропустить отказ — жалоба и штраф;
 *   • отписать лишнего — человек не получит напоминание и не придёт на приём.
 *
 * Поэтому отказом считается только короткое сообщение, целиком состоящее из
 * стоп-слова или начинающееся с него. «Стоп, а во сколько приём?» — это
 * вопрос, а не отказ, и такое сообщение проходит к администратору.
 */

export type OptOutIntent = "opt_out" | "opt_in" | null;

/** Слова отказа. Дополнять можно, но каждое должно быть однозначным. */
const OPT_OUT_TOKENS = [
	"стоп",
	"stop",
	"отписаться",
	"отписка",
	"отпишите",
	"отписать",
	"отказ",
	"отказаться",
	"unsubscribe",
	"прекратите",
	"прекратить"
];

/** Слова возврата к рассылке. */
const OPT_IN_TOKENS = ["старт", "start", "подписаться", "подписка", "подпишите", "subscribe", "возобновить"];

/** Многословные выражения отказа, которые ловятся целиком. */
const OPT_OUT_PHRASES = [
	"не писать",
	"не пишите",
	"больше не пишите",
	"не присылайте",
	"не присылать",
	"больше не присылайте",
	"отказываюсь от рассылки",
	"уберите меня из рассылки",
	"удалите меня из рассылки"
];

/**
 * Убирает знаки, лишние пробелы и приводит к нижнему регистру. «ё» сводится к
 * «е»: пациент напишет и так, и так.
 */
function normalize(text: string): string {
	return text
		.toLowerCase()
		.replace(/ё/g, "е")
		.replace(/[^\p{L}\p{N}\s]+/gu, " ")
		.replace(/\s+/g, " ")
		.trim();
}

/** Не больше трёх слов — иначе это уже фраза, а не команда. */
const MAX_COMMAND_WORDS = 3;

export function detectOptOutIntent(rawText: string | null | undefined): OptOutIntent {
	const text = normalize(rawText ?? "");
	if (!text) return null;

	for (const phrase of OPT_OUT_PHRASES) {
		if (text === phrase || text.startsWith(`${phrase} `)) return "opt_out";
	}

	const words = text.split(" ");
	if (words.length > MAX_COMMAND_WORDS) return null;

	// Короткое сообщение: достаточно, чтобы стоп-слово стояло первым. «стоп
	// рассылку», «стоп смс» — это отказ; «во сколько приём» — нет.
	const first = words[0] ?? "";
	if (OPT_OUT_TOKENS.includes(first)) return "opt_out";
	if (OPT_IN_TOKENS.includes(first)) return "opt_in";

	// Односложное сообщение целиком совпадает со словом — самый частый случай.
	if (words.length === 1) {
		if (OPT_OUT_TOKENS.includes(text)) return "opt_out";
		if (OPT_IN_TOKENS.includes(text)) return "opt_in";
	}

	return null;
}

/** Текст ответа пациенту. Молчаливая отписка выглядит как игнорирование. */
export function optOutAcknowledgement(intent: Exclude<OptOutIntent, null>, clinicName: string): string {
	if (intent === "opt_out") {
		return (
			`${clinicName}: вы отписаны от сообщений по этому каналу. ` +
			"Напоминания о приёме больше не придут — если понадобится, позвоните в клинику или напишите «СТАРТ»."
		);
	}
	return `${clinicName}: рассылка возобновлена. Напоминания о приёме будут приходить по этому каналу.`;
}
