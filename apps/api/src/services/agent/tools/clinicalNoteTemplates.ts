/**
 * Returns note templates filtered by category, or all templates if category is omitted.
 */
export function listNoteTemplates(category?: string): NoteTemplate[] {
	const all = Object.values(CLINICAL_NOTE_TEMPLATES);
	if (!category || category === "all") {
		return all;
	}
	const normalizedCat = category.toLowerCase().trim();
	return all.filter((tpl) => tpl.category.toLowerCase() === normalizedCat);
}

/**
 * Finds a specific template by its unique ID.
 */
export function findNoteTemplateById(id: string): NoteTemplate | undefined {
	return CLINICAL_NOTE_TEMPLATES[id];
}
