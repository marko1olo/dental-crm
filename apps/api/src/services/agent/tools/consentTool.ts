// ─── RESULT INTERFACES ────────────────────────────────────────────────────

export interface InformedConsentSection {
	readonly number: number;
	readonly title: string;
	readonly content: string;
}

export interface GenerateInformedConsentResult {
	readonly success: boolean;
	readonly documentId: string;
	readonly patientId: string;
	readonly patientName: string;
	readonly procedureType: ConsentProcedureType;
	readonly procedureTitle: string;
	readonly toothOrArea: string;
	readonly doctorName: string;
	readonly signatureSha256: string;
	readonly legalText: string;
	readonly sections: InformedConsentSection[];
	readonly createdAt: string;
}

// ─── TOOL DEFINITION ────────────────────────────────────────────────────────

export const generateInformedConsentTool: ToolDefinition<
	typeof generateInformedConsentSchema,
	GenerateInformedConsentResult
> = {
	name: "generate_informed_consent",
	description:
		"Генерация полного юридического текста Информированного Добровольного Согласия (ИДС) по ст. 20 323-ФЗ и Приказу Минздрава № 1051н с детальными рисками, показаниями, альтернативами, рекомендациями и криптографическим хэшем подписи SHA-256.",
	parameters: generateInformedConsentSchema,
	permissions: ["clinical.write", "clinical.read"],
	category: "write",
	handler: async (ctx, args) => {
		const targetDb = ctx.db ?? db;

		// 1. Fetch patient
		const [patient] = await targetDb
			.select({
				id: patients.id,
				fullName: patients.fullName,
				birthDate: patients.birthDate,
				phone: patients.phone,
			})
			.from(patients)
			.where(
				and(
					eq(patients.organizationId, ctx.organizationId),
					eq(patients.id, args.patientId),
				),
			)
			.limit(1);

		if (!patient) {
			throw new Error(`Пациент с ID ${args.patientId} не найден`);
		}

		// 2. Fetch known patient allergies to integrate into risk profile
		const allergies = await targetDb
			.select({
				allergenGroup: patientDrugAllergies.allergenGroup,
				drugInnLatin: patientDrugAllergies.drugInnLatin,
				reactionSeverity: patientDrugAllergies.reactionSeverity,
			})
			.from(patientDrugAllergies)
			.where(
				and(
					eq(patientDrugAllergies.organizationId, ctx.organizationId),
					eq(patientDrugAllergies.patientId, args.patientId),
				),
			);

		const preset = CONSENT_PROCEDURE_PRESETS[args.procedureType];
		const toothStr = args.toothCode ? `Зуб/зона: ${args.toothCode}` : "Полость рта / зубной ряд";

		// Combine preset risks with patient allergies and custom risks
		const allRisks = [...preset.specificRisks];
		if (allergies.length > 0) {
			const allergyStr = allergies
				.map((a) => `${a.allergenGroup || a.drugInnLatin || "Непереносимость"} (${a.reactionSeverity || "умеренная"})`)
				.join(", ");
			allRisks.push(`Особый аллергологический статус пациента в анамнезе: ${allergyStr}`);
		}
		if (args.customRisks && args.customRisks.length > 0) {
			for (const r of args.customRisks) {
				allRisks.push(r);
			}
		}

		const trustedContactText = args.trustedContact
			? args.trustedContact
			: "Сведения о состоянии здоровья третьим лицам не передавать (за исключением случаев, предусмотренных ч. 4 ст. 13 323-ФЗ)";

		const currentDateStr = new Date().toLocaleDateString("ru-RU", {
			day: "2-digit",
			month: "2-digit",
			year: "numeric",
		});

		// 3. Build Structured Sections according to Art. 20 323-FZ & Order 1051n
		const sections: InformedConsentSection[] = [
			{
				number: 1,
				title: "Сведения о пациенте, лечащем враче и планируемом медицинском вмешательстве",
				content: [
					`Пациент: ${patient.fullName} (д.р. ${patient.birthDate || "—"}), тел.: ${patient.phone || "—"}.`,
					`Лечащий врач, проводивший очное разъяснение: ${args.doctorName}.`,
					`Вид медицинского вмешательства: ${preset.titleRu}.`,
					`Анатомическая область / локализация: ${toothStr}.`,
					`Клинические показания: ${preset.diagnosisOrIndication}.`,
					`Планируемое обезболивание: ${preset.plannedAnesthesia}.`,
					`Материалы и технологии: ${preset.materialsAndMethods}.`,
				].join("\n"),
			},
			{
				number: 2,
				title: "Цели вмешательства и ожидаемые результаты",
				content:
					"Целью медицинского вмешательства является купирование болевого синдрома и воспалительного процесса, восстановление анатомической формы, жевательной функции и эстетики зубочелюстной системы, предотвращение дальнейшего разрушения твердых тканей и распространения инфекции.",
			},
			{
				number: 3,
				title: "Разъясненные риски, возможные осложнения и побочные эффекты",
				content: [
					"Пациенту в доступной форме подробно разъяснены вероятные риски и возможные индивидуальные осложнения:",
					...allRisks.map((r, i) => `  ${i + 1}. ${r}`),
				].join("\n"),
			},
			{
				number: 4,
				title: "Альтернативные методы лечения и последствия отказа",
				content: [
					"Пациенту разъяснены альтернативные методы лечения и их сравнительная клиническая эффективность:",
					...preset.alternatives.map((a, i) => `  ${i + 1}. ${a}`),
					"Пациент предупрежден, что отказ от своевременного медицинского вмешательства может привести к прогрессированию патологического процесса, потере зуба, развитию гнойно-воспалительных осложнений челюстно-лицевой области.",
				].join("\n"),
			},
			{
				number: 5,
				title: "Режим и предписания после проведенного вмешательства",
				content: [
					"Пациент обязуется строго соблюдать предписания лечащего врача и правила гигиены:",
					...preset.aftercareRequirements.map((req, i) => `  ${i + 1}. ${req}`),
				].join("\n"),
			},
			{
				number: 6,
				title: "Сведения о доверенных лицах (ч. 3 ст. 13 Федерального закона № 323-ФЗ)",
				content: `В соответствии с частью 3 статьи 13 Федерального закона № 323-ФЗ пациент доверяет передачу сведений о диагнозе, состоянии здоровья и результатах лечения следующим лицам: ${trustedContactText}.`,
			},
			{
				number: 7,
				title: "Информированное волеизъявление и юридические подтверждения",
				content: [
					"1. Пациент подтверждает, что сообщил лечащему врачу полные и достоверные сведения о перенесенных и сопутствующих заболеваниях, аллергических реакциях и принимаемых лекарствах.",
					"2. Пациент получил исчерпывающие и понятные ответы на все интересующие вопросы, связанные с предстоящим лечением.",
					"3. Пациент проинформирован о праве отказаться от медицинского вмешательства или потребовать его прекращения на любом этапе в соответствии с ч. 3 ст. 20 Федерального закона № 323-ФЗ.",
					"4. Пациент добровольно дает свое согласие на проведение указанного медицинского вмешательства.",
				].join("\n"),
			},
		];

		// 4. Render Full Legal Document Text
		const legalText = [
			"═══════════════════════════════════════════════════════════════════════════════",
			" ИНФОРМИРОВАННОЕ ДОБРОВОЛЬНОЕ СОГЛАСИЕ НА МЕДИЦИНСКОЕ ВМЕШАТЕЛЬСТВО",
			" (в соответствии со ст. 20 Федерального закона от 21.11.2011 № 323-ФЗ",
			"  и Приказом Министерства здравоохранения РФ от 12.11.2021 № 1051н)",
			"═══════════════════════════════════════════════════════════════════════════════",
			`Дата оформления: ${currentDateStr}`,
			"",
			...sections.flatMap((s) => [
				`РАЗДЕЛ ${s.number}. ${s.title.toUpperCase()}`,
				"─────────────────────────────────────────────────────────────────────────────",
				s.content,
				"",
			]),
			"ПОДПИСИ СТОРОН:",
			`Пациент / Законный представитель: ___________________ / ${patient.fullName} /`,
			`Лечащий врач: ___________________ / ${args.doctorName} /`,
			"═══════════════════════════════════════════════════════════════════════════════",
		].join("\n");

		// 5. Canonical JSON Payload for Cryptographic Hash
		const canonicalPayload = {
			law: "323-FZ-Art-20",
			order: "Minzdrav-1051n",
			organizationId: ctx.organizationId,
			patientId: patient.id,
			patientFullName: patient.fullName,
			patientBirthDate: patient.birthDate,
			doctorFullName: args.doctorName,
			procedureType: args.procedureType,
			procedureTitle: preset.titleRu,
			toothOrArea: toothStr,
			indications: preset.diagnosisOrIndication,
			plannedAnesthesia: preset.plannedAnesthesia,
			materials: preset.materialsAndMethods,
			risks: allRisks,
			alternatives: preset.alternatives,
			aftercare: preset.aftercareRequirements,
			trustedContact: trustedContactText,
			createdAt: new Date().toISOString(),
		};

		const normalizedJson = JSON.stringify(
			canonicalPayload,
			Object.keys(canonicalPayload).sort(),
		);
		const signatureSha256 = createHash("sha256")
			.update(normalizedJson, "utf8")
			.digest("hex");

		// 6. Persist generated consent into generatedDocuments table
		const [createdDoc] = await targetDb
			.insert(generatedDocuments)
			.values({
				organizationId: ctx.organizationId,
				patientId: args.patientId,
				kind: "informed_consent",
				status: "draft",
				title: `ИДС: ${preset.titleRu} (${toothStr})`,
				payloadJson: JSON.stringify(canonicalPayload),
				issuedSnapshotSha256: signatureSha256,
				issuedSnapshotCreatedAt: new Date(),
			})
			.returning({
				id: generatedDocuments.id,
				createdAt: generatedDocuments.createdAt,
			});

		return {
			success: true,
			documentId: createdDoc.id,
			patientId: patient.id,
			patientName: patient.fullName,
			procedureType: args.procedureType,
			procedureTitle: preset.titleRu,
			toothOrArea: toothStr,
			doctorName: args.doctorName,
			signatureSha256,
			legalText,
			sections,
			createdAt: createdDoc.createdAt.toISOString(),
		};
	},
};
