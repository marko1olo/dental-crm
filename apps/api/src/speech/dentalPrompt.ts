function promptEnabled(): boolean {
	const value = (process.env.DENTAL_STT_DENTAL_PROMPT ?? "on")
		.trim()
		.toLowerCase();
	return !["0", "off", "false", "no"].includes(value);
}

function maxPromptChars(): number {
	return Math.max(
		220,
		Math.min(numberFromEnv("DENTAL_STT_PROMPT_MAX_CHARS", 1100), 1800),
	);
}

function customTerms(): string[] {
	return (process.env.DENTAL_STT_CUSTOM_TERMS ?? "")
		.split(/[,\n;]/)
		.map((term) => term.trim())
		.filter(Boolean)
		.slice(0, 40);
}

function uniqueTerms(values: readonly string[]): string[] {
	return Array.from(
		new Set(values.map((value) => value.trim()).filter(Boolean)),
	);
}

function promptTermsForSpecialty(specialty: DentalSpecialty): string[] {
	const criticalBaseTerms = baseTerms.slice(0, 40);
	const specialtyList = specialtyTerms[specialty] ?? specialtyTerms.universal;
	return uniqueTerms([
		...criticalBaseTerms,
		...specialtyList,
		...customTerms(),
		...baseTerms.slice(40),
	]).slice(0, 72);
}

function _sourceHint(source: SpeechTranscriptionSource): string {
	if (source === "visit") return "Диктовка приема у кресла.";
	if (source === "import") return "Административная диктовка для импорта.";
	if (source === "document") return "Диктовка для черновика документа.";
	return "Тестовая диктовка в настройках.";
}

function trimPrompt(value: string, maxBytes: number): string {
	if (Buffer.byteLength(value, "utf8") <= maxBytes) return value;

	let end = value.length;
	while (end > 0 && Buffer.byteLength(value.slice(0, end), "utf8") > maxBytes) {
		end--;
	}

	const clipped = value.slice(0, end);
	const lastComma = clipped.lastIndexOf(",");
	if (lastComma > 0) {
		return `${clipped.slice(0, lastComma).trimEnd()}.`;
	}
	return `${clipped.trimEnd()}.`;
}

export function buildDentalSttPrompt(input: {
	providerId: SpeechProviderKind;
	specialty?: DentalSpecialty | null;
	source?: SpeechTranscriptionSource | null;
}): string | null {
	if (!promptEnabled() || !promptProviders.includes(input.providerId))
		return null;
	const specialty = input.specialty ?? "universal";
	const terms = promptTermsForSpecialty(specialty);
	const prompt = `Стоматологическая терминология DENTE, зубная формула FDI: ${terms.join(", ")}.`;

	const providerMax =
		input.providerId === "groq_whisper" ? 850 : maxPromptChars();
	return trimPrompt(prompt, providerMax);
}

export function getDentalSttPromptPolicy(): SpeechSttPromptPolicy {
	const terms = uniqueTerms([...baseTerms, ...customTerms()]);
	const promptPreview =
		buildDentalSttPrompt({
			providerId: "groq_whisper",
			specialty: "universal",
			source: "visit",
		}) ?? "Стоматологический словарь распознавания выключен.";
	const warnings: string[] = [];
	if (!promptEnabled())
		warnings.push(
			"Стоматологический словарь распознавания выключен в серверных настройках.",
		);
	if (customTerms().length)
		warnings.push(
			"К стандартному словарю распознавания добавлены термины клиники из серверных настроек.",
		);

	return {
		enabled: promptEnabled(),
		version: promptVersion,
		appliesTo: promptProviders,
		maxChars: maxPromptChars(),
		termCount: terms.length,
		promptPreview,
		warnings,
	};
}

