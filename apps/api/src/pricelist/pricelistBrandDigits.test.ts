import { describe, test } from "node:test";
import assert from "node:assert/strict";
import type { ServiceCatalogItem } from "@dental/shared";
import { analyzePricelist } from "./analyzer.js";

/**
 * Код модели с цифрой ценой услуги НЕ является — а цена рядом с ним обязана
 * читаться.
 *
 * ЧТО БЫЛО СЛОМАНО. Бренд с цифрой в названии стоит в русском стоматологическом
 * прайсе повсеместно: Filtek Z550 и Z250, Osstem TS3, Zoom 4, Damon Q, Nobel
 * Active 3.0, IPS e.max. Сканер цены разбирал такие строки двумя разными
 * способами, и оба были неверны:
 *   • разрядная альтернатива склеивала хвост модели с началом цены —
 *     «Пломба Filtek Z550 3500» давала 550 350 ₽ (переплата в 157 раз),
 *     «Отбеливание Zoom 4 25000» — 4 250 ₽, «Имплантация Osstem TS3 45000» —
 *     3 450 ₽, и предупреждения не было ни одного;
 *   • после запрета неполной разрядной группировки хвост модели стал отдельным
 *     кандидатом: «550» из «Z550» расходилось с настоящими «3500», строка
 *     объявлялась неоднозначной и приезжала в каталог БЕЗ цены.
 * Оба исхода доезжают из прайса в план лечения, а оттуда в документ, который
 * подписывает пациент.
 *
 * ЧЕМ ЗАКРЫТО. Приклеенность числа к букве слева — понижение кандидата в ранге, а
 * не запрет: приклеенный кандидат выбрасывается ТОЛЬКО когда в строке есть
 * отдельно стоящий. Жёсткий запрет здесь неверен, и это измерено: он уносит цену
 * из «Осмотр1500» и «от12000 до 18000», которые читались верно. Отличить «Z550»
 * от «Осмотр1500» ни регистром, ни длиной слова нельзя — прайс пишет названия
 * капслоком, а «КТ», «ОПТГ», «ТРГ» — короткие заглавные аббревиатуры настоящих
 * услуг.
 *
 * Каждая строка ниже проверена на живом разборщике. При откате правки набор
 * падает на первом же бренде.
 */

/** Каталог не нужен: проверяется выбор цены, а не сопоставление с услугой. */
const EMPTY_CATALOG: ServiceCatalogItem[] = [];

async function itemOf(line: string) {
	const response = await analyzePricelist(
		{
			sourceName: "brand-digits-test",
			sourceKind: "text",
			rawText: line,
			imageMimeType: "image/jpeg",
			preferredSpecialty: "universal",
			useServerAi: false,
		},
		EMPTY_CATALOG,
	);
	const item = response.items[0];
	assert.ok(item, `строка «${line}» не разобралась ни в одну позицию прайса`);
	return item;
}

describe("цифра в коде модели ценой не становится", () => {
	test("латинский бренд с цифрой не отнимает цену у строки", async () => {
		for (const [line, expectedPrice] of [
			// Трёхзначный хвост, проходящий нижнюю границу цены в 300 ₽, — тот самый
			// случай, из-за которого строка теряла цену целиком.
			["Пломба Filtek Z550 3500", 3500],
			["Пломба Filtek Z550 3500 руб", 3500],
			["Скайс Swarovski XL500 2500", 2500],
			// Четырёхзначный хвост: запрета слева на одной позиции здесь не хватает,
			// сканер сдвинулся бы на цифру правее и взял ценой «500».
			["Пломба Filtek Z5500 3500", 3500],
			// Хвост ниже 300 ₽ ценой не проходил и до правки — форма обязана остаться целой.
			["Пломба Filtek Z250 2900", 2900],
			["Штифт RelyX U-200 1200", 1200],
			// Дефис и точка внутри кода модели — часть склейки, а не разделитель.
			["Штифт RelyX U-550 1200", 1200],
			["Имплантация Osstem TS-3 45000", 45000],
			["Коронка IPS e.max 2 18000", 18000],
			["Имплант Nobel Active 3.0 52000", 52000],
			// Формы, на которых склейка разрядов занижала цену в 6 и 13 раз.
			["Отбеливание Zoom 4 25000", 25000],
			["Имплантация Osstem TS3 45000", 45000],
			["Брекеты Damon Q 38000", 38000],
		] as const) {
			const item = await itemOf(line);
			assert.equal(item.priceRub, expectedPrice, `ценой стал хвост кода модели (строка «${line}»)`);
			assert.equal(item.priceMaxRub, null, `выдуман диапазон (строка «${line}»)`);
			assert.ok(!item.warnings.includes("price_not_found"), `цена не прочитана (строка «${line}»)`);
		}
	});

	test("кириллический бренд с цифрой закрыт вместе с латинским", async () => {
		// Запрет, знающий только латиницу, оставил бы половину прайса сломанной:
		// оттенки по Vita и русские марки материалов пишут кириллицей.
		for (const [line, expectedPrice] of [
			["Цемент РЦ550 1400", 1400],
			["Слепок Спидекс400 2200", 2200],
			["Реставрация оттенок А2 4500", 4500],
			["Коронка цирконий Т3 21000", 21000],
		] as const) {
			const item = await itemOf(line);
			assert.equal(item.priceRub, expectedPrice, `ценой стал хвост кода модели (строка «${line}»)`);
		}
	});

	test("копейки и разряды цены рядом с кодом модели остаются целы", async () => {
		const withKopecks = await itemOf("Пломба Filtek Z550 3500,50");
		assert.equal(withKopecks.priceRub, 3500.5, "копейки цены потеряны рядом с кодом модели");

		const withGroups = await itemOf("Пломба Filtek Z550 12 500");
		assert.equal(withGroups.priceRub, 12500, "разряды цены потеряны рядом с кодом модели");
	});

	test("код модели остаётся в названии услуги", async () => {
		// Ценой хвост модели не стал, значит вырезать его из названия нечем:
		// вырезается РОВНО прочитанная цена (stripPriceFromTitle). Название уходит
		// в каталог, в план лечения и в подписываемый пациентом документ, а без
		// «Z550» врач не знает, какой материал он продаёт.
		const item = await itemOf("Пломба Filtek Z550 3500");
		assert.equal(item.title, "Пломба Filtek Z550", `название разрушено: «${item.title}»`);

		const zoom = await itemOf("Отбеливание Zoom 4 25000");
		assert.equal(zoom.title, "Отбеливание Zoom 4", `название разрушено: «${zoom.title}»`);
	});
});

describe("понижение в ранге не превращается в запрет", () => {
	test("цена, приклеенная к названию услуги, читается по-прежнему", async () => {
		/*
		 * ГЛАВНЫЙ РИСК ЭТОГО ПРАВИЛА. Приклеенное к букве число — единственный
		 * кандидат в этих строках, и жёсткий запрет слева (lookbehind в
		 * amountPattern или гашение в notMoneyPatterns) оставил бы их без цены.
		 * Пробел между названием и ценой теряется при выгрузке прайса из PDF и при
		 * распознавании фотографии, то есть форма приходит от живых клиник.
		 */
		const glued = await itemOf("Осмотр1500");
		assert.equal(glued.priceRub, 1500, "цена, приклеенная к названию услуги, потеряна");

		const gluedWithCurrency = await itemOf("Осмотр1500 руб");
		assert.equal(gluedWithCurrency.priceRub, 1500, "цена со знаком рубля, приклеенная к названию, потеряна");

		// Короткая заглавная аббревиатура настоящей услуги неотличима от кода
		// модели: ни регистром, ни длиной. Только тем, что других чисел в строке нет.
		const abbreviation = await itemOf("ОПТГ1200");
		assert.equal(abbreviation.priceRub, 1200, "аббревиатура услуги принята за код модели");
	});

	test("предлог, приклеенный к границе диапазона, диапазон не разрушает", async () => {
		for (const line of ["от12000 до 18000", "от 12000 до18000"] as const) {
			const item = await itemOf(line);
			assert.equal(item.priceRub, 12000, `нижняя граница диапазона потеряна (строка «${line}»)`);
			assert.equal(item.priceMaxRub, 18000, `верхняя граница диапазона потеряна (строка «${line}»)`);
		}
	});

	test("название с дефисом перед ценой цену не теряет", async () => {
		// Дефис между названием и ценой — обычная запись русского прайса, и слева
		// от него стоит буква. Правило понижает такого кандидата, но он
		// единственный, поэтому ценой остаётся.
		const item = await itemOf("Гигиена-3500");
		assert.equal(item.priceRub, 3500, "цена после дефиса потеряна");
	});

	test("разделитель диапазона приклеенностью не считается", async () => {
		// В «12000-18000» слева от дефиса стоит цифра, а не буква: диапазон обязан
		// уцелеть при любом виде записи.
		for (const line of ["Отбеливание 12000-18000", "Отбеливание 12000 - 18000", "Отбеливание от 12000 до 18000"] as const) {
			const item = await itemOf(line);
			assert.equal(item.priceRub, 12000, `нижняя граница диапазона потеряна (строка «${line}»)`);
			assert.equal(item.priceMaxRub, 18000, `верхняя граница диапазона потеряна (строка «${line}»)`);
		}
	});

	test("два отдельно стоящих числа без знака рубля цены по-прежнему не получают", async () => {
		/*
		 * Правило снимает неоднозначность ТОЛЬКО между приклеенным числом и
		 * отдельно стоящим. Два отдельно стоящих числа без знака рубля — это и две
		 * опции, и две колонки таблицы, и цена с числом рядом; позиционного правила
		 * для них нет, и отказ от цены здесь остаётся верным исходом.
		 */
		const item = await itemOf("Пломба 3500 4000");
		assert.equal(item.priceRub, null, "выдумана цена там, где строка неоднозначна");
		assert.ok(item.warnings.includes("price_not_found"), "отказ от цены не показан клинике");
	});
});
