import { describe, test } from "node:test";
import assert from "node:assert/strict";
import type { ServiceCatalogItem } from "@dental/shared";
import { analyzePricelist } from "./analyzer.js";

/**
 * Последнее число строки прайса ценой услуги НЕ является.
 *
 * ЧТО БЫЛО СЛОМАНО. Когда в строке нет ни одного знака рубля, extractPrice брал
 * ПОСЛЕДНЕЕ подходящее число («.at(-1)»). В русском прайсе последнее число —
 * чаще номер кабинета, срок гарантии, длительность или количество, чем цена.
 * Измерено на дереве до правки:
 *   «Седация 5000/120 мин кабинет 412»   → 412 ₽ вместо 5000 ₽ (в 12 раз ниже);
 *   «Имплантация 45000 кабинет 412»      → 412 ₽ вместо 45000 ₽ (в 109 раз);
 *   «Коронка 15000 гарантия 1000 дней»   → 1000 ₽ вместо 15000 ₽.
 * Предупреждения при этом не было ни одного: цена выглядела прочитанной и
 * доезжала из прайса в план лечения, а оттуда в подписываемый пациентом
 * документ.
 *
 * ЧЕМ ЗАМЕНЕНО. Двумя правилами, а не новым угадыванием позиции:
 *   1. число, подписанное как не-деньги («кабинет 412») или несущее единицу
 *      измерения («120 мин», «1000 дней», «500 мл»), гасится ещё в сканере цены
 *      и кандидатом не становится;
 *   2. если после этого без знака рубля осталось несколько РАЗНЫХ чисел, строка
 *      остаётся без цены с предупреждением price_not_found — как номер
 *      документа «5678/2024» выше в том же файле.
 * Позиционного правила, делающего такую строку деньгами, не существует.
 */

/** Каталог не нужен: проверяется выбор цены, а не сопоставление с услугой. */
const EMPTY_CATALOG: ServiceCatalogItem[] = [];

async function itemsOf(line: string) {
	const response = await analyzePricelist(
		{
			sourceName: "last-number-test",
			sourceKind: "text",
			rawText: line,
			imageMimeType: "image/jpeg",
			preferredSpecialty: "universal",
			useServerAi: false,
		},
		EMPTY_CATALOG,
	);
	return response.items;
}

async function itemOf(line: string) {
	const items = await itemsOf(line);
	const item = items[0];
	assert.ok(item, `строка «${line}» не разобралась ни в одну позицию прайса`);
	return item;
}

describe("номер кабинета услугу не оценивает", () => {
	test("цена берётся не из конца строки, а из числа без подписи", async () => {
		for (const [line, expectedPrice] of [
			["Седация 5000/120 мин кабинет 412", 5000],
			// Та же строка БЕЗ разделителя: минуты и номер кабинета стоят просто
			// через пробел, и цена не имеет ни знака рубля, ни позиционного
			// преимущества. Здесь работают оба правила подряд — гашение подписи и
			// гашение единицы измерения, — а не выбор последнего числа.
			["Седация 5000 120 мин кабинет 412", 5000],
			["Седация 5000 руб/120 мин кабинет 412", 5000],
			["Имплантация 45000 кабинет 412", 45000],
			["Имплантация 45000 каб. 412", 45000],
			["Имплантация 45000 этаж 2 кабинет 412", 45000],
			["Осмотр 1500 № 412", 1500],
		] as const) {
			const item = await itemOf(line);
			assert.equal(item.priceRub, expectedPrice, `ценой стал не тот номер (строка «${line}»)`);
			assert.equal(item.priceMaxRub, null, `выдуман диапазон (строка «${line}»)`);
		}
	});

	test("номер кабинета остаётся в названии услуги", async () => {
		// Ценой он не стал, значит из названия его вырезать нечем: вырезается
		// РОВНО прочитанная цена (stripPriceFromTitle).
		const item = await itemOf("Имплантация 45000 кабинет 412");
		assert.ok(item.title.includes("кабинет 412"), `из названия исчез номер кабинета: «${item.title}»`);
		assert.ok(!item.title.includes("45000"), `цена осталась в названии: «${item.title}»`);
	});
});

describe("номер телефона услугу не оценивает", () => {
	/*
	 * ЧТО БЫЛО СЛОМАНО. Правило подписи «это не деньги» гасило РОВНО ОДНУ группу
	 * цифр после слова (`\s*\d+`): из «тел 8 999 123 45 67» стиралось «тел 8», а
	 * «999 123 45 67» доходило до сканера цены. Там разряды с пробелом читают
	 * «999 123» как деньги, кандидат стоит отдельно от букв и потому старше
	 * приклеенного, и телефон клиники продавался как услуга. Измерено на дереве:
	 *   «Тел 8 999 123 45 67»            → услуга «Тел 8 45 67» за 999 123 ₽
	 *   «Запись 8 (999) 123-45-67»       → услуга «Запись 8 ( ) 123-45-67» за 999 ₽
	 *   «Осмотр1500 тел 8 999 123 45 67» → 999 123 ₽ вместо 1500 ₽ (в 666 раз выше)
	 * Контактную строку клиника вставляет вместе с прайсом почти всегда.
	 */
	test("цена берётся из услуги, а не из номера телефона", async () => {
		for (const [line, expectedPrice] of [
			["Осмотр1500 тел 8 999 123 45 67", 1500],
			["Осмотр 1500 тел 8 999 123 45 67", 1500],
			["Осмотр 1500 руб тел 8 999 123 45 67", 1500],
			["Осмотр 1500 запись 8 (999) 123-45-67", 1500],
			["Осмотр 1500 запись +7 999 123 45 67", 1500],
		] as const) {
			const item = await itemOf(line);
			assert.equal(item.priceRub, expectedPrice, `ценой стал номер телефона (строка «${line}»)`);
			assert.equal(item.priceMaxRub, null, `выдуман диапазон (строка «${line}»)`);
		}
	});

	test("номер телефона остаётся в названии целым", async () => {
		// Из середины номера вырезался кусок как будто это цена, и в каталоге
		// оставалось «Осмотр1500 тел 8 45 67».
		const item = await itemOf("Осмотр1500 тел 8 999 123 45 67");
		assert.ok(item.title.includes("8 999 123 45 67"), `номер телефона порван: «${item.title}»`);
	});

	test("строка без услуги ценой не обзаводится", async () => {
		for (const line of ["Тел 8 999 123 45 67", "Телефон 8 999 123 45 67", "Запись 8 (999) 123-45-67"]) {
			const items = await itemsOf(line);
			// Позиции прайса из контактной строки быть не должно вовсе; если она
			// всё-таки появилась, цены у неё быть не может.
			assert.equal(items[0]?.priceRub ?? null, null, `контактная строка получила цену («${line}»)`);
		}
	});

	test("правило телефона не съедает цену из семи цифр", async () => {
		/*
		 * ГЛАВНЫЙ РИСК ЭТОГО ПРАВИЛА — тот же, что у правила единиц измерения:
		 * жадный захват уносит настоящую цену. После «8» или «+7» требуется ровно
		 * 10 цифр в группировке 3-3-2-2, и «1 200 000» под неё не подходит: цифр
		 * семь, а первая группа одна цифра, а не три.
		 *
		 * Цена, НАЧИНАЮЩАЯСЯ на восьмёрку, проверяется отдельно: префикс правила —
		 * это ровно «8», и на такой цене он срабатывает первым делом.
		 *
		 * Восьмимиллионной цены в наборе нет умышленно: её отвергает не это
		 * правило, а потолок здравого смысла в 2 000 000 ₽ внутри parseMoney, и
		 * ждать от такой строки цену значило бы проверять не то. Проверено прямым
		 * вызовом регулярки: «Имплантация 8 000 000» она не находит вовсе.
		 */
		for (const [line, expectedPrice] of [
			["Имплантация 1 200 000", 1200000],
			["Ортодонтия 800 000", 800000],
			["Наркоз 8 000 руб", 8000],
			["Коронка 12 500 руб", 12500],
		] as const) {
			const item = await itemOf(line);
			assert.equal(item.priceRub, expectedPrice, `правило телефона съело цену (строка «${line}»)`);
		}
	});
});

describe("единица измерения ценой не становится", () => {
	test("срок, длительность и объём не вытесняют цену", async () => {
		for (const [line, expectedPrice] of [
			["Коронка 15000 гарантия 1000 дней", 15000],
			["Гигиена 3000 60 мин", 3000],
			["Гигиена 3000 1 час 500 мл", 3000],
			["Каппа 4500 16 лет", 4500],
			["Наркоз 8000 40 мин 500 мл", 8000],
		] as const) {
			const item = await itemOf(line);
			assert.equal(item.priceRub, expectedPrice, `единица измерения стала ценой (строка «${line}»)`);
		}
	});

	test("разделитель разрядов в цене не съедается единицей измерения справа", async () => {
		/*
		 * ГЛАВНЫЙ РИСК ЭТОГО ПРАВИЛА. Первая версия разрешала пробел внутри
		 * гасимого числа, и жадный захват съедал цену, стоящую СЛЕВА: в «Гигиена
		 * 3000 1 час» гасилось «3000 1 час» целиком, и строка теряла цену совсем.
		 * Цена с разделителем разрядов и единица измерения справа должны стоять в
		 * одной строке без потерь.
		 */
		const item = await itemOf("Коронка 12 500 30 дней");
		assert.equal(item.priceRub, 12500, "разряды цены съедены правилом единиц измерения");
	});

	test("гашение числа не уносит его из названия услуги", async () => {
		// Гашение живёт ТОЛЬКО в тексте, по которому ищется цена: название
		// строится из исходной строки минус прочитанная цена, поэтому минуты и
		// номер кабинета обязаны остаться на месте.
		const item = await itemOf("Седация 5000/120 мин кабинет 412");
		assert.ok(item.title.includes("120 мин"), `из названия исчезли минуты: «${item.title}»`);
		assert.ok(item.title.includes("кабинет 412"), `из названия исчез номер кабинета: «${item.title}»`);
	});

	test("длительность приёма из русской строки читается, а не теряется", async () => {
		/*
		 * Гашение числа для поиска цены не должно задеть длительность: она
		 * читается из ИСХОДНОЙ строки. Заодно закрыт отдельный дефект того же
		 * класса — durationFromLine кончалась на `\b` после «мин», а в JavaScript
		 * `\b` определён через [A-Za-z0-9_], поэтому после кириллического «н»
		 * границы слова не возникает никогда, и длительность из русского прайса не
		 * читалась НИ РАЗУ. Английская строка при этом работала, поэтому дефект и
		 * жил незамеченным.
		 */
		for (const [line, expectedDuration] of [
			["Седация 5000/120 мин кабинет 412", 120],
			["Гигиена 3000 60 минут", 60],
			["Седация 5000 120 мин.", 120],
			["Sedation 5000 120 minutes", 120],
		] as const) {
			const item = await itemOf(line);
			assert.equal(item.durationMinutes, expectedDuration, `длительность приёма потеряна (строка «${line}»)`);
		}
	});

	test("похожее слово длительностью не становится", async () => {
		// Запрет буквы справа обязан отсечь «минимум»: иначе «5000 минимум»
		// назначило бы приёму длину 5000 минут — почти четверо суток.
		const item = await itemOf("Гигиена 3000 500 минимум");
		assert.equal(item.durationMinutes, null, "слово «минимум» прочитано как минуты");
	});
});

describe("отброшенное число не оставляет висеть разделитель", () => {
	test("разделитель уходит из названия вместе с ценой", async () => {
		/*
		 * ЧТО БЫЛО СЛОМАНО. Когда вторая часть записи «число/число» ценой не
		 * признана (минуты, часы, количество), отрезок цены кончался на самой цене,
		 * и разделитель оставался висеть в названии: «Седация /120 мин кабинет
		 * 412», «Гигиена /1 час». Тот же оборванный хвост, который этот файл уже
		 * убрал у диапазона («Отбеливание 12000-»). Название услуги врач видит в
		 * каталоге, а пациент — в подписываемом документе.
		 */
		for (const [line, expectedTitle, expectedPrice] of [
			["Седация 5000 руб/120 мин кабинет 412", "Седация 120 мин кабинет 412", 5000],
			["Седация 5000/120 мин", "Седация 120 мин", 5000],
			["Гигиена 3000/1 час", "Гигиена 1 час", 3000],
			["Пломба 1500/2 поверхности", "Пломба 2 поверхности", 1500],
			["Коронка 15000/зуб", "Коронка /зуб", 15000],
		] as const) {
			const item = await itemOf(line);
			assert.equal(item.title, expectedTitle, `название испорчено: «${item.title}» (строка «${line}»)`);
			assert.equal(item.priceRub, expectedPrice, `цена потеряна (строка «${line}»)`);
		}
	});
});

describe("неоднозначная строка остаётся без цены, а не с выдуманной", () => {
	test("два разных числа без знака рубля дают price_not_found", async () => {
		/*
		 * «Пломба 3500 4000» — это и две опции, и две колонки таблицы, и цена с
		 * числом рядом. Клиника видит предупреждение и проверяет одну строку
		 * руками; молча выбранное последнее число не видно никак и уходит в
		 * документ, который подписывает пациент.
		 */
		for (const line of ["Пломба 3500 4000", "Осмотр 1024 ; Пломба ; 3500"]) {
			const item = await itemOf(line);
			assert.equal(item.priceRub, null, `цена выдумана из неоднозначной строки («${line}»)`);
			assert.equal(item.priceMaxRub, null);
			assert.ok(item.warnings.includes("price_not_found"), `клиника не предупреждена («${line}»)`);
			assert.equal(item.title, line, `название испорчено: «${item.title}»`);
		}
	});

	test("знак рубля неоднозначность снимает: выбрана последняя явная цена", async () => {
		// Зафиксированное поведение явной ветки: две цены со знаком рубля в одной
		// строке — это две услуги, и разделить их разбор пока не умеет.
		const item = await itemOf("Осмотр 500 руб, повторный осмотр 300 руб");
		assert.equal(item.priceRub, 300);
	});

	test("одно и то же число дважды неоднозначностью не является", async () => {
		const item = await itemOf("Пломба 3500 ; 3500");
		assert.equal(item.priceRub, 3500, "совпадающие числа отвергнуты как неоднозначные");
	});
});
