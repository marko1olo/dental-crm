/**
 * routeNotFound.ts — что человек читает, когда экран зовёт адрес, которого на
 * сервере нет.
 *
 * ЧТО БЫЛО. `setNotFoundHandler` не стоял нигде во всём `apps/api/src`, поэтому
 * несуществующий адрес отдавал штатный ответ Fastify:
 * `{"message":"Route POST:/api/settings/catalog not found","error":"Not Found"}`.
 * Это не выдумка — ровно этот ответ описан в двух стражах прайса и протоколов
 * приёма (`tests/routes/serviceCatalogRoutes.test.ts`,
 * `tests/routes/protocolTemplateRoutes.test.ts`) как признак «маршрута нет», и
 * ровно на него натыкалась вкладка «Настройки → Прайс», у которой сервера под
 * тремя кнопками не существовало вовсе.
 *
 * ЧЕМ ЭТО ПЛОХО ДЛЯ КЛИНИКИ. Текст английский, поэтому фильтр клиента
 * (`apps/web/src/AppHelpers.tsx`, `operatorReadableErrorDetail`: строка без
 * русских букв отбрасывается целиком) его гасит, и человек получает подсказку по
 * коду 404. Сверх того ответ echo'ит метод и путь запроса обратно клиенту —
 * служебная подробность, которой на экране администратора делать нечего, а в
 * журнале сервера её как раз не было.
 *
 * ЧТО СЕРВЕР ЗНАЕТ И ЧЕГО НЕ ЗНАЕТ. Знает одно: такой метод с таким путём не
 * обслуживается. Причин может быть две — экран новее сервера (обновили не всё)
 * или адрес в программе набран неверно. Обе лечит один шаг: звать
 * администратора, а не повторять запрос. Поэтому текст называет следствие и шаг,
 * а «программа обновлена не полностью» стоит с оговоркой «скорее всего» — это
 * догадка, и она обозначена как догадка.
 */
import type { FastifyInstance } from "fastify";

/** Единственный текст отказа «такого адреса на сервере нет». */
export const routeNotFoundMessage =
	"Программа клиники обратилась к разделу, которого на этом сервере нет. Повторение не поможет — сообщите администратору: скорее всего сервер и экраны обновлены не одинаково.";

/**
 * Ставит русский ответ на несуществующий адрес.
 *
 * Метод и путь уходят в журнал сервера, а не в тело ответа: администратору они
 * не нужны, разработчику нужны, и в журнале их прежде не было вовсе.
 */
export function registerRouteNotFoundHandler(app: FastifyInstance): void {
	app.setNotFoundHandler((request, reply) => {
		request.log.warn(
			{ method: request.method, url: request.url },
			"Запрос к необслуживаемому адресу",
		);
		reply.code(404).send({
			error: "RouteNotFound",
			message: routeNotFoundMessage,
		});
	});
}
