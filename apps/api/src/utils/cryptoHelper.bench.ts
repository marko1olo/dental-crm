/**
 * Сколько сервер НЕ ОТВЕЧАЕТ НИКОМУ, пока проверяет один пароль.
 *
 * ЧТО ЗДЕСЬ БЫЛО И ПОЧЕМУ ЭТО НЕ ИЗМЕРЯЛО НИЧЕГО. Замер сравнивал
 * «последовательный» и «параллельный» прогоны хеширования. Параллельного прогона
 * не существовало: `hashCredential` была синхронной, внутри `pbkdf2Sync`, поэтому
 * все пятьдесят хешей считались ещё ДО первого `await` — при построении обещаний.
 * Два числа отличались только накладными расходами на `Promise`, и вывод
 * «параллельно быстрее» был бессмысленным. Вдобавок первая редакция звала
 * `.then()` прямо на строке и падала с `TypeError` — то есть замер не выполнялся
 * ни разу.
 *
 * ЧТО ИЗМЕРЯЕТСЯ ТЕПЕРЬ. Ровно то, что важно клинике: занимает ли хеширование
 * ЦИКЛ СОБЫТИЙ. Пока цикл занят, сервер не обрабатывает ни одного другого
 * запроса — ни расписание, ни карту приёма, ни печать документа. Поэтому здесь
 * два числа с понятным смыслом:
 *
 *   1. Сколько миллисекунд занимает одна проверка пароля.
 *   2. Насколько уезжает таймер, который обязан срабатывать каждые 5 мс, пока идёт
 *      серия проверок. Это и есть время, на которое сервер оглох.
 *
 * ВТОРОЕ ЧИСЛО — ЕДИНСТВЕННОЕ, ЧТО ВАЖНО. Первое почти не меняется и меняться не
 * должно: медленный хеш и есть защита от подбора пароля. Смысл имеет только то,
 * отвечает ли сервер остальным, пока считает.
 *
 * ЗАМЕРЫ НА РАБОЧЕЙ МАШИНЕ, 2026-07-29 (шаг таймера 5 мс, 50 проверок подряд;
 * машина под нагрузкой от параллельных сборок, поэтому абсолютные значения
 * гуляют — важно отношение):
 *
 *   pbkdf2Sync (коммит a8d582063):  срабатываний 4,   наибольшая задержка 10 473 мс
 *   pbkdf2 в пуле потоков:          срабатываний 389, наибольшая задержка     18 мс
 *
 * Задержка упала в 580 раз: с десяти с половиной секунд до восемнадцати
 * миллисекунд. Четыре срабатывания таймера за десять секунд — это и был
 * утренний вход смены: персонал прикладывается к PIN одновременно, входы
 * выстраиваются в очередь, и всё это время программа не отвечает никому,
 * включая врача у кресла, который ничего не вводил.
 *
 * Число срабатываний (389) заметно меньше теоретического потолка (5274 мс / 5 мс
 * ≈ тысяча) — это уже не блокировка, а обычная конкуренция за процессор с
 * четырьмя потоками пула на загруженной машине.
 *
 * ПОЧЕМУ ПОРОГ СТОРОЖА — ДОЛЯ, А НЕ АБСОЛЮТНЫЕ МИЛЛИСЕКУНДЫ. Первая редакция
 * этого сторожа краснела при задержке больше 20 мс (четыре шага таймера), и она
 * НЕ РАБОТАЛА. Замер на той же, уже исправленной, реализации при загруженной
 * машине: срабатываний 999, наибольшая задержка 161 мс — то есть цикл событий
 * был очевидно свободен (999 срабатываний против 4 при блокировке), а сторож всё
 * равно объявил блокировку и вернул код 1. Ложная тревога у сторожа хуже его
 * отсутствия: следующий инженер начнёт её отключать.
 *
 * Различает два состояния не абсолютная задержка, а её ДОЛЯ от всей серии.
 * При блокировке одна остановка съедает почти всю серию целиком (4437 мс из
 * 4441, 10 473 из 10 477 — свыше 99%); при счёте в пуле потоков худшая задержка
 * составила 161 мс из 26 169, то есть 0.6%. Между 99% и 0.6% лежит запас,
 * который загрузка хоста не съедает. Порог: четверть серии плюс абсолютный
 * нижний предел, чтобы условие не выполнялось на пустом месте.
 *
 * ЗАПУСК: cd apps/api && npx tsx src/utils/cryptoHelper.bench.ts
 * Код возврата 1 означает, что цикл событий снова блокируется.
 */

import { hashCredential, verifyCredential } from "./cryptoHelper.js";

const SAMPLES = 50;
/** Шаг контрольного таймера. 5 мс — заметно меньше одной проверки пароля. */
const TICK_MS = 5;

async function measureOnce(): Promise<number> {
	const started = performance.now();
	const hash = await hashCredential("password");
	await verifyCredential("password", hash);
	return performance.now() - started;
}

async function main(): Promise<void> {
	// Прогрев: первый вызов платит за подготовку модуля крипто.
	await measureOnce();

	const durations: number[] = [];
	for (let index = 0; index < SAMPLES; index += 1)
		durations.push(await measureOnce());
	durations.sort((left, right) => left - right);
	const median = durations[Math.floor(durations.length / 2)] ?? 0;
	const worst = durations.at(-1) ?? 0;
	const total = durations.reduce((sum, value) => sum + value, 0);

	console.log(
		`Одна проверка пароля: медиана ${median.toFixed(1)} мс, худшая ${worst.toFixed(1)} мс`,
	);
	console.log(`Серия из ${SAMPLES} проверок: ${total.toFixed(0)} мс подряд`);

	/*
	 * Сколько уехал таймер. Он обязан срабатывать каждые 5 мс; всё, что он
	 * проспал, — это время, в которое сервер не мог ответить никому. Замер идёт на
	 * той же серии, а не отдельно: важна именно блокировка, а не скорость
	 * хеширования сама по себе.
	 *
	 * Серия ПОСЛЕДОВАТЕЛЬНАЯ (await в цикле), а не Promise.all, и это
	 * принципиально: сравнивать надо с прежним поведением один к одному — те же
	 * пятьдесят проверок одна за другой. Параллельный прогон измерял бы уже
	 * пропускную способность пула потоков, а не блокировку цикла событий.
	 */
	let ticks = 0;
	let maxLagMs = 0;
	let previous = performance.now();
	const timer = setInterval(() => {
		const now = performance.now();
		maxLagMs = Math.max(maxLagMs, now - previous - TICK_MS);
		previous = now;
		ticks += 1;
	}, TICK_MS);

	await new Promise((resolve) => setTimeout(resolve, 50));
	const blockedFrom = performance.now();
	for (let index = 0; index < SAMPLES; index += 1) await measureOnce();
	const blockedMs = performance.now() - blockedFrom;
	await new Promise((resolve) => setTimeout(resolve, 50));
	clearInterval(timer);

	console.log(
		`Контрольный таймер (шаг ${TICK_MS} мс): срабатываний ${ticks}, наибольшая задержка ${maxLagMs.toFixed(0)} мс`,
	);

	/*
	 * Блокировкой считается остановка, съевшая заметную ДОЛЮ всей серии, а не
	 * просто крупное число миллисекунд. Обоснование и измеренная ложная тревога
	 * прежнего абсолютного порога — в пояснении в начале файла. Абсолютный
	 * нижний предел нужен, чтобы условие не сработало на очень короткой серии,
	 * где четверть — это единицы миллисекунд.
	 */
	const blockedShare = blockedMs > 0 ? maxLagMs / blockedMs : 0;
	const looksBlocked = blockedShare > 0.25 && maxLagMs > 500;

	if (looksBlocked) {
		console.log(
			`ВЫВОД: пока считаются ${SAMPLES} паролей (${blockedMs.toFixed(0)} мс), сервер не отвечает никому. ` +
				"Утренний вход смены, когда персонал прикладывается к PIN одновременно, выстраивается в очередь ровно на это время.",
		);
		console.log(
			`ВНИМАНИЕ: цикл событий стоял ${maxLagMs.toFixed(0)} мс — это ${(blockedShare * 100).toFixed(0)}% всей серии, ` +
				`а таймер с шагом ${TICK_MS} мс сработал за неё всего ${ticks} раз. Это блокировка, а не загрузка машины. ` +
				"Хеширование обязано считаться в пуле потоков: crypto.pbkdf2 с обратным вызовом, а не pbkdf2Sync (utils/cryptoHelper.ts).",
		);
		// Замер обязан уметь покраснеть, иначе он не сторож, а справка. Возврат
		// синхронного хеширования роняет этот прогон, а не проходит молча.
		process.exitCode = 1;
		return;
	}

	console.log(
		`ВЫВОД: те же ${SAMPLES} проверок пароля заняли ${blockedMs.toFixed(0)} мс, и всё это время сервер отвечал остальным: ` +
			`контрольный таймер сработал ${ticks} раз, а худшая его задержка ${maxLagMs.toFixed(0)} мс — это ` +
			`${(blockedShare * 100).toFixed(1)}% серии против свыше 99% при блокировке. ` +
			"Счёт ушёл в пул потоков libuv, цикл событий свободен — расписание, карта приёма и печать документа работают во время входа сотрудника.",
	);
}

main().catch((error) => {
	console.error(error);
	process.exitCode = 1;
});
