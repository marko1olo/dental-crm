/**
 * clinicSessionRefusal.ts — ОДИН дом для текстов отказа «запрос пришёл без
 * рабочего кабинета клиники».
 *
 * ПОЧЕМУ ДОМ ОДИН, И ПОЧЕМУ ИМЕННО ЗДЕСЬ
 *
 * Это самое частое состояние отказа в продукте: любой экран, у которого истёк
 * вход в кабинет, попадает в него. Формулировка к моменту создания этого файла
 * уже расползлась по дереву тремя независимыми копиями с разными словами:
 *   • `routes/patients.ts` — два текста, «нет входа» и «вход не принят»
 *     (правка второго прохода участка «человеческий текст сервера»);
 *   • `routes/diary.ts`, ветка `POST /api/diaries/:id/lock` — своя третья
 *     формулировка того же состояния;
 *   • `routes/schedule.ts`, `routes/diary.ts` (ещё четыре ветки),
 *     `routes/templates.ts` — вообще без текста, голый код ответа.
 * В этом дереве уже выросли четыре разных расчёта долга ровно так: каждый раз
 * заводили ещё одно место. Четвёртой копии этого текста не будет — вместо неё
 * есть этот файл, и все перечисленные маршруты собирают фразу здесь.
 *
 * Второго словаря сообщений тоже не заводится: сюда переехали ТОЛЬКО тексты
 * этого одного состояния. Отказы по существу действия (нет названия, время
 * занято, недостаточно материала) остаются рядом со своей проверкой, потому что
 * их причину знает только она.
 *
 * ТРИ СОСТОЯНИЯ, А НЕ ОДНО, И РАЗНИЦА НЕ КОСМЕТИЧЕСКАЯ
 *
 *  1. Токена кабинета в запросе НЕТ ВОВСЕ. Человеку нужно войти в кабинет.
 *  2. Токен пришёл, но НЕ ПРИНЯТ. Человеку нужно войти ЗАНОВО, и слово «заново»
 *     здесь несёт весь смысл: без него администратор с истёкшим входом читает
 *     отказ как «доступа вам не давали» и идёт к администратору вместо входа.
 *  3. Клиника в запросе НЕ ОПРЕДЕЛЕНА (`accessGuard.resolveOrganizationId`
 *     вернул null). Состояния 1 и 2 здесь РАЗЛИЧИТЬ НЕЛЬЗЯ: `getRequestIdentity`
 *     возвращает пустую личность и когда токенов нет, и когда `verifyToken` их
 *     отверг (`security/identity.ts`). Поэтому текст называет обе возможные
 *     причины и одно действие, которое лечит любую из них. Сервер не утверждает
 *     того, чего не знает.
 *
 * ПОЧЕМУ БЕЗ ЛАТИНИЦЫ И БЕЗ ДВОЕТОЧИЙ ВНУТРИ ФРАЗЫ
 *
 * Клиент гасит текст отказа целиком, если в нём нет русских букв или есть
 * латинское слово из шести и более букв — `operatorReadableErrorDetail` и
 * `technicalWorkflowFailurePattern` в `apps/web/src/AppHelpers.tsx`. Имя поля,
 * класса ошибки или переменной окружения в тексте для человека означает, что
 * человек не увидит НИЧЕГО. Машинный код при этом остаётся в отдельном поле
 * `error` — интерфейс по нему ветвится, и ни один код здесь не меняется.
 *
 * Двоеточий внутри фраз нет намеренно: часть экранов подставляет текст после
 * своего заголовка («Запись не создана: …»), и второе двоеточие в одном
 * предложении читается как обрывок.
 *
 * У КАЖДОГО ТЕКСТА ТРИ ЧАСТИ: что произошло, почему, что делать дальше. Отказ
 * без третьей части — это код ответа русскими словами, то есть тот же дефект.
 */

/**
 * Токена рабочего кабинета в запросе нет вовсе (обычно 401 `AuthRequired`).
 *
 * @param subjectClause чем именно занимался человек и почему без кабинета это
 *   невозможно — например «запись на приём сохраняется только из кабинета».
 *   Подлежащее называется русской подписью с экрана, а не именем маршрута.
 */
export function clinicSessionMissingMessage(subjectClause: string): string {
	return `Требуется авторизация рабочего кабинета клиники — ${subjectClause}. Войдите в кабинет клиники и повторите действие.`;
}

/**
 * Токен рабочего кабинета пришёл, но не принят: истёк срок, повреждена запись о
 * входе либо подпись не сходится (обычно 401 `AuthExpired`).
 *
 * Текст один на все маршруты и параметра не имеет: различить перечисленные
 * причины сервер не может (`verifyToken` возвращает null на любую из них), а
 * действие у них общее — войти заново.
 */
export const clinicSessionRejectedMessage =
	"Вход в рабочий кабинет клиники не принят — срок входа истёк или запись о входе повреждена. Войдите в кабинет клиники заново и повторите действие.";

/**
 * Клиника запроса не определена (обычно 403 `OrgRequired`): секрет периметра
 * приняли, а подписанного токена кабинета в запросе нет или он негоден.
 *
 * @param blockedAction что из-за этого сделать нельзя — «подписать дневник
 *   нельзя», «список протоколов приёма не открыть».
 * @param reassurance необязательная приписка о судьбе набранного: там, где
 *   человек уже что-то напечатал, первое, что он обязан услышать, — что текст не
 *   потерян. Без неё врач бросает заполненный дневник.
 */
export function clinicNotIdentifiedMessage(
	blockedAction: string,
	reassurance?: string,
): string {
	const tail = reassurance ? ` — ${reassurance}` : "";
	return `Рабочий кабинет клиники не определён, поэтому ${blockedAction}. Вход в кабинет либо не выполнен, либо его срок истёк. Войдите в кабинет клиники заново и повторите действие${tail}.`;
}
