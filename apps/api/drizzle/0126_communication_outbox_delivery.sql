-- 0126 — квитанции о доставке в очереди исходящих.
--
-- ЗАЧЕМ
-- Статус `sent` означает «шлюз принял сообщение», а не «пациент его получил».
-- Разница существенная: SMS на выключенный телефон шлюз принимает и берёт за
-- неё деньги, а до пациента она не доходит. Для напоминания о приёме это
-- значит, что администратор считает человека предупреждённым, а он не придёт.
--
-- Провайдеры присылают квитанцию отдельным запросом. Идентификатор сообщения у
-- провайдера уже сохраняется (provider_message_id с миграции 0123), поэтому
-- нужны только время доставки и текст квитанции.

ALTER TABLE "communication_outbox"
  ADD COLUMN IF NOT EXISTS "delivered_at" timestamptz;

-- Что именно сказал провайдер: код и расшифровка. Нужно для разбора спорных
-- случаев — «мы отправили, но пациент не получил».
ALTER TABLE "communication_outbox"
  ADD COLUMN IF NOT EXISTS "receipt_detail" text;

-- Поиск строки по идентификатору у провайдера — основная операция обработчика
-- квитанций. Индекс частичный: у строк в очереди идентификатора ещё нет.
CREATE INDEX IF NOT EXISTS "communication_outbox_provider_message_idx"
  ON "communication_outbox" ("provider_message_id")
  WHERE "provider_message_id" IS NOT NULL;
