-- 0138 — склад научился хранить партию и срок годности.
--
-- ЧТО БЫЛО. Экран склада показывал колонку «Партия / Срок» и читал поля
-- item.expirationDate и item.lotNumber. Таких колонок в таблице
-- inventory_items нет, сервер их не отдаёт, и колонка на экране всегда
-- показывала «Не указан» — в любой клинике, при любом количестве материалов.
-- Ввести срок годности было негде: в форме материала таких полей тоже нет.
--
-- ПОЧЕМУ ЭТО НЕ КОСМЕТИКА. Расходники в стоматологии имеют срок годности, и
-- просроченный композит, анестетик или адгезив — это не «неаккуратный учёт», а
-- вред пациенту и претензия к клинике. Учёт срока годности есть у всех, с кем
-- нас сравнивают. Колонка на экране была, обещание было, данных не было.
--
-- Колонка приводится к типу date, а не timestamp: у расходников срок указан
-- днём или месяцем, часовой пояс тут только мешал бы.
--
-- ДАННЫЕ. Колонки новые, обе допускают пустое значение. Существующие строки не
-- затрагиваются: у материала, заведённого раньше, партия и срок просто пусты,
-- и экран честно это покажет.

ALTER TABLE "inventory_items"
  ADD COLUMN IF NOT EXISTS "lot_number" text;

ALTER TABLE "inventory_items"
  ADD COLUMN IF NOT EXISTS "expiration_date" date;

-- Поиск «что просрочено и что вот-вот истечёт» идёт по организации и дате.
CREATE INDEX IF NOT EXISTS "inventory_items_expiration_idx"
  ON "inventory_items" ("organization_id", "expiration_date");
