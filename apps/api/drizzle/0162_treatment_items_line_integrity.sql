-- no-transaction
-- 0162_treatment_items_line_integrity.sql
--
-- СТРОКА ЛЕЧЕНИЯ: КОЛИЧЕСТВО И ДЕНЬГИ СТАНОВЯТСЯ НЕВОЗМОЖНЫМИ ПО УСТРОЙСТВУ БАЗЫ
--
-- ============================================================================
-- ЧТО ИМЕННО БЫЛО СЛОМАНО
-- ============================================================================
--
-- Замер на живой базе (PostgreSQL 18.4) ДО этой миграции:
--
--   pg_constraint, conrelid = 'treatment_items', contype = 'c' ......... 0
--   ограничений CHECK на эту таблицу во всех 131 файле drizzle/*.sql ... 0
--   quantity ........ numeric(10, 2) NOT NULL DEFAULT '1'::numeric
--   discount_rub .... numeric(12, 2) NOT NULL DEFAULT 0
--   unit_price_rub .. numeric(12, 2) NOT NULL
--   price_rub ....... numeric(12, 2) NOT NULL
--
-- То есть о строке лечения база не знала НИЧЕГО, кроме «не NULL». Количество 0,
-- количество −1, количество 1,5, отрицательная скидка и отрицательная цена были
-- достижимы одним оператором INSERT — и достижимы не гипотетически: в этом
-- дереве по строке лечения считают долг пациента, смету, счёт, печатную форму
-- документа и отбор получателей рассылки о задолженности.
--
-- Правила при этом существовали — но только на словах и только над одним
-- входом:
--   • общий контракт `packages/shared/src/index.ts`, `treatmentPlanItemSchema`:
--     `quantity: z.number().int().positive()`, `unitPriceRub` и `discountRub` —
--     `nonNegativeMoneyRubSchema`;
--   • канон расчёта `apps/api/src/money/patientDebt.ts`,
--     `assertContractQuantity`: количество ≤ 0 — ОТКАЗ, дословно «позицию без
--     объёма надо отменять статусом cancelled, а не считать как одну единицу»;
--     дробное количество — тоже отказ, потому что три прежних расчёта округляли
--     его тремя разными способами;
--   • единственный производственный писатель `routes/odontogram.ts` проверяет
--     `z.number().int().min(1).max(999)`.
--
-- Договорённость трёх файлов — это не ограничение. Она действует ровно на том
-- пути, который через них проходит, и не действует ни для прямого SQL, ни для
-- переноса данных из чужой системы, ни для скрипта уборки, ни для второй службы,
-- которая однажды сядет на ту же схему. База — единственное место, через которое
-- обязаны пройти ВСЕ записи, поэтому проверка приложения и ограничение базы
-- закрывают разные множества событий, и наличие первой не отменяет вторую.
--
-- ============================================================================
-- ПОЧЕМУ ИМЕННО ЭТИ ПЯТЬ И НИ ОДНОГО СВЕРХ
-- ============================================================================
--
-- Правило отбора одно: ограничение обязано ПОВТОРЯТЬ уже объявленный контракт, а
-- не вводить новую политику снизу. Ограничение строже вышестоящих слоёв — это не
-- целостность, а отказ в обслуживании, приезжающий к пользователю пятисоткой
-- вместо внятного 400.
--
--   1. quantity > 0
--      Повторяет `.positive()` контракта и отказ канона на `qty <= 0`. Здесь же
--      закрывается самый дорогой случай: позиция с количеством 0 у прежнего
--      выражения отчётов `greatest(quantity, 1)` выставлялась как ОДНА ЕДИНИЦА,
--      то есть счёт за объём, которого в позиции нет.
--
--   2. quantity = trunc(quantity)
--      Повторяет `.int()` контракта. Колонка объявлена numeric(10, 2) и дробное
--      значение физически пропускает — об этом прямо сказано ещё в 0135.
--
--   3. discount_rub >= 0
--   4. unit_price_rub >= 0
--      Повторяют `nonNegativeMoneyRubSchema` обоих полей контракта.
--
--   5. price_rub >= 0
--      Собственного контракта у этой колонки нет: её сегодня не читает никто,
--      писатель заполняет её тем же значением, что и unit_price_rub (конвенция
--      парной денежной колонки, `tests/routes/serviceCatalogWriteProof.ts`).
--      Ограничение поставлено осознанно и названо честно: это не повтор
--      контракта, а запрет отрицательных денег в денежной колонке, которую
--      завтра кто-нибудь начнёт читать и унаследует дыру целиком. Ни один
--      существующий писатель отрицательного значения в неё не кладёт, поэтому
--      цена решения — ноль.
--
-- ПОЧЕМУ trunc, А НЕ scale И НЕ floor. Измерено на этой базе, а не взято из
-- документации:
--
--   значение (numeric(10,2))   scale()   min_scale()   = trunc(значение)
--   1.00                          2           0             true
--   2.00                          2           0             true
--   1.50                          2           1             false
--
-- То есть `scale(quantity) = 0` отвергло бы КАЖДУЮ законную строку: колонка с
-- объявленной дробной частью приводит к ней любое значение, и scale() честно
-- сообщает объявленную, а не значащую. `min_scale(quantity) = 0` работает
-- правильно, но существует с PostgreSQL 13 и требует от читателя знать разницу
-- между двумя видами «scale». `floor` от `trunc` отличается только на
-- отрицательных числах, а при равенстве значения своей целой части оба варианта
-- совпадают всегда; выбран `trunc`, потому что он говорит «дробной части нет» и
-- не зависит от знака ни в каком прочтении.
--
-- ЧЕГО ЭТИ ОГРАНИЧЕНИЯ НЕ ЛОВЯТ, И ЭТО НАДО ЗНАТЬ ЗАРАНЕЕ. Колонка приводит
-- значение к своей дробной части ДО того, как ограничение его увидит. Измерено:
-- `1.004::numeric(10,2)` превращается в `1.00` и проверку целости ПРОХОДИТ,
-- а контракт `.int()` такое число отверг бы. Ограничение базы поэтому не
-- заменяет проверку маршрута, а страхует её. В ту же сторону работает и второй
-- замер: `0.001::numeric(10,2)` превращается в `0.00` и отвергается пунктом 1 —
-- то есть подкопеечное количество не проскакивает, а падает.
--
-- ============================================================================
-- ПОЧЕМУ ЗДЕСЬ НЕТ ОГРАНИЧЕНИЯ «СКИДКА <= ЦЕНА * КОЛИЧЕСТВО»
-- ============================================================================
--
-- Оно рассматривалось всерьёз и отклонено. Именно эта строка — корень дефекта,
-- который сегодня закрыли на клиенте (`apps/web/src/FinanceLedger.tsx`
-- показывал пациенту отрицательную сумму там, где сервер даёт 0), так что довод
-- «оно закрыло бы дефект в корне» настоящий. Не перевесил по четырём причинам:
--
--   1. ТАКОГО ПРАВИЛА НЕТ НИ В ОДНОМ СЛОЕ ВЫШЕ. Контракт объявляет
--      неотрицательность цены и скидки ПООТДЕЛЬНОСТИ и не связывает их между
--      собой. Маршрут `routes/odontogram.ts` проверяет их независимо и
--      пропускает скидку до 100 000 000 ₽ при любой цене. Канон
--      `chargeLineKopecks` этот случай не запрещает, а ОБРАБАТЫВАЕТ:
--      `Math.max(0, цена × количество − скидка)`. Ограничение, которого нет
--      наверху, превращает сегодня принимаемый ввод в необработанное нарушение
--      ограничения, то есть в пятисотку вместо объяснимого отказа.
--
--   2. ПОРЯДОК РАБОТ ОБРАТНЫЙ. Правильная последовательность — сначала правило в
--      контракте, потом перекрёстная проверка маршрута с внятным сообщением,
--      и только потом ограничение базы. Приехать одной последней ступенью —
--      значит поменять тихое неверное число на падение.
--
--   3. УЧЁТНАЯ ПРАКТИКА ТАКОГО ЗАПРЕТА НА СТРОКЕ НЕ ТРЕБУЕТ. Требование
--      отраслевых правил — «итог строки не может быть отрицательным», и скидка,
--      превышающая стоимость, в учётных системах ПЕРЕКВАЛИФИЦИРУЕТСЯ отдельным
--      документом (бонусная подпозиция со стопроцентной уценкой, кредит-нота,
--      отдельная строка возврата), а не отвергается на уровне позиции. Сто
--      процентов — законный потолок, и он у нас уже достижим: лечение по
--      гарантии оформляется скидкой, равной стоимости. То, что БОЛЬШЕ
--      стоимости, — это уже не скидка, а выплата пациенту, и её дом в этой
--      схеме есть: таблица `payments` со статусами возврата.
--
--   4. ОТРИЦАТЕЛЬНОГО ИТОГА СТРОКИ НИ ОДИН ЧИТАТЕЛЬ УЖЕ НЕ ВИДИТ. На сервере
--      стоят `greatest(…, 0)` в SQL и `Math.max(0, …)` в каноне, на клиенте
--      зажим поставлен сегодня. Пункты 3 и 4 этого файла (неотрицательные цена и
--      скидка) закрывают ВТОРУЮ дорогу к отрицательному итогу — отрицательную
--      цену, — а у неё, в отличие от большой скидки, законного прочтения нет
--      вовсе.
--
-- ЧТО ОСТАЁТСЯ НЕЗАКРЫТЫМ, СКАЗАНО ПРЯМО: строка со скидкой выше стоимости
-- по-прежнему возможна, и для каждого читателя она молча становится нулём —
-- то есть клиника не может УВИДЕТЬ, что данные неверны. Это пробел ОТЧЁТНОСТИ,
-- а не целостности, и лечится он перекрёстной проверкой маршрута плюс отчётом
-- «позиции со скидкой выше стоимости», а не тихо добавленным сюда ограничением.
--
-- ============================================================================
-- ФОРМА ДОБАВЛЕНИЯ: NOT VALID, ПОТОМ VALIDATE, И ПОЧЕМУ ФАЙЛ БЕЗ ТРАНЗАКЦИИ
-- ============================================================================
--
-- Разница между простым ADD CONSTRAINT ... CHECK и парой
-- ADD CONSTRAINT ... NOT VALID + VALIDATE CONSTRAINT — это разница в том, ЧТО
-- держится под самой тяжёлой блокировкой:
--
--   • ADD CONSTRAINT ... CHECK  — ACCESS EXCLUSIVE на таблицу И ПОЛНЫЙ ПРОХОД по
--     ней под этой блокировкой. ACCESS EXCLUSIVE — единственный уровень, который
--     останавливает даже чтение. Хуже самого ожидания то, что очередь блокировок
--     в PostgreSQL — это FIFO: за ожидающим DDL встают все последующие запросы, и
--     приложение выглядит замершим целиком, а не медленным.
--   • ADD CONSTRAINT ... NOT VALID — та же ACCESS EXCLUSIVE, но БЕЗ прохода:
--     правка каталога, то есть доли миллисекунды. При этом ограничение начинает
--     действовать на новые записи НЕМЕДЛЕННО; непроверенными остаются только
--     старые строки.
--   • VALIDATE CONSTRAINT — полный проход, но уже под SHARE UPDATE EXCLUSIVE.
--     Этот уровень не мешает ни чтению, ни записи.
--
-- ПОЭТОМУ ФАЙЛ ПОМЕЧЕН no-transaction, И ЭТО НЕ УКРАШЕНИЕ. Если положить ADD и
-- VALIDATE в ОДНУ транзакцию, весь выигрыш исчезает: ACCESS EXCLUSIVE, взятая
-- на ADD, держится до конца транзакции, и проход VALIDATE идёт под ней же. Пара
-- «NOT VALID + VALIDATE» внутри одной транзакции — это театр, ничем не лучше
-- простого ADD CHECK. Раскатчик (`src/scripts/migrate.ts`) выполняет файл с этим
-- маркером по одному выражению в autocommit, то есть каждое VALIDATE получает
-- собственную транзакцию и собственную лёгкую блокировку. Ради этого маркер и
-- поставлен.
--
-- ПОЧЕМУ ПОТЕРЯ АТОМАРНОСТИ ЗДЕСЬ ДОПУСТИМА, В ОТЛИЧИЕ ОТ 0161. Там половина
-- применённой защиты — это таблица с отозванными правами и без сторожа, то есть
-- состояние ХУЖЕ исходного. Здесь ограничения независимы и только добавляются:
-- любое частичное применение строго сильнее исходного, а непроверенное
-- ограничение всё равно держит новые записи. Повторный прогон доводит дело до
-- конца.
--
-- ЗАЧЕМ lock_timeout. Кластер общий. Без ограничения ожидания ALTER, упершийся в
-- чужую долгую транзакцию, встаёт в очередь и блокирует за собой всех. С
-- таймаутом он падает быстро, миграция не отмечается применённой, и повторный
-- прогон продолжает с того же места. Значение задаётся на сессию раскатчика и
-- умирает вместе с ней.
--
-- НА ЭТОЙ БАЗЕ РАЗНИЦЫ НЕТ, И ЭТО ИЗМЕРЕНО, А НЕ ПРЕДПОЛОЖЕНО. Под обходом RLS
-- (`app.superuser_bypass = 'on'`, механизм из 0158) в `treatment_items` 0 строк,
-- нарушителей по каждому из пяти условий — 0. Без обхода тот же счёт тоже даёт
-- 0, но это ЛОЖНЫЙ ноль: политика 0157 фильтрует строки чужих арендаторов, и
-- пустой ответ на соединении без `app.current_tenant` не означает пустую таблицу.
-- Форма выбрана не под сегодняшнюю пустую таблицу, а под ту боевую базу, в
-- которой этот же файл однажды выполнится на миллионе строк.
--
-- ============================================================================
-- ИДЕМПОТЕНТНОСТЬ
-- ============================================================================
--
-- Измерено на этой базе в откаченной транзакции:
--   повторный ADD CONSTRAINT ...... ОШИБКА 42710 «ограничение уже существует»;
--                                   IF NOT EXISTS у ADD CONSTRAINT не бывает,
--                                   поэтому нужен явный просмотр pg_constraint;
--   повторный VALIDATE CONSTRAINT . ПРОХОДИТ молча, состояние не меняет.
--
-- Отсюда несимметричное оформление: добавление закрыто просмотром каталога,
-- проверка вызывается как есть. DROP CONSTRAINT IF EXISTS перед ADD сознательно
-- НЕ используется: вне транзакции между удалением и добавлением возникает окно,
-- в котором ограничения нет, и в это окно проходит любая запись.
--
-- ============================================================================
-- ЧТО СЛОМАЕТСЯ. НАЗВАНО ЗДЕСЬ, ЧТОБЫ НЕ ИСКАЛИ ПРИЧИНУ ПОТОМ
-- ============================================================================
--
-- Ограничение CHECK проверяется на КАЖДОЙ вставке и на КАЖДОМ обновлении строки
-- целиком, а не только тех колонок, которые перечислены в операторе. Практически
-- это значит: если в боевой базе найдётся старая строка с количеством 0, то
-- сломается не только запись новых позиций, но и `routes/diary.ts:585`, который
-- при закрытии дневника переводит позиции визита в статус `completed` и никаких
-- денежных колонок не трогает. Поэтому VALIDATE и стоит в этом файле: пропустить
-- его значило бы оставить мину, которая взорвётся на постороннем UPDATE.
--
-- Тестовые наборы, которые сеют позиции лечения напрямую через drizzle
-- (`tests/routes/*`, `tests/chains/*`, `scripts/seedOpsScreenshotDemo.ts`),
-- ограничениям не противоречат: все они кладут целое количество не меньше 1 и
-- неотрицательные суммы. Проверено чтением, не предположено.

SET lock_timeout = '5s';

-- =============================================================================
-- 1. Пять ограничений, добавленных без прохода по таблице.
--
-- Один блок на все пять: добавление — это правка каталога, и держать её в одной
-- короткой транзакции дешевле и честнее, чем пять раз брать и отпускать тяжёлую
-- блокировку. Проход по данным сюда не входит — он ниже, отдельными выражениями.
--
-- Просмотр pg_constraint по имени, а не по определению: имя и есть то, что
-- PostgreSQL печатает в сообщении об отказе, поэтому оно же обязано быть ключом
-- идемпотентности.
-- =============================================================================

DO $do$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
     WHERE conrelid = 'treatment_items'::regclass
       AND conname = 'treatment_items_quantity_positive'
  ) THEN
    ALTER TABLE "treatment_items"
      ADD CONSTRAINT "treatment_items_quantity_positive"
      CHECK ("quantity" > 0) NOT VALID;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
     WHERE conrelid = 'treatment_items'::regclass
       AND conname = 'treatment_items_quantity_whole'
  ) THEN
    ALTER TABLE "treatment_items"
      ADD CONSTRAINT "treatment_items_quantity_whole"
      CHECK ("quantity" = trunc("quantity")) NOT VALID;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
     WHERE conrelid = 'treatment_items'::regclass
       AND conname = 'treatment_items_unit_price_rub_nonnegative'
  ) THEN
    ALTER TABLE "treatment_items"
      ADD CONSTRAINT "treatment_items_unit_price_rub_nonnegative"
      CHECK ("unit_price_rub" >= 0) NOT VALID;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
     WHERE conrelid = 'treatment_items'::regclass
       AND conname = 'treatment_items_price_rub_nonnegative'
  ) THEN
    ALTER TABLE "treatment_items"
      ADD CONSTRAINT "treatment_items_price_rub_nonnegative"
      CHECK ("price_rub" >= 0) NOT VALID;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
     WHERE conrelid = 'treatment_items'::regclass
       AND conname = 'treatment_items_discount_rub_nonnegative'
  ) THEN
    ALTER TABLE "treatment_items"
      ADD CONSTRAINT "treatment_items_discount_rub_nonnegative"
      CHECK ("discount_rub" >= 0) NOT VALID;
  END IF;
END $do$;

-- =============================================================================
-- 2. Проверка существующих строк — по одному выражению на ограничение.
--
-- Каждое идёт отдельной транзакцией (файл помечен no-transaction), поэтому берёт
-- SHARE UPDATE EXCLUSIVE и не мешает работе клиники. Разбивка по одному нужна и
-- по второй причине: если в боевой базе найдутся нарушители, сообщение назовёт
-- ИМЕННО ТО ограничение, которое не сошлось, а остальные четыре к этому моменту
-- уже будут проверены и не потеряются вместе с ним.
--
-- Повторный вызов на уже проверенном ограничении — молчаливый no-op (измерено),
-- поэтому обёртка не нужна.
-- =============================================================================

ALTER TABLE "treatment_items" VALIDATE CONSTRAINT "treatment_items_quantity_positive";
ALTER TABLE "treatment_items" VALIDATE CONSTRAINT "treatment_items_quantity_whole";
ALTER TABLE "treatment_items" VALIDATE CONSTRAINT "treatment_items_unit_price_rub_nonnegative";
ALTER TABLE "treatment_items" VALIDATE CONSTRAINT "treatment_items_price_rub_nonnegative";
ALTER TABLE "treatment_items" VALIDATE CONSTRAINT "treatment_items_discount_rub_nonnegative";
