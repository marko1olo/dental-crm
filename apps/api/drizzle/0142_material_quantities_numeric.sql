-- Количества материалов: integer в базе против numeric в модели.
--
-- ЧТО БЫЛО СЛОМАНО ДЛЯ КЛИНИКИ. Врач не мог закрыть приём, если в услуге стояло
-- дробное количество. Подписание дневника визита списывает материалы по правилу
-- «сколько единиц на одну услугу» и умножает его на treatment_items.quantity,
-- а это настоящий numeric(10,2). Услуга с количеством 1.5 при правиле 1 требует
-- записать -8.5 в колонку quantity_changed, объявленную в схеме numeric(10,3),
-- но фактически созданную в базе как integer. PostgreSQL такой запрос отвергает,
-- ошибка драйвера не является DiarySigningError и уходит в общий обработчик как
-- 500. Транзакция откатывается ЦЕЛИКОМ: остаток на складе прежний, ни одной
-- строки расхода, и дневник НЕ ПОДПИСАН. Измерено, а не предположено — замер
-- зафиксирован в apps/api/src/routes/diary.ts рядом с расчётом списания.
--
-- ПОЧЕМУ ПРАВИМ БАЗУ, А НЕ КОД. Три причины, и ни одна не про удобство.
--
-- 1. Дробные количества в стоматологии — норма, а не край. Половина карпулы
--    анестетика, 0.3 г композита, 1.5 мл ирригационного раствора. Целочисленный
--    остаток склада для клиники неверен по существу.
-- 2. Источник умножения уже дробный: treatment_items.quantity — numeric(10,2).
--    Приёмник обязан быть не грубее источника, иначе часть значений источника
--    непредставима, и это ровно то, что происходит сейчас.
-- 3. Округление было бы ВЫДУМАННОЙ ПОЛИТИКОЙ НА МАТЕРИАЛАХ. Округление вниз
--    крадёт материал у учёта, вверх — у клиники, «к ближайшему» делает и то и
--    другое в зависимости от дроби. Себестоимость входит в расчёт выплат врачам
--    (services/finance/doctorPayouts.ts), то есть выдуманная дробь превратилась
--    бы в выдуманную зарплату.
--
-- Модель уже объявляет эти колонки numeric (db/schema.ts:1591, :1630, :1757),
-- поэтому миграция приводит базу к ОБЪЯВЛЕННОМУ виду, а не меняет контракт.
-- Точности взяты из схемы, чтобы расхождение закрылось, а не переехало:
--   inventory_items.stock_quantity            numeric(10,3)
--   inventory_transactions.quantity_changed   numeric(10,3)
--   procedure_material_rules.quantity_to_deduct numeric(12,4)
--
-- ПОТЕРИ ДАННЫХ НЕТ: любое целое представимо в numeric точно, поэтому
-- USING-приведение целочисленных значений не теряет и не меняет ни одного из них.
-- Ограничения NOT NULL и значения по умолчанию сохранены явно: ALTER TYPE их не
-- снимает, но и не переносит автоматически в новом типе — default пришлось бы
-- переписать вручную, если бы он был выражением. Здесь это константы.

ALTER TABLE inventory_items
  ALTER COLUMN stock_quantity TYPE numeric(10, 3) USING stock_quantity::numeric(10, 3),
  ALTER COLUMN stock_quantity SET DEFAULT 0;

ALTER TABLE inventory_transactions
  ALTER COLUMN quantity_changed TYPE numeric(10, 3) USING quantity_changed::numeric(10, 3);

ALTER TABLE procedure_material_rules
  ALTER COLUMN quantity_to_deduct TYPE numeric(12, 4) USING quantity_to_deduct::numeric(12, 4),
  ALTER COLUMN quantity_to_deduct SET DEFAULT 1.0000;

