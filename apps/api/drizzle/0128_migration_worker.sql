-- 0128 — статус «в очереди» для асинхронного выполнения переноса.
--
-- ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ
-- PostgreSQL запрещает ссылаться на новое значение перечисления в той же
-- транзакции, где оно добавлено: «unsafe use of new value». Наш накатыватель
-- выполняет каждый файл в отдельной транзакции, поэтому добавление значения
-- живёт здесь, а всё, что на него ссылается (частичный индекс очереди), —
-- в следующем файле 0129.
--
-- Статус нужен, чтобы отличать «оператор нажал выполнить, исполнителя ещё нет»
-- от «исполнитель взял и умер». Без этого различия воркер либо не подберёт
-- новый прогон, либо повторно возьмёт живой.

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_enum e
    JOIN pg_type t ON t.oid = e.enumtypid
    WHERE t.typname = 'migration_run_status' AND e.enumlabel = 'queued'
  ) THEN
    ALTER TYPE "migration_run_status" ADD VALUE 'queued' AFTER 'validated';
  END IF;
END $$;
