-- ============================================================================
-- ЧТО ИМЕННО БЫЛО СЛОМАНО
-- ============================================================================
--
-- Комментарий «IMMUTABILITY GUARANTEE» в `src/routes/audit.ts` описывает
-- неизменность журнала, которой на уровне базы не существовало ни в каком виде.
-- Замер на живой базе (PostgreSQL 18.4) до этой миграции:
--
--   information_schema.role_table_grants, роль dental, обе таблицы журнала:
--     DELETE, INSERT, REFERENCES, SELECT, TRIGGER, TRUNCATE, UPDATE
--   pg_class.relacl ................................ NULL (прав никто не трогал)
--   триггеров во всей схеме public ................. 0
--   строк в audit_events / clinical_audit_logs ..... 0 / 0
--
-- То есть роль приложения могла стереть собственный журнал одним оператором.
-- Опыт в откаченной транзакции подтвердил это буквально: INSERT события,
-- затем UPDATE reason -> 'TAMPERED' (1 строка), затем DELETE (1 строка). Обе
-- команды прошли без единого возражения базы.
--
-- Принудительный RLS из 0157-0160 эту дыру НЕ закрывает и закрывать не может:
-- он изолирует арендаторов друг от друга, а не защищает журнал от его
-- собственного владельца. Арендатор A действительно не сотрёт журнал
-- арендатора B, но свой собственный сотрёт целиком. Более того, отдельно
-- измерено: TRUNCATE политикам RLS НЕ подчиняется вообще. На соединении без
-- `app.current_tenant` DELETE удалил 0 строк (политика сработала), а TRUNCATE
-- в тех же условиях уничтожил строку, которую то же соединение даже не видело.
-- Значит TRUNCATE — это межарендный стиратель, и REVOKE на него обязателен
-- отдельным пунктом, а не «до кучи».
--
-- Правовая рамка, ради которой это вообще делается: мера РСБ.7 приказа ФСТЭК
-- России N 21 (защита сведений о событиях безопасности от уничтожения и
-- модификации, доступ только уполномоченным) входит в базовый набор для УЗ-3 и
-- выше; приказ Роскомнадзора N 179 от 28.10.2022 требует подтверждать
-- уничтожение персональных данных выгрузкой из журнала регистрации событий, а
-- журнал, который стирается изнутри приложения, такой выгрузки не обеспечивает.
--
-- ============================================================================
-- ГРАНИЦА ЗАЩИТЫ. ЧИТАТЬ ДО ТОГО, КАК ССЫЛАТЬСЯ НА ЭТУ МИГРАЦИЮ КАК НА ДОКАЗАТЕЛЬСТВО
-- ============================================================================
--
-- Роль приложения `dental` ВЛАДЕЕТ обеими таблицами журнала (как и всеми
-- остальными 148). Владелец таблицы в PostgreSQL не ограничен ни отзывом прав,
-- ни триггером, и это проверено опытом на этой самой базе, а не выведено из
-- документации. Четыре попытки обхода, все в откаченной транзакции:
--
--   (а) вернуть себе отозванное: GRANT UPDATE, DELETE, TRUNCATE TO dental
--       -> ПРОШЛО. Отзыв прав у владельца отменяется одной командой.
--   (б) отключить триггер: ALTER TABLE ... DISABLE TRIGGER
--       -> ПРОШЛО, причём и над триггером, помеченным ENABLE ALWAYS. После
--          этого защищённая строка была успешно изменена и удалена.
--   (в) удалить триггер: DROP TRIGGER
--       -> ПРОШЛО. И DROP FUNCTION, и DROP TABLE самой таблицы журнала — тоже.
--   (г) TRUNCATE после возврата себе права
--       -> ПРОШЛО.
--
-- Единственные две двери, которые перед `dental` закрыты, измерены там же:
-- CREATE EVENT TRIGGER отвергается (42501, нужен суперпользователь) и
-- SET session_replication_role отвергается (42501,
-- has_parameter_privilege('dental','session_replication_role','SET') = false).
--
-- ОТСЮДА ЧЕСТНЫЙ ВЫВОД, И ЕГО НЕЛЬЗЯ СМЯГЧАТЬ В ОТЧЁТАХ:
--   • эта миграция закрывает журнал от ОБЫЧНОГО ХОДА ПРОГРАММЫ — от кода
--     приложения, от ORM, от скриптов уборки, от одиночного внедрённого
--     оператора DML, от ошибки оператора. Стирание перестаёт быть побочным
--     эффектом чужой задачи и становится отдельным, намеренным актом DDL;
--   • эта миграция НЕ закрывает журнал от того, кто выполняет произвольный SQL
--     от имени `dental`. Такой участник снимает всю защиту двумя командами.
--
-- Настоящее append-only на уровне базы требует РАЗДЕЛЕНИЯ ВЛАДЕЛЬЦА И РОЛИ
-- ПРИЛОЖЕНИЯ: владельцем обеих таблиц становится отдельная роль, а `dental`
-- получает только INSERT и SELECT. Сделать это внутри данной миграции
-- НЕВОЗМОЖНО по устройству прав: файл раскатывается под `dental`, а
-- ALTER TABLE ... OWNER TO требует членства в целевой роли, которого у `dental`
-- нет и которое она сама себе выдать не может (rolcreaterole = false). Это
-- шаг для суперпользователя `dente_admin` и архитектурное решение ведущего,
-- а не то, что подпольно доделывает миграция.
--
-- ============================================================================
-- ПОЧЕМУ ДВА СЛОЯ, А НЕ ОДИН
-- ============================================================================
--
-- Слой прав (REVOKE) и слой триггеров ловят разные вещи, и ни один из них по
-- отдельности не годится.
--
-- ТОЛЬКО REVOKE недостаточно. Он отменяется одной командой GRANT (опыт «а»), и
-- он же молча перестаёт действовать, если кто-нибудь однажды напишет
-- GRANT ALL ON ALL TABLES IN SCHEMA public TO <роль> — приём, который в этом
-- репозитории уже применялся к другим таблицам. Триггер такой строчки не
-- заметит и продолжит держать.
--
-- ТОЛЬКО ТРИГГЕР недостаточно. Триггер срабатывает ПОСЛЕ проверки прав, то есть
-- он не защищает от команды, для которой прав и так нет, — зато проверка прав
-- дешевле и даёт отказ раньше. Кроме того, отзыв прав виден в pg_dump и в
-- information_schema как декларация намерения, а триггер надо искать.
--
-- Порядок отказа получается такой: REVOKE отвергает команду на входе (42501),
-- триггер остаётся вторым рубежом для любой роли, которой права однажды выдали.
-- Оба слоя намеренно говорят ОДНИМ И ТЕМ ЖЕ кодом 42501: приложение и скрипты
-- не должны различать, какой из рубежей сработал, а 42501 в этом коде уже
-- обрабатывается как отказ политики RLS.
--
-- ПОЧЕМУ ОТДЕЛЬНЫЙ ТРИГГЕР НА TRUNCATE. Измерено: триггер BEFORE UPDATE OR
-- DELETE FOR EACH ROW команду TRUNCATE НЕ ЛОВИТ ВООБЩЕ — таблица с таким
-- триггером опустошается молча, потому что TRUNCATE не порождает построчных
-- событий. Ловит только отдельный BEFORE TRUNCATE FOR EACH STATEMENT. Отсюда
-- по два триггера на таблицу, а не по одному.
--
-- ПОЧЕМУ ENABLE ALWAYS. Измерено честно: против владельца это НЕ помогает,
-- DISABLE TRIGGER снимает и такой триггер. Пометка ставится ради другого
-- случая: обычный триггер (ENABLE ORIGIN) не срабатывает у сессии с
-- session_replication_role = replica, в котором работают процессы применения
-- логической репликации и часть инструментов восстановления. Если эта база
-- когда-нибудь станет подписчиком, реплицированный DELETE снёс бы журнал в
-- обход сторожа. ENABLE ALWAYS закрывает именно эту дорогу и никакую другую;
-- выдавать его за защиту от владельца — ложь.
--
-- ============================================================================
-- ПОЧЕМУ У clinical_audit_logs ЕСТЬ УЗКАЯ ПОЛОСА НА patient_id
-- ============================================================================
--
-- Глухой запрет UPDATE на clinical_audit_logs сломал бы слияние карточек
-- пациентов, и это не гипотеза. `services/patients/patientMerge.ts` не знает
-- список таблиц заранее: он берёт его из information_schema в момент
-- выполнения — все внешние ключи на patients.id плюс все колонки с именем
-- patient_id или local_patient_id. Тот же запрос, выполненный на живой базе,
-- даёт 50 колонок, и clinical_audit_logs.patient_id среди них. Слияние идёт
-- одной транзакцией по принципу «всё или ничего», поэтому отказ на журнале
-- уронил бы операцию целиком. Это был бы отказ в обслуживании вместо защиты —
-- ровно тот размен, который делать нельзя.
--
-- Полоса сделана максимально узкой, и узость держится ДВУМЯ независимыми
-- механизмами:
--   1. право уровня КОЛОНКИ. Табличное UPDATE отозвано, выдано только
--      GRANT UPDATE (patient_id). Оператор, меняющий заодно action или meta,
--      отвергается системой прав (42501) ещё до триггера — проверено;
--   2. триггер, который поверх этого требует, чтобы UPDATE был именно
--      перестановкой ссылки: всё, кроме patient_id, побайтово не изменилось
--      (сравнение to_jsonb(OLD) и to_jsonb(NEW) без этого ключа — оно не
--      требует перечислять колонки и переживёт ADD COLUMN), сама ссылка
--      действительно изменилась, и новая ссылка ведёт на существующего
--      пациента ТОЙ ЖЕ организации.
--
-- Третье условие закрывает лазейку, которую первая версия этого файла
-- оставляла открытой и которую нашёл собственный опыт, а не рассуждение:
-- с одним лишь правом на колонку проходил UPDATE ... SET patient_id = NULL,
-- то есть запись журнала теряла пациента, оставаясь формально неизменной.
-- Стирание ссылки — это и есть порча журнала, и оно запрещено.
--
-- У audit_events такой полосы нет и быть не должно: колонки patient_id у неё
-- нет, в список слияния она не попадает, законных писателей UPDATE у неё нет
-- ни одного (все обращения в apps/api/src — только INSERT и SELECT).
--
-- ============================================================================
-- ПОЧЕМУ У КОЛОНОК ВНЕШНИХ КЛЮЧЕЙ ПРАВО UPDATE ВСЁ-ТАКИ ОСТАЁТСЯ
-- ============================================================================
--
-- Обе таблицы журнала стоят на ССЫЛАЮЩЕЙСЯ стороне пяти внешних ключей:
--   audit_events.organization_id -> organizations.id
--   audit_events.actor_user_id -> users.id
--   clinical_audit_logs.organization_id -> organizations.id
--   clinical_audit_logs.patient_id -> patients.id
--   clinical_audit_logs.user_id -> users.id
-- Все пять — без ON DELETE, то есть NO ACTION. Удаляя строку РОДИТЕЛЯ,
-- PostgreSQL выполняет проверку целостности, а она берёт на дочерней таблице
-- блокировку строк (SELECT ... FOR KEY SHARE). Такая блокировка требует права
-- UPDATE или DELETE — и отзыв обоих ломает удаление родителя.
--
-- Это не рассуждение, а замер. С полностью отозванным UPDATE удаление
-- организации и пользователя падало с 42501 «нет доступа к таблице
-- audit_events» ДАЖЕ КОГДА В ЖУРНАЛЕ НОЛЬ СТРОК. Цена такой ошибки здесь не
-- теоретическая: разбор всего каталога тестов показывает, что уборка после
-- почти каждого набора идёт через db.delete(organizations) и db.delete(users),
-- то есть неаккуратный отзыв прав покрасил бы `npm run test` целиком. Защита,
-- которая валит тестовый контур на пустом журнале, — это отказ в обслуживании,
-- а не защита.
--
-- Измерены четыре варианта прав; во всех четырёх все запреты держатся, и
-- различаются они только тем, какой рубеж отвечает отказом. Достаточно, чтобы
-- у роли было право UPDATE ХОТЯ БЫ НА ОДНУ колонку — проверка целостности
-- берёт блокировку и на этом. Поэтому выдана самая узкая осмысленная полоса:
-- колонки внешних ключей, то есть ровно те, о значениях которых и говорит
-- ограничение. Всё, что несёт СОДЕРЖАНИЕ события (action, entity_type,
-- entity_id, reason, created_at, meta, ip_address, user_agent и прочее),
-- остаётся недоступным для записи на уровне прав, а сами ключевые колонки
-- держит триггер: UPDATE любой из них отвергается им же.
--
-- У clinical_audit_logs отдельная выдача под это НЕ нужна: право
-- GRANT UPDATE (patient_id), выданное ниже ради слияния карточек, одновременно
-- закрывает и требование проверки целостности. Тот, кто однажды решит убрать
-- полосу слияния, обязан помнить, что вместе с ней сломает удаление
-- организаций, пользователей и пациентов.
--
-- Оговорка на будущее: проверка целостности исполняется от имени ВЛАДЕЛЬЦА
-- таблицы, а здесь владелец и роль приложения — одно лицо, поэтому данный
-- замер не отвечает на вопрос, понадобится ли эта выдача после разделения
-- владельца. При разделении её надо перепроверить тем же опытом, а не
-- переносить по памяти.
--
-- ============================================================================
-- ЧТО СЛОМАЕТСЯ. НАЗВАНО ЗДЕСЬ, ЧТОБЫ НЕ ИСКАЛИ ПРИЧИНУ ПОТОМ
-- ============================================================================
--
-- Четыре скрипта физически стирают журнал и после этой миграции падают с 42501:
--   scripts/seedOpsScreenshotDemo.ts:169   db.delete(auditEvents)
--   scripts/verify-migration-http.ts:477   delete from audit_events
--   scripts/verify-migration-formats.ts:545 delete from audit_events
--   scripts/verify-migration-engine.ts:479 delete from audit_events
--
-- Последствие глубже одной упавшей строки: во всех четырёх этот DELETE стоит
-- ровно перед удалением организации и существует только затем, чтобы снять
-- внешний ключ audit_events.organization_id -> organizations.id. Теперь
-- организация с историей аудита не удаляется вовсе — проверка целостности
-- отвечает 23503. Это не дефект миграции, а прямое следствие неудаляемого
-- журнала, и решать его надо на уровне модели: либо организации помечаются
-- архивными вместо удаления, либо зачистку выполняет роль, которой `dental`
-- не является. Скрипты этой миграцией сознательно не правились.
--
-- Организация БЕЗ записей аудита удаляется как прежде — это проверено
-- отдельно, потому что именно на этом держится уборка тестового контура.
--
-- ============================================================================
-- ИДЕМПОТЕНТНОСТЬ И РЕЖИМ ВЫПОЛНЕНИЯ
-- ============================================================================
--
-- CREATE OR REPLACE FUNCTION, DROP TRIGGER IF EXISTS перед CREATE TRIGGER,
-- REVOKE и GRANT — всё повторяемо; повторный прогон файла целиком проверен и
-- состояние не меняет.
--
-- Файл транзакционный (маркер no-transaction не ставится): половина
-- применённой защиты — это таблица с отозванными правами и без сторожа либо
-- наоборот, а раскатчик режет транзакционный файл только по маркеру
-- drizzle-kit, поэтому тело функции в долларовых кавычках уходит в базу целиком
-- и не рвётся по точке с запятой.

-- =============================================================================
-- 1. Универсальный сторож: любое изменение и любое удаление — отказ.
--
-- RETURN в теле сознательно нет. Для триггера BEFORE ... FOR EACH ROW возврат
-- NULL означает «молча пропустить операцию» — то есть тихий отказ, худший из
-- возможных исходов для журнала. Если однажды кто-то вырежет отсюда RAISE,
-- функция упадёт с «control reached end of trigger procedure without RETURN»,
-- то есть громко. Это выбрано намеренно.
--
-- Функция обслуживает и построчные триггеры, и триггер уровня оператора на
-- TRUNCATE, поэтому она не имеет права обращаться к OLD и NEW: в триггере
-- уровня оператора их не существует. Она к ним и не обращается.
-- =============================================================================

CREATE OR REPLACE FUNCTION audit_log_append_only_guard() RETURNS trigger
LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION
    'Журнал аудита %: операция % запрещена, таблица открыта только на дозапись',
    TG_TABLE_NAME, TG_OP
    USING ERRCODE = '42501',
          HINT = 'Записи журнала регистрации событий безопасности не изменяются и не удаляются (мера РСБ.7 приказа ФСТЭК России N 21).';
END $fn$;

-- =============================================================================
-- 2. Сторож слияния карточек для clinical_audit_logs.
--
-- Пропускает ровно один вид UPDATE: перестановку patient_id с одного
-- существующего пациента организации на другого. Всё прочее — отказ.
--
-- Порядок проверок важен и выбран так, чтобы сообщение об отказе называло
-- настоящую причину, а не первую попавшуюся.
--
-- Проверка организации читает patients под действующими политиками RLS, а не в
-- обход них. Это не упущение: слияние всегда выполняется в тенант-контексте
-- (withTenantCtx в patientMerge.ts), поэтому основная карточка ему видна, а
-- попытка переставить ссылку на пациента, которого текущий контекст не видит,
-- обязана быть отвергнута — это и есть смысл проверки.
-- =============================================================================

CREATE OR REPLACE FUNCTION clinical_audit_logs_merge_guard() RETURNS trigger
LANGUAGE plpgsql AS $fn$
BEGIN
  IF to_jsonb(NEW) - 'patient_id' IS DISTINCT FROM to_jsonb(OLD) - 'patient_id' THEN
    RAISE EXCEPTION
      'Журнал аудита clinical_audit_logs: содержимое записи изменять запрещено'
      USING ERRCODE = '42501',
            HINT = 'В записи журнала допустима единственная правка — перестановка patient_id при слиянии карточек пациента.';
  END IF;

  IF NEW.patient_id IS NOT DISTINCT FROM OLD.patient_id THEN
    RAISE EXCEPTION
      'Журнал аудита clinical_audit_logs: операция UPDATE запрещена, таблица открыта только на дозапись'
      USING ERRCODE = '42501';
  END IF;

  IF OLD.patient_id IS NULL OR NEW.patient_id IS NULL THEN
    RAISE EXCEPTION
      'Журнал аудита clinical_audit_logs: ссылку patient_id можно переставить, но не стереть и не проставить задним числом'
      USING ERRCODE = '42501';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM patients p
     WHERE p.id = NEW.patient_id
       AND p.organization_id = OLD.organization_id
  ) THEN
    RAISE EXCEPTION
      'Журнал аудита clinical_audit_logs: patient_id можно переставить только на существующего пациента той же организации'
      USING ERRCODE = '42501';
  END IF;

  RETURN NEW;
END $fn$;

-- =============================================================================
-- 3. audit_events — неизменяем полностью.
--
-- Триггер на TRUNCATE отдельный: построчный сторож этой команды не видит.
