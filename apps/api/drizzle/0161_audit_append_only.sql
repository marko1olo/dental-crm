-- =============================================================================
-- 5. Права.
--
-- INSERT и SELECT не трогаются ни одной командой ниже: журнал обязан остаться
-- записываемым и читаемым, иначе защита превращается в отказ в обслуживании.
-- REFERENCES и TRIGGER тоже остаются — они не дают ни изменить, ни удалить
-- строку, а их отзыв сломал бы будущие внешние ключи и саму эту миграцию при
-- повторном прогоне.
--
-- GRANT на колонки идёт СТРОГО ПОСЛЕ REVOKE на таблицу: обратный порядок снёс
-- бы только что выданное право, потому что табличный REVOKE снимает и
-- колоночные. Обоснование каждой из двух выдач — в разделах выше: колонки
-- внешних ключей нужны проверке целостности при удалении родителя,
-- clinical_audit_logs.patient_id — слиянию карточек пациента.
-- =============================================================================

REVOKE UPDATE, DELETE, TRUNCATE ON "audit_events" FROM dental;
REVOKE UPDATE, DELETE, TRUNCATE ON "clinical_audit_logs" FROM dental;
GRANT UPDATE ("organization_id", "actor_user_id") ON "audit_events" TO dental;
GRANT UPDATE ("patient_id") ON "clinical_audit_logs" TO dental;
