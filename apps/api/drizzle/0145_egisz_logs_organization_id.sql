-- ─────────────────────────────────────────────────────────────────────────────
-- egisz_logs.organization_id: журнал обмена с ЕГИСЗ принадлежит клинике.
--
-- ЗАЧЕМ. Таблица создана миграцией 0000 (строки 521-529) с семью колонками, и
-- принадлежности клинике среди них нет:
--     id, patient_id, visit_id, status, transaction_id, error_details, created_at
-- Это журнал передачи медицинских данных в государственную систему: каждая
-- строка называет пациента и приём, а поле error_details хранит ответ ЕГИСЗ с
-- подробностями отказа. В многопользовательской базе такая таблица либо
-- принадлежит клинике, либо является дырой в изоляции арендаторов — любой
-- запрос к журналу возвращал бы строки всех клиник сразу, и первая же выборка
-- «что мы отправили» показала бы чужих пациентов. Фильтровать было нечем:
-- запрос по organization_id падал с «column "organization_id" does not exist».
--
-- ЧТО С СУЩЕСТВУЮЩИМИ СТРОКАМИ. На момент написания их ноль
-- (select count(*) from egisz_logs → 0), поэтому NOT NULL применяется без
-- какого-либо переноса данных. Порядок «дозаполнить, затем NOT NULL» всё равно
-- соблюдён, как в миграции 0119: файл должен примениться и на установке, где
-- журнал не пуст, а не только на пустой базе. Источник принадлежности —
-- patient_id: он NOT NULL, у него внешний ключ на patients с ON DELETE CASCADE,
-- а patients.organization_id объявлен NOT NULL, то есть у любой строки журнала
-- владелец восстанавливается однозначно и без догадок. DEFAULT не ставится
-- намеренно: подставленная «клиника по умолчанию» приписала бы одной клинике
-- отчётность другой, и это было бы хуже отсутствия колонки — ошибка стала бы
-- невидимой.
--
-- Безопасно применять повторно.
-- ─────────────────────────────────────────────────────────────────────────────

-- 1. Колонка появляется допускающей NULL, иначе ALTER упал бы на непустом
--    журнале до того, как принадлежность будет восстановлена.
ALTER TABLE "egisz_logs"
  ADD COLUMN IF NOT EXISTS "organization_id" uuid;

-- 2. Восстановление принадлежности по пациенту приёма.
UPDATE "egisz_logs" AS el
SET "organization_id" = p."organization_id"
FROM "patients" AS p
WHERE el."organization_id" IS NULL
  AND p."id" = el."patient_id";

-- 3. Внешний ключ на организацию — как у соседей по домену
--    (egisz_blank_permissions, external_schedule_action_logs): удалённая
--    организация не должна оставлять журнал с ссылкой в никуда.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'egisz_logs_organization_id_organizations_id_fk'
  ) THEN
    ALTER TABLE "egisz_logs"
      ADD CONSTRAINT "egisz_logs_organization_id_organizations_id_fk"
      FOREIGN KEY ("organization_id") REFERENCES "organizations"("id");
  END IF;
END $$;

-- 4. Только теперь запрет NULL. Если на какой-то установке шаг 2 не заполнил
--    все строки, ALTER упадёт здесь — это верное поведение: строку журнала без
--    известного владельца нельзя ни оставить видимой всем, ни приписать
--    наугад, и разбирать такой случай нужно руками.
ALTER TABLE "egisz_logs"
  ALTER COLUMN "organization_id" SET NOT NULL;
