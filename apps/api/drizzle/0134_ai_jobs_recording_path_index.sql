-- 0134 — у ai_jobs не было ни одного индекса кроме первичного ключа, поэтому
-- каждый фрагмент диктовки стоил последовательное чтение всей таблицы.
--
-- ЧТО БЫЛО СЛОМАНО. pg_indexes по ai_jobs отдавал ровно одну строку:
-- «CREATE UNIQUE INDEX ai_jobs_pkey ON public.ai_jobs USING btree (id)».
-- А долговременное хранилище диктовки ищет строку записи НЕ по id: и чтение
-- конверта (apps/api/src/speech/storage.ts loadDurableRecordingEnvelope), и его
-- перезапись (persistSpeechRecording) фильтруют по паре
-- (organization_id, input_storage_path). EXPLAIN (ANALYZE, BUFFERS) этого
-- предиката давал «Seq Scan on ai_jobs», то есть на КАЖДЫЙ фрагмент диктовки
-- приходилось два последовательных чтения таблицы — одно на чтение конверта,
-- одно на его обновление. Замер ревьюера на одной записи из 200 фрагментов:
-- среднее время первых двадцати 3.3 мс, последних двадцати 10.45 мс (рост в
-- 3.2 раза), самый медленный фрагмент 24 мс, переписано около 43 МБ. И это при
-- ПУСТОЙ таблице ai_jobs: слагаемое последовательного чтения тогда стоило почти
-- ноль. Оно перестанет быть бесплатным, как только в той же таблице накопятся
-- задания paper_ocr, image_summary и document_draft — у них тот же ai_jobs.
--
-- ПОЧЕМУ ИНДЕКС УНИКАЛЬНЫЙ. Вторая, независимая причина. На запись диктовки по
-- замыслу приходится РОВНО ОДНА строка, и код это подразумевает: сначала
-- UPDATE ... WHERE organization_id AND input_storage_path, и только если он
-- ничего не обновил — INSERT. Без уникального индекса это ничем не защищено, а
-- у UPDATE нет LIMIT: две строки с одним путём (гонка двух процессов на первом
-- фрагменте записи) были бы обе перезаписаны одним конвертом, то есть текст
-- второй строки уничтожался бы целиком, а не «терялись бы её фрагменты».
-- Уникальный индекс превращает эту гонку в громкий отказ записи, который код
-- уже умеет показывать врачу (предупреждение «Фрагмент не сохранен в базу»), и
-- при следующем фрагменте текст доезжает через слияние с сохранённым конвертом.
--
-- ПОЧЕМУ ЭТО НЕ ЛОМАЕТ ВТОРОГО АВТОРА ТАБЛИЦЫ. В ai_jobs пишет ещё
-- apps/api/src/db/aiQuery.ts createAiRecognitionJobInDb — он input_storage_path
-- не заполняет вообще, то есть оставляет NULL. В btree-индексе без
-- NULLS NOT DISTINCT значения NULL считаются различными, поэтому сколько угодно
-- его строк в одной организации уникальности не нарушают. Проверено по живой
-- базе: строк с input_storage_path = '' нет, строк с NULL уникальность не
-- задевает, а групп-дубликатов (organization_id, input_storage_path) с непустым
-- путём — ноль.
--
-- ПОЧЕМУ НЕ CONCURRENTLY. Свой мигратор (apps/api/src/scripts/migrate.ts)
-- выполняет файл целиком в ОДНОЙ транзакции, а CREATE INDEX CONCURRENTLY внутри
-- транзакции запрещён Postgres. Таблица маленькая, обычного CREATE INDEX
-- достаточно; если она когда-нибудь вырастет до размеров, при которых
-- блокировка записи на время построения недопустима, индекс надо будет
-- пересоздавать отдельной операцией вне мигратора.
--
-- ПОЧЕМУ ПРОВЕРКА ДУБЛИКАТОВ ОТДЕЛЬНЫМ БЛОКОМ. На чужой базе дубликаты могли
-- успеть появиться до этого индекса. Тогда CREATE UNIQUE INDEX падает
-- сообщением про «could not create unique index», по которому непонятно, что
-- делать. Ниже он падает сообщением, которое называет число конфликтующих
-- групп и говорит прямо: строки надо слить руками, потому что в каждой из них
-- лежит медицинский текст, и выбрать за администратора, какую удалить, миграция
-- права не имеет.

DO $$
DECLARE
  conflicting_groups integer;
BEGIN
  SELECT count(*) INTO conflicting_groups
  FROM (
    SELECT 1
    FROM ai_jobs
    WHERE input_storage_path IS NOT NULL
    GROUP BY organization_id, input_storage_path
    HAVING count(*) > 1
  ) duplicates;

  IF conflicting_groups > 0 THEN
    RAISE EXCEPTION
      'Уникальный индекс ai_jobs_organization_storage_path_key не создан: групп строк с одинаковым (organization_id, input_storage_path) — %. В каждой такой строке лежит распознанный текст, поэтому миграция не удаляет их сама. Слейте конверты вручную и повторите.',
      conflicting_groups;
  END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS "ai_jobs_organization_storage_path_key"
  ON "ai_jobs" ("organization_id", "input_storage_path");
