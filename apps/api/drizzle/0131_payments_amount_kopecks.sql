-- 0131 — касса научилась принимать копейки.
--
-- ЧТО БЫЛО. payments.amount_rub объявлена integer, схема API требует
-- z.number().int(), а поле ввода на экране пропускает только цифры без
-- разделителя и отвечает «укажите сумму целыми рублями без копеек». То есть
-- клиника не могла принять ни 1500,50, ни 0,50 — ни через интерфейс, ни через
-- API. Проверено живьём (scratch/verify-money-kopecks.mjs): дробная сумма даёт
-- 400, в базу не попадает. Денег не теряли — но и принять их не могли.
--
-- ПОЧЕМУ numeric(12,2), А НЕ ЦЕЛЫЕ КОПЕЙКИ. Колонка называется amount_rub и
-- хранит рубли; переводить её в копейки означало бы умножить смысл всех
-- существующих значений на сто, то есть переписать данные и одновременно все
-- места чтения и записи — на деньгах это неоправданный риск. numeric(12,2)
-- сохраняет каждое существующее значение как есть (1500 становится 1500.00),
-- название колонки остаётся правдой, а копейки становятся представимы точно.
-- Тип точный десятичный, а не двоичный: 0.01 хранится ровно как 0.01.
-- Ровно так же уже объявлены 31 денежная колонка в этой базе, включая
-- cash_ledger.amount_rub и patient_invoices.total_rub.
--
-- ДЕЛЕНИЕ БЕЗ ПОТЕРЬ. Проверено запросом к базе: 1000.00 / 3 даёт по 333.33 при
-- остатке 333.34, то есть сумма частей равна целому до копейки.
--
-- ЧТО ЕЩЁ ПОТРЕБОВАЛОСЬ. Драйвер node-postgres отдаёт numeric строкой, поэтому
-- одновременно с этой миграцией включён разбор типа в
-- apps/api/src/db/moneyTypeParsers.ts — иначе суммы начали бы склеиваться
-- вместо сложения.
--
-- ОСТАЛЬНЫЕ 15 ЦЕЛОЧИСЛЕННЫХ ДЕНЕЖНЫХ КОЛОНОК не тронуты этой миграцией
-- намеренно: единица измерения у них та же (рубли), поведение прежнее, а
-- переводить их надо тем же приёмом и с такой же живой проверкой каждой.
-- Список в отчёте отрезка.

ALTER TABLE "payments"
  ALTER COLUMN "amount_rub" TYPE numeric(12, 2) USING "amount_rub"::numeric(12, 2);
