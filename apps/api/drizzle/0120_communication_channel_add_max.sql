-- communication_channel: добавляем значение 'max'.
--
-- ЗАЧЕМ: db/schema.ts объявляет перечисление как
--     ["phone","sms","whatsapp","telegram","email","in_person","vk","max"]
-- а физический тип в базе содержит только первые семь значений. Из-за этого
-- routes/max.ts записывал сообщения мессенджера MAX с channel = 'telegram' и
-- комментарием «map max to telegram channel in DB schema»: вставка настоящего
-- значения упала бы. В истории коммуникаций переписка из MAX неотличима от
-- Telegram — отчёты по каналам и разбор конфликтных ситуаций врут.
--
-- ADD VALUE IF NOT EXISTS идемпотентен и безопасен при повторном применении.
-- Выполняется вне явной транзакции: до PostgreSQL 12 ALTER TYPE ... ADD VALUE
-- внутри транзакции запрещён, а раннер применяет файлы по одному.
-- ─────────────────────────────────────────────────────────────────────────────

ALTER TYPE "communication_channel" ADD VALUE IF NOT EXISTS 'max';
