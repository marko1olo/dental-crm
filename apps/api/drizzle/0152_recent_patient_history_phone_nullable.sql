-- =============================================================================
-- Журнал «недавние пациенты» не должен требовать телефон, которого у пациента нет.
--
-- recent_patient_history — денормализованный журнал «кого кассир/врач смотрел
-- последним». Колонка phone копируется из patients.phone, а она в объявлении
-- НЕ обязательна (text("phone") без .notNull()) — пациент может законно не иметь
-- телефона.
--
-- ЧТО ЛОМАЛОСЬ. Миграция 0076 создала колонку "phone" text NOT NULL. Писатель
-- recordPatientViewInDb (apps/api/src/db/recentPatientHistoryQuery.ts) пишет
-- `phone: patient.phone ?? null` — т.е. сознательно NULL для безтелефонного
-- пациента. Такая вставка падает с NOT NULL violation на колонке, и запись в
-- журнал недосчитывает безтелефонных пациентов.
--
-- КАК РЕШЕНО. Право на стороне объявления: модель уже объявляет phone
-- необязательной, данных «нужен телефон» в колонке нет (NULL-пациент легитимен),
-- поэтому база приводится к объявлению — DROP NOT NULL. Ни DROP таблицы, ни
-- перезапись, ни backfill не выполняются: ограничение снимается без следа в
-- данных.
--
-- Сторож расхождения в schemaMatchesLiveDatabase.test.ts уже знал этот разрыв:
-- `recent_patient_history.phone` числится в notNullInDatabase (в базе NOT NULL,
-- в модели необязательна). После применения миграции запись убирается из реестра
-- тем же коммитом, что и сама миграция — иначе сторож падает.
--
-- Обратная правка — ALTER COLUMN ... SET NOT NULL, только если когда-нибудь
-- появится бизнес-требование «у недавнего пациента обязан быть телефон».
-- =============================================================================

ALTER TABLE "recent_patient_history" ALTER COLUMN "phone" DROP NOT NULL;
