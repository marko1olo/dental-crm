-- 0139 — набор включённых модулей стал храниться в базе.
--
-- ЧТО БЫЛО. Модульность — сердце продукта: соло-врач не должен видеть склад,
-- зарплаты, воронку обращений и аналитику, мелкая клиника видит своё, сеть
-- филиалов своё. Мастер первого запуска спрашивает про это, и в настройках есть
-- вкладка «Модули». Но на сервере этого не существовало вовсе:
--
--   GET /api/workspace/profile возвращал ЖЁСТКО ПРОПИСАННУЮ константу — все
--     девятнадцать признаков true, пресет "enterprise", onboardingCompleted true,
--     одинаково для любой клиники;
--   POST /api/workspace/profile разбирал из тела семнадцать признаков и не писал
--     НИ ОДНОГО: `.set({ updatedAt: new Date() })` — и отвечал { ok: true }.
--
-- Что видел пользователь. В браузере всё «работало»: хранилище на клиенте
-- (useWorkspaceProfile) сохраняет выбор в localStorage, поэтому переключатели
-- держались. Но:
--   на втором устройстве, в другом браузере и после чистки данных клиника снова
--     получала все модули включёнными;
--   выбор, сделанный в мастере первого запуска, не доживал до сервера;
--   у второго сотрудника той же клиники набор модулей был свой собственный,
--     потому что localStorage у каждого свой;
--   ответ { ok: true } на «Сохранить» был неправдой.
--
-- ПОЧЕМУ ОДНА КОЛОНКА jsonb, А НЕ ДЕВЯТНАДЦАТЬ boolean. Набор признаков меняется
-- вместе с продуктом: за ночь в него уже добавляли hasBpmWorkflows,
-- hasClinicalRules, hasReferralModule. Девятнадцать колонок означали бы миграцию
-- на каждый новый переключатель и рассинхронизацию с типом на клиенте. Признаки
-- читаются и пишутся целиком, по одному не выбираются, поиска и сортировки по ним
-- нет — то есть ровно тот случай, для которого jsonb и нужен.
--
-- ДАННЫЕ. Колонка новая и допускает пустое значение. Пустое значение означает
-- «клиника ещё не настраивалась» и читается как прежние умолчания, поэтому у
-- существующих организаций ничего не меняется.

ALTER TABLE "organizations"
  ADD COLUMN IF NOT EXISTS "workspace_feature_flags" jsonb;
