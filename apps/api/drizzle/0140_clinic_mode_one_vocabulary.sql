-- 0140 — режим клиники стал одним перечислением вместо трёх разных.
--
-- ЧТО БЫЛО СЛОМАНО. Модульность (соло-врач не видит того, что ему не нужно) —
-- это колонка organizations.clinic_mode. На неё в проекте было ТРИ несовпадающих
-- словаря, и ни один не пересекался с остальными:
--
--   packages/shared/src/index.ts:797  solo_doctor | one_chair | small_clinic | network_clinic
--                                     — единственный, у которого есть тип, Zod-схема
--                                       и таблица возможностей в интерфейсе;
--   apps/api/src/db/schema.ts:228     DEFAULT 'demo', а в комментарии рядом
--                                     «demo, single, network»;
--   routes/workspaceProfile.ts:684    мастер первого запуска писал 'single' / 'network';
--   scripts/setup-fresh-db.ts:92      разворачивание чистой базы писало 'single'.
--
-- Следствие, измеренное на живой базе перед этой миграцией: 2 организации из 2,
-- то есть ВСЕ, лежали со значением 'demo' — вне перечисления. И это не старые
-- данные, а УМОЛЧАНИЕ КОЛОНКИ ('demo'::text), то есть каждая будущая клиника
-- рождалась бы вне перечисления тоже.
--
-- Почему этого никто не видел. Значение вне перечисления молча подменялось при
-- чтении, причём в двух местах по-разному: db/domainStateHydration.ts:350 сводил
-- его к 'one_chair' (этот путь питает главный экран и рельсу меню), а
-- db/settingsQuery.ts:39 — к 'solo_doctor' (этот путь питает экран настроек).
-- Одна и та же клиника в один и тот же момент была в разном режиме в зависимости
-- от того, какой запрос спросил. А режим 'solo_doctor' был недостижим в работе:
-- в базу его не писал никто, кроме экрана настроек, а любое подтверждение вида
-- «у отдельного врача это скрыто» проверить было нечем.
--
-- ПРАВИЛО ПЕРЕНОСА СУЩЕСТВУЮЩИХ СТРОК. Считается по тому, что в базе ЕСТЬ, а не
-- по догадке (.agents/AGENTS.md §10: чего нет — записываем долгом, не выдумываем):
--
--   1. значение уже из перечисления — не трогаем вовсе;
--   2. филиалов (clinics) больше одного -> 'network_clinic'. Несколько адресов —
--      единственный признак сети, который база вообще несёт;
--   3. иначе активных кресел больше одного ИЛИ активных врачей больше одного ->
--      'small_clinic'. Оба признака означают «работают одновременно несколько»,
--      а именно это отличает клинику от кабинета;
--   4. иначе -> 'one_chair'. Это документированное умолчание для случая, когда
--      данных не хватает, чтобы отличить одно от другого.
--
-- ПОЧЕМУ МИГРАЦИЯ НИКОГДА НЕ СТАВИТ 'solo_doctor'. База не различает «врач
-- работает один» и «клинику ещё не заполнили»: у организации без сотрудников и у
-- настоящего соло-врача одни и те же нули. 'solo_doctor' — самый узкий режим, он
-- убирает рассылки по базе, разрез по врачам, занятость кресел, продвижение и
-- воронку обращений. Поставить его по ОТСУТСТВИЮ данных значит отнять разделы у
-- клиники, которая просто не успела завести кресла, и человек будет искать
-- пропавшее меню. Обратная ошибка дешевле: лишний раздел заметят и выключат.
-- Этот режим ставит либо мастер первого запуска (он прямо спрашивает про кресла и
-- состав команды), либо человек на вкладке настроек клиники.
--
-- ПОЧЕМУ ПОЯВЛЯЕТСЯ CHECK, А НЕ ТОЛЬКО ИСПРАВЛЕНИЕ ДАННЫХ. Подмена при чтении
-- прятала расхождение всю кампанию. Пока колонка — свободный text, следующий
-- писатель заведёт четвёртый словарь так же незаметно, как это сделали
-- предыдущие три. С ограничением такая запись падает в момент записи и с именем
-- виноватого значения, а не через полгода в виде «почему у всех одинаковое меню».
-- Проверка ограничением — не замена проверке в коде: enum остаётся в
-- clinicModeSchema, ограничение лишь запрещает базе хранить то, чего в нём нет.

-- 1. Существующие строки — по правилу выше.
WITH shape AS (
  SELECT o.id,
         o.clinic_mode,
         (SELECT count(*) FROM clinics c WHERE c.organization_id = o.id) AS clinic_count,
         (SELECT count(*) FROM chairs ch WHERE ch.organization_id = o.id AND ch.is_active) AS chair_count,
         (SELECT count(*) FROM users u WHERE u.organization_id = o.id AND u.is_active AND u.role = 'doctor') AS doctor_count
    FROM organizations o
)
UPDATE organizations AS o
   SET clinic_mode = CASE
         WHEN shape.clinic_count > 1 THEN 'network_clinic'
         WHEN shape.chair_count > 1 OR shape.doctor_count > 1 THEN 'small_clinic'
         ELSE 'one_chair'
       END,
       updated_at = now()
  FROM shape
 WHERE shape.id = o.id
   AND o.clinic_mode NOT IN ('solo_doctor', 'one_chair', 'small_clinic', 'network_clinic');

-- 2. Умолчание колонки. Клиника, ещё не прошедшая мастер первого запуска,
--    рождается в «одном кабинете»: это самый узкий режим, который НЕ убирает
--    отчёты руководителю и настройки, то есть не отнимает у новой клиники те
--    экраны, через которые она себя и настраивает.
ALTER TABLE "organizations"
  ALTER COLUMN "clinic_mode" SET DEFAULT 'one_chair';

-- 3. Запрет на четвёртый словарь. Имя проверки называет предмет, чтобы в тексте
--    ошибки Postgres было видно, о чём речь.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'organizations_clinic_mode_known'
  ) THEN
    ALTER TABLE "organizations"
      ADD CONSTRAINT "organizations_clinic_mode_known"
      CHECK ("clinic_mode" IN ('solo_doctor', 'one_chair', 'small_clinic', 'network_clinic'));
  END IF;
END $$;
