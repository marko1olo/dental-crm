-- 0132 — назначение сообщения «ответ на обращение пациента».
--
-- ЗАЧЕМ. Пациент пишет «СТОП». Согласие отзывается, сообщения прекращаются — и
-- пациент об этом НЕ УЗНАЁТ: текст подтверждения в проекте написан
-- (services/communications/optOut.ts, optOutAcknowledgement) и не отправляется
-- никуда, кроме теста. С точки зрения человека это выглядит так: он попросил
-- перестать, ему не ответили, а через неделю пришло напоминание о приёме
-- (служебное — оно разрешено). Вывод пациента: его игнорируют. Дальше жалоба.
--
-- ПОЧЕМУ НЕЛЬЗЯ ПОСЛАТЬ ЭТО КАК ОБЫЧНОЕ СЛУЖЕБНОЕ СООБЩЕНИЕ. Два препятствия,
-- и оба правильные для рассылок:
--   1. Согласие только что отозвано, и проверка в диспетчере закономерно
--      запретит отправку по этому каналу.
--   2. Тихие часы отложили бы отправку до утра, а пациент написал сейчас и
--      ждёт ответа сейчас.
--
-- ПОЧЕМУ ЭТО ЗАКОННО. ФЗ «О рекламе» ст. 18 ч. 1 требует согласия на
-- РАСПРОСТРАНЕНИЕ РЕКЛАМЫ по сетям связи. Ответ на прямое обращение человека —
-- не реклама и не рассылка: инициатива принадлежит ему, содержание сводится к
-- подтверждению его же просьбы. Отдельное назначение нужно именно для того,
-- чтобы это исключение было явным, узким и видимым в журнале, а не
-- подмешивалось в служебные сообщения общим флагом.
--
-- Значения enum в PostgreSQL не удаляются, поэтому имя выбрано общее:
-- transactional_reply подойдёт и для будущих ответов на обращения (например,
-- подтверждения записи, сделанной пациентом самостоятельно).

ALTER TYPE "communication_intent" ADD VALUE IF NOT EXISTS 'transactional_reply';
