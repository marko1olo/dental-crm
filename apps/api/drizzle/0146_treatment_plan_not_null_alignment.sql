-- =============================================================================
-- Сведение базы с объявлением там, где право на стороне объявления.
--
-- Пять колонок объявлены в apps/api/src/db/schema.ts обязательными, а база
-- разрешала в них NULL. Остальные расхождения той же волны сведены правкой
-- объявления (право было на стороне базы); здесь ровно те, где обязательность
-- нужна САМИМ ДАННЫМ. Разбор с замерами: .agents/lead/recon-schema-vs-live-database.md.
--
-- ПОЧЕМУ ЭТО НЕ СТОИТ НИ ОДНОЙ СТРОКИ. Проверено на живой базе 2026-07-29,
-- ДО применения:
--     treatment_plans           rows=0  organization_id NULL=0  title NULL=0
--     treatment_plan_items_new  rows=0  price_id NULL=0  created_at NULL=0
--     patient_ct_plannings      rows=1  plan_status NULL=0
-- То есть SET NOT NULL нечего отвергать: NULL-строк нет ни в одной из пяти
-- колонок. Ни DROP, ни перезапись, ни backfill не выполняются. Обратная правка —
-- ALTER COLUMN ... DROP NOT NULL, без следа в данных.
--
-- У ЧЕТЫРЁХ ИЗ ПЯТИ КОЛОНОК УЖЕ ЕСТЬ УМОЛЧАНИЕ В БАЗЕ (title = '',
-- created_at = now(), plan_status = 'draft'), поэтому вставка через drizzle не
-- могла записать в них NULL и раньше: ограничение закрывает путь через сырой SQL
-- и через чужой клиент, а не меняет поведение приложения.
-- =============================================================================

-- ПЛАН ЛЕЧЕНИЯ БЕЗ КЛИНИКИ — САМОЕ ДОРОГОЕ ИЗ ПЯТИ.
--
-- treatment_plans.organization_id допускал NULL, а план лечения — это
-- медицинский документ с суммой и подписью пациента. Бесхозная строка одинаково
-- открыта любому арендатору базы: выборка вида
-- `organization_id = :orgId OR organization_id IS NULL` отдала бы её первой
-- обратившейся клинике вместе с деньгами и составом лечения. Прецедент дословный
-- и уже оплаченный: ровно так бесхозная семейная группа вместе с балансом
-- семейного кошелька досталась чужой клинике, и это закрывала миграция 0119
-- (family_groups.organization_id). Изоляция по клинике — правило №2
-- .agents/DATABASE.md и самое нарушаемое правило репозитория.
ALTER TABLE "treatment_plans" ALTER COLUMN "organization_id" SET NOT NULL;

-- Заголовок плана: умолчание '' в базе есть, объявление требует значение.
ALTER TABLE "treatment_plans" ALTER COLUMN "title" SET NOT NULL;

-- Позиция сметы без ссылки на прайс — строка, которую нечем сопоставить с
-- услугой: ни цену проверить, ни начисление врачу посчитать. Объявление
-- .notNull() уже держит это в типах, и на него прямо опирается
-- services/tests/recallScheduler.test.ts.
ALTER TABLE "treatment_plan_items_new" ALTER COLUMN "price_id" SET NOT NULL;

-- Время создания позиции сметы: умолчание now() в базе есть.
ALTER TABLE "treatment_plan_items_new" ALTER COLUMN "created_at" SET NOT NULL;

-- Статус разметки планирования имплантации: умолчание 'draft' в базе есть.
-- Разметка операции без статуса не имеет смысла — по нему хирург отличает
-- черновик от подтверждённого плана установки имплантов.
ALTER TABLE "patient_ct_plannings" ALTER COLUMN "plan_status" SET NOT NULL;
