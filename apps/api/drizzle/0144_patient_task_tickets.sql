-- Задачи (поручения) по карте пациента.
--
-- ЗАЧЕМ. Экран карточки пациента полностью готов и написан честно:
-- apps/web/src/components/patients/PatientTaskTicketsWidget.tsx разводит
-- загрузку, отказ чтения и пустоту, сбрасывает начатую задачу при переходе на
-- другого пациента и прямо говорит об этом («чужое поручение не должно попасть в
-- эту карту»), а при отказе записи обещает, что введённый текст остался в форме.
-- Сервера под ним не было вовсе: живая проверка сети
-- scratch/probe-failed-requests.mjs показала 404 на GET .../tickets. Админстратор
-- нажимал «Создать задачу», получал отказ и не имел ни одного способа поручить
-- «перезвонить по отёку» или «дослать снимок». Задача по пациенту — это
-- перезвонить, дослать документы, проверить самочувствие; потерянное поручение
-- означает несделанный звонок больному человеку.
--
-- Долг был записан в apps/api/src/tests/webCallsExistingRoutes.test.ts строкой
-- «Задачи по пациенту: ни маршрута, ни таблицы» — на этот раз долг описан ВЕРНО,
-- в отличие от соседней записи про рекламации. Строка снята вместе с миграцией.
--
-- РЕШЕНИЯ ПО СТОЛБЦАМ. Имена полей повторяют то, что экран уже отправляет и
-- читает (title, description, assignedToId, status, createdAt): выдумывать свой
-- контракт поверх работающего клиента значило бы сломать его молча.
CREATE TABLE IF NOT EXISTS "patient_task_tickets" (
	"id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
	-- Изоляция клиники здесь не удобство: поручение называет пациента по имени и
	-- диагнозу, и утечка его в другую клинику — разглашение врачебной тайны.
	"organization_id" uuid NOT NULL REFERENCES "organizations"("id"),
	"patient_id" uuid NOT NULL REFERENCES "patients"("id") ON DELETE CASCADE,
	-- Ответственный сотрудник. Без внешнего ключа намеренно, как и врач в
	-- рекламациях: сотрудника могут уволить и удалить из штата, а поручение
	-- обязано остаться в карте вместе с историей. Экран уже умеет показать
	-- «Неизвестный сотрудник», если сотрудник не найден в списке.
	"assigned_to_id" uuid,
	"title" text NOT NULL,
	"description" text,
	-- Ровно два значения, которыми пользуется экран: в работе и выполнена.
	-- Ограничение стоит в самой базе, чтобы третье значение не прошло мимо
	-- проверки на сервере и не осталось навсегда невидимым в интерфейсе: экран
	-- считает «в работе» строгим сравнением со 'pending', и любое иное значение
	-- выглядело бы выполненной задачей.
	"status" text NOT NULL DEFAULT 'pending',
	-- Важность экран отправляет ('normal'), но пока не показывает. Хранится без
	-- CHECK: полный набор значений продукта неизвестен, а придумывать его здесь
	-- значило бы навязать базе перечень, которого никто не согласовывал.
	"priority" text NOT NULL DEFAULT 'normal',
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	"updated_at" timestamp with time zone DEFAULT now() NOT NULL,
	CONSTRAINT "patient_task_tickets_status_check" CHECK ("status" IN ('pending', 'completed'))
);

-- Список всегда читают по одной карте и всегда в порядке «свежие сверху».
CREATE INDEX IF NOT EXISTS "patient_task_tickets_patient_idx"
	ON "patient_task_tickets" ("organization_id", "patient_id", "created_at" DESC);
