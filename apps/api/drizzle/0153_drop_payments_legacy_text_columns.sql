-- =============================================================================
-- Убрать мёртвые текстовые колонки legacy из payments.
--
-- Живая база (information_schema, замерено 2026-08-04) держит в payments сразу
-- две пары «способ/статус»:
--   • method payment_method (enum),  status payment_status (enum) — ОБЪЯВЛЕНЫ в
--     schema.ts и используются всем кодом (billing.ts, billingQuery.ts и др.);
--   • payment_method text (nullable), payment_status text (nullable) — КОЛОНКИ,
--     которых нет в модели drizzle. Через drizzle они недостижимы: ключ, которого
--     нет в форме таблицы, он в запрос не переносит — ни на запись, ни на чтение.
--
-- ЧТО ЭТО. След прежней схемы, где способ/статус хранились текстом; при переходе
-- на enum-колонки старые текстовые остались брошенными. Проверено: на колонки
-- НЕТ ни констрейнтов, ни индексов; таблица пуста (0 строк), обе колонки на 100%
-- NULL; код нигде их не читает и не пишет (grep по всему apps/api — ноль совпадений).
--
-- ПОЧЕМУ DROP, А НЕ ОБЪЯВЛЕНИЕ В МОДЕЛИ. Право на стороне объявления: enum-пары
-- method/status — источник истины. Объявлять text-дубли в модели значит закрепить
-- двусмысленность и дать писателю две колонки на одно значение. Потерять нечего —
-- данных в них нет.
--
-- Безопасность: DROP COLUMN на пустых колонках без зависимостей. Обратная правка
-- не требуется — добавление text-колонок обратно ничего не восстанавливает.
--
-- Сторож schemaMatchesLiveDatabase.test.ts фиксировал эти две колонки как
-- НОВОЕ расхождение undeclaredInModel (payments.payment_method,
-- payments.payment_status). После применения миграции расхождение исчезает.
-- =============================================================================

ALTER TABLE "payments" DROP COLUMN IF EXISTS "payment_method";
ALTER TABLE "payments" DROP COLUMN IF EXISTS "payment_status";
