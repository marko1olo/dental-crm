-- Индекс по арендатору для `clinic_workflows`.
--
-- ЧТО ЗДЕСЬ БЫЛО И ПОЧЕМУ УБРАНО. Файл создавался как «добавить clinic_workflows»
-- и содержал `CREATE TABLE IF NOT EXISTS` на семь колонок плюс внешний ключ.
-- Обе части — ПУСТЫШКИ, проверено чтением миграций:
--
--   * таблица создаётся в `0008_add_settings.sql:5` с тем же составом колонок.
--     Номер 0008 меньше, значит на чистой базе она уже существует к моменту
--     0165, и `IF NOT EXISTS` пропускает блок целиком. Объявленные здесь
--     `varchar(255)` вместо `text` и `uuidv7()` вместо `gen_random_uuid()`
--     не применились бы НИКОГДА — ни на чистой базе, ни на рабочей.
--     Молчаливо пропущенный `CREATE TABLE` выглядит как выполненная работа:
--     миграция отрабатывает без ошибки, а состав таблицы остаётся прежним.
--
--   * внешний ключ на `organizations` уже создан в `0008:16` под тем же именем
--     `clinic_workflows_organization_id_organizations_id_fk`. Повторный
--     `ADD CONSTRAINT` перехватывается `WHEN duplicate_object THEN null`,
--     то есть тоже ничего не делает. Заявленное здесь `ON DELETE cascade`
--     фактическое `ON DELETE no action` из 0008 не заменило бы.
--
-- RLS ТРОГАТЬ НЕ НУЖНО, и это не упущение: `0159_rls_force_and_write_check.sql`
-- :630-633 уже включает `ROW LEVEL SECURITY`, добавляет `FORCE` и заводит
-- политику `tenant_isolation` с `USING` и `WITH CHECK`. Повторять здесь значило
-- бы завести вторую копию правила изоляции — расхождение таких копий в этом
-- проекте уже приводило к молчаливой потере проверок.
--
-- Осталось единственное действие, которое реально что-то меняет: индекс.
-- Он нужен потому, что политика арендатора фильтрует по `organization_id` в
-- каждом запросе, и без индекса это последовательный проход по таблице.
CREATE INDEX IF NOT EXISTS "clinic_workflows_org_idx"
	ON "clinic_workflows" USING btree ("organization_id");
