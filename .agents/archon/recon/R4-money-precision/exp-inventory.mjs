// R4 deliverable 1: the complete live money-column inventory as a markdown table.
// Live type from information_schema, Drizzle declaration + mode from the schema files,
// live row count from pg_stat_user_tables (exact count for the small tables).
// READ-ONLY.
import { appendFileSync, readFileSync } from "node:fs";
import pg from "pg";

const ROOT = "C:/Clinic_MVP/dental-crm";
const FILES = [
	"apps/api/src/db/schema.ts",
	"apps/api/src/db/communicationsSchema.ts",
	"apps/api/src/db/patientsSchema.ts",
];
const url = readFileSync(`${ROOT}/.env`, "utf8")
	.split(/\r?\n/)
	.find((l) => l.startsWith("DATABASE_URL="))
	.slice("DATABASE_URL=".length)
	.trim();

const decl = new Map();
for (const rel of FILES) {
	let src;
	try {
		src = readFileSync(`${ROOT}/${rel}`, "utf8");
	} catch {
		continue;
	}
	const tableStart = /export const \w+ = pgTable\(\s*"([a-z0-9_]+)"\s*,\s*\{/g;
	let m;
	while ((m = tableStart.exec(src)) !== null) {
		const table = m[1].toLowerCase();
		let depth = 1;
		let i = tableStart.lastIndex;
		while (i < src.length && depth > 0) {
			if (src[i] === "{") depth += 1;
			else if (src[i] === "}") depth -= 1;
			i += 1;
		}
		const startLine = src.slice(0, tableStart.lastIndex).split("\n").length;
		src
			.slice(tableStart.lastIndex, i - 1)
			.split("\n")
			.forEach((line, k) => {
				const d = /^\s*(\w+)\s*:\s*(\w+)\(\s*"([a-z0-9_]+)"/.exec(line);
				if (!d) return;
				const mode = /mode:\s*"(\w+)"/.exec(line);
				decl.set(`${table}.${d[3].toLowerCase()}`, {
					file: rel.replace("apps/api/src/db/", ""),
					line: startLine + k,
					builder: d[2],
					mode: mode ? mode[1] : null,
				});
			});
	}
}

const client = new pg.Client({ connectionString: url });
await client.connect();
const { rows } = await client.query(`
  select table_name, column_name, numeric_precision p, numeric_scale s,
         is_nullable, coalesce(column_default,'') dflt
  from information_schema.columns
  where table_schema='public' and data_type='numeric'
  order by table_name, column_name`);
const counts = new Map();
for (const t of new Set(rows.map((r) => r.table_name))) {
	const c = await client.query(`select count(*)::int n from "${t}"`);
	counts.set(t, c.rows[0].n);
}
await client.end();

// Money vs not-money is a judgement call; state it explicitly rather than hide it in a regex.
const NOT_MONEY = new Set([
	"confirmation_performance_reports.conversion_rate_percent",
	"diagnocat_ai_findings.ai_confidence_score",
	"diagnocat_ai_findings.confidence_score",
	"ingested_patients_mapping.confidence_score",
	"patient_duplicate_merge_queues.match_score",
	"inventory_items.current_qty",
	"inventory_items.min_qty",
	"inventory_transactions.qty",
	"procedure_material_rules.required_qty",
	"sterilization_logs.pressure_bar",
	"sterilization_logs.temperature_celsius",
	"system_ram_watchdogs.external_mb",
	"system_ram_watchdogs.heap_total_mb",
	"system_ram_watchdogs.heap_used_mb",
	"system_ram_watchdogs.rss_mb",
	"treatment_items.quantity",
]);
const PERCENT = new Set([
	"doctor_commissions.commission_pct",
	"doctor_commissions.commission_percent",
	"doctor_commissions.material_cost_deduction_pct",
	"insurance_contracts.coverage_hygiene_pct",
	"insurance_contracts.coverage_ortho_pct",
	"insurance_contracts.coverage_surgery_pct",
	"insurance_contracts.coverage_therapy_pct",
	"pricelist_doctor_payrolls.doctor_payroll_percent",
]);

const out = [];
out.push(
	"| # | table.column | live type | app type via Drizzle | declared at | rows |",
);
out.push("|---|---|---|---|---|---|");
let n = 0;
const groups = { money: [], percent: [], other: [] };
for (const r of rows) {
	const key = `${r.table_name}.${r.column_name}`;
	const d = decl.get(key);
	const appType = !d
		? "**NOT IN THE ORM**"
		: d.builder !== "numeric" && d.builder !== "decimal"
			? `**${d.builder}()** — wrong builder`
			: d.mode === "number"
				? "`number`"
				: "`string`";
	const row = `| ${++n} | \`${key}\` | numeric(${r.p},${r.s}) | ${appType} | ${d ? `${d.file}:${d.line}` : "—"} | ${counts.get(r.table_name)} |`;
	if (NOT_MONEY.has(key)) groups.other.push(row);
	else if (PERCENT.has(key)) groups.percent.push(row);
	else groups.money.push(row);
}

const md = [];
md.push("");
md.push(
	"## DELIVERABLE 1 — COMPLETE LIVE MONEY COLUMN INVENTORY (all 70 numeric columns, nothing sampled)",
);
md.push("");
md.push(
	"Generated by `.agents/archon/recon/R4-money-precision/exp-inventory.mjs` against",
);
md.push(
	"`dental_crm` on `127.0.0.1:5432` (PostgreSQL 18.4). Row counts are exact `count(*)`, not estimates.",
);
md.push(
	"**Every money column in this database stores ROUBLES with an exact 2-decimal scale. None stores kopecks as an integer,",
);
md.push(
	"and none is `integer`, `real`, `double precision` or PostgreSQL `money`.**",
);
md.push("");
md.push(`### 1a. Money (${groups.money.length} columns)`);
md.push(...out.slice(0, 2), ...groups.money);
md.push("");
md.push(
	`### 1b. Percentages that multiply money (${groups.percent.length}) — a float percent produces wrong kopecks just as reliably as a float sum`,
);
md.push(...out.slice(0, 2), ...groups.percent);
md.push("");
md.push(
	`### 1c. Non-money numerics, listed so the inventory is provably complete (${groups.other.length})`,
);
md.push(...out.slice(0, 2), ...groups.other);
md.push("");
md.push(
	`Total: ${groups.money.length} + ${groups.percent.length} + ${groups.other.length} = ${n} numeric columns. Cross-check: \`select count(*) from information_schema.columns where table_schema='public' and data_type='numeric'\` = 70.`,
);
md.push("");
appendFileSync(
	`${ROOT}/.agents/archon/recon/R4-money-precision/dossier.md`,
	md.join("\n"),
);
