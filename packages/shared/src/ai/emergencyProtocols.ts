export const emergencyActionStepSchema = z.object({
	stepNumber: z.number().int().positive(),
	titleRu: z.string().min(1),
	actionRu: z.string().min(1),
	exactMedicationDoseRu: z.string().optional(),
	contraindicationsOrWarningsRu: z.string().optional()
});

export const emergencyProtocolDefinitionSchema = z.object({
	id: z.enum([
		"emergency_anaphylaxis",
		"emergency_syncope_collapse",
		"emergency_hypochlorite_accident",
		"emergency_instrument_separation",
		"emergency_hypertensive_crisis",
		"emergency_last_toxicity"
	]),
	nameRu: z.string().min(1),
	severityLevel: z.enum(["critical_fatal_risk", "urgent_acute", "urgent_monitoring"]),
	recognitionSignsRu: z.array(z.string()).min(1),
	immediateActionsFirstMinuteRu: z.array(z.string()).min(1),
	actionSteps: z.array(emergencyActionStepSchema).min(1),
	chairsideMedicationsKit: z.array(z.string()).min(1),
	postEmergencyDispositionRu: z.string().min(1)
});
