/**
 * Получить протокол неотложной помощи по его идентификатору.
 */
export function getEmergencyProtocolById(id: EmergencyProtocolId): EmergencyProtocolDefinition | undefined {
	return EMERGENCY_PROTOCOLS[id];
}

/**
 * Найти протоколы неотложной помощи по ключевым триггерам или симптомам.
 */
export function findEmergencyProtocolsByTrigger(triggerText: string): EmergencyProtocolDefinition[] {
	if (!triggerText || !triggerText.trim()) return [];
	const lower = triggerText.toLowerCase();

	const matchedIds = new Set<EmergencyProtocolId>();

	if (
		lower.includes("анафилак") || lower.includes("квинке") || lower.includes("крапивниц") ||
		lower.includes("аллерги") || lower.includes("ларингоспазм") || lower.includes("бронхоспазм") ||
		lower.includes("отек гортани") || lower.includes("стридор")
	) {
		matchedIds.add("emergency_anaphylaxis");
	}
	if (
		lower.includes("обморок") || lower.includes("коллапс") || lower.includes("потеря сознания") ||
		lower.includes("синкопе") || lower.includes("нашатыр") || lower.includes("бледность")
	) {
		matchedIds.add("emergency_syncope_collapse");
	}
	if (
		lower.includes("гипохлорит") || lower.includes("naocl") || lower.includes("авария") ||
		lower.includes("отек щеки") || lower.includes("за апекс") || lower.includes("хлор")
	) {
		matchedIds.add("emergency_hypochlorite_accident");
	}
	if (
		lower.includes("файлолом") || lower.includes("отломок") || lower.includes("сломал") ||
		lower.includes("облом") || lower.includes("аспирац") || lower.includes("проглотил") ||
		lower.includes("сепарац")
	) {
		matchedIds.add("emergency_instrument_separation");
	}
	if (
		lower.includes("давлен") || lower.includes("гипертон") || lower.includes("криз") ||
		lower.includes("180/") || lower.includes("200/") || lower.includes("гипотензив")
	) {
		matchedIds.add("emergency_hypertensive_crisis");
	}
	if (
		lower.includes("last") || lower.includes("токсич") || lower.includes("судорог") ||
		lower.includes("передозировк") || lower.includes("интралипид") || lower.includes("липид")
	) {
		matchedIds.add("emergency_last_toxicity");
	}

	// Также проверяем вхождение триггера в симптомы распознавания всех протоколов
	for (const proto of Object.values(EMERGENCY_PROTOCOLS)) {
		if (proto.recognitionSignsRu.some((s) => s.toLowerCase().includes(lower))) {
			matchedIds.add(proto.id);
		}
	}

	return Array.from(matchedIds).map((id) => EMERGENCY_PROTOCOLS[id]);
}

/**
 * Формирует компактную клиническую шпаргалку неотложной помощи у кресла.
 */
export function formatEmergencyCheatSheet(id: EmergencyProtocolId): string {
	const proto = EMERGENCY_PROTOCOLS[id];
	if (!proto) return "Протокол не найден.";

	const lines: string[] = [
		`🚨 <b>НЕОТЛОЖНЫЙ ПРОТОКОЛ: ${proto.nameRu.toUpperCase()}</b>`,
		`⚡ <b>Уровень угрозы:</b> ${proto.severityLevel === "critical_fatal_risk" ? "КРИТИЧЕСКИЙ (УГРОЗА ЖИЗНИ)" : "НЕОТЛОЖНЫЙ"}\n`,
		`🔍 <b>Распознавание:</b>`
	];

	for (const sign of proto.recognitionSignsRu) {
		lines.push(`• ${sign}`);
	}

	lines.push(`\n⏱ <b>ДЕЙСТВИЯ ПЕРВОЙ МИНУТЫ:</b>`);
	for (const imm of proto.immediateActionsFirstMinuteRu) {
		lines.push(imm);
	}

	lines.push(`\n💉 <b>ПОШАГОВЫЙ АЛГОРИТМ:</b>`);
	for (const step of proto.actionSteps) {
		lines.push(`<b>${step.stepNumber}. ${step.titleRu}</b>`);
		lines.push(`— ${step.actionRu}`);
		if (step.exactMedicationDoseRu) {
			lines.push(`  💊 <i>Дозировка: ${step.exactMedicationDoseRu}</i>`);
		}
		if (step.contraindicationsOrWarningsRu) {
			lines.push(`  ⚠️ <i>Внимание: ${step.contraindicationsOrWarningsRu}</i>`);
		}
	}

	lines.push(`\n📦 <b>Состав укладки:</b> ${proto.chairsideMedicationsKit.join("; ")}`);
	lines.push(`\n🏥 <b>Тактика после купирования:</b> ${proto.postEmergencyDispositionRu}`);

	return lines.join("\n");
}

