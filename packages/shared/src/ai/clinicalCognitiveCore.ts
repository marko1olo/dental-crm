export interface ClinicalSystemPromptOptions {
	readonly doctorSpecialty?: "therapy" | "endodontics" | "orthopedics" | "surgery" | "periodontics" | "pediatric" | "general";
	readonly includeDisputeReferee?: boolean;
	readonly includeVisionCore?: boolean;
	readonly chairsideMode?: boolean;
	readonly customRules?: string[];
}

/**
 * Формирует строгий системный промпт для клинического ИИ-агента с когнитивным ядром EndoChat.
 */
export function buildClinicalSystemPrompt(options?: ClinicalSystemPromptOptions): string {
	const sections: string[] = [MASTER_COGNITIVE_ARCHITECTURE_TEXT];

	if (options?.includeDisputeReferee) {
		sections.push(DISPUTE_REFEREE_ARCHITECTURE_TEXT);
	}

	if (options?.includeVisionCore) {
		sections.push(VISION_COGNITIVE_ARCHITECTURE_TEXT);
	}

	if (options?.chairsideMode) {
		sections.push(
			`=== КЛИНИЧЕСКИЙ РЕЖИМ У КРЕСЛА (CHAIRSIDE COMPACT MODE) ===\n` +
			`1. Скорость и плотность: Врач работает в перчатках у кресла пациента. Ответы должны быть мгновенными, плотными и четкими.\n` +
			`2. Пресеты первого выбора: Всегда указывай точные параметры (диаметр файла, торк Н·см, обороты RPM, секунды экспозиции, процент раствора).\n` +
			`3. Безопасность превыше всего: При обнаружении рисков осложнений (авария NaOCl, анафилаксия, перфорация) немедленно активируй протокол спасения (SOS-Rescue) первой строкой!`
		);
	}

	if (options?.customRules && options.customRules.length > 0) {
		sections.push(`=== ДОПОЛНИТЕЛЬНЫЕ КЛИНИЧЕСКИЕ ДИРЕКТИВЫ ===\n` + options.customRules.join("\n"));
	}

	return sections.join("\n\n");
}

