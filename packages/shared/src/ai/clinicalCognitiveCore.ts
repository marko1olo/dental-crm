export const SHORT_DENTAL_TERMS = new Set<string>(
	Array.from(DENTAL_KEYWORDS).filter((term) => term.length < 4)
);

export const INNER_ROOTS = new Set<string>([
	"протез", "препар", "преп", "шлиф", "бонд", "скан", "имплант",
	"пломб", "цемент", "коронк", "фрез", "полир"
]);

export const NON_CLINICAL_PREFIXES = new Set<string>([
	"преподав", "преподн", "препятств", "препир", "скандал", "сканди"
]);

const WORD_SPLIT_REGEX = /[\wа-яё-]+/gi;
const REVERSE_MATCH_MIN_RATIO = 0.6;

/**
 * Проверяет, является ли слово бытовым омонимом, маскирующимся под клинический корень.
 */
export function isNonClinicalWord(word: string): boolean {
	const w = (word ?? "").toLowerCase();
	for (const p of NON_CLINICAL_PREFIXES) {
		if (w.includes(p)) return true;
	}
	return false;
}

/**
 * Проверяет, относится ли токен к стоматологической лексике.
 */
export function isDentalKeyword(word: string): boolean {
	if (!word) return false;
	const w = word.toLowerCase().trim();
	if (isNonClinicalWord(w)) return false;

	for (const term of DENTAL_KEYWORDS) {
		if (term.length <= 2) {
			if (w === term) return true;
			continue;
		}
		if (term.length < 4) {
			if (w.startsWith(term)) return true;
			continue;
		}
		if (w.startsWith(term)) return true;

		// Обратная проверка покрытия стема
		if (term.startsWith(w) && w.length >= term.length * REVERSE_MATCH_MIN_RATIO) {
			return true;
		}
	}

	// Проверка на внутренние клинические корни (препарирование, дебондинг, остеоинтеграция)
	for (const root of INNER_ROOTS) {
		if (w.includes(root)) return true;
	}

	return false;
}

/**
 * Проверяет наличие клинического стоматологического контекста в сыром тексте.
 */
export function hasDentalTerm(text: string): boolean {
	if (!text) return false;
	const tokens = text.match(WORD_SPLIT_REGEX);
	if (!tokens) return false;

	for (const token of tokens) {
		const lowerToken = token.toLowerCase();
		const parts = lowerToken.includes("-") ? [lowerToken, ...lowerToken.split("-")] : [lowerToken];

		for (const part of parts) {
			if (part.length < 4) {
				if (SHORT_DENTAL_TERMS.has(part)) return true;
				continue;
			}
			if (isNonClinicalWord(part)) continue;
			if (isDentalKeyword(part)) return true;
		}
	}

	return false;
}

/**
 * Извлекает все уникальные клинические термины из текста.
 */
export function extractDentalKeywords(text: string): string[] {
	if (!text) return [];
	const tokens = text.match(WORD_SPLIT_REGEX) ?? [];
	const matched = new Set<string>();

	for (const token of tokens) {
		const lower = token.toLowerCase();
		if (isDentalKeyword(lower)) {
			matched.add(lower);
		}
	}

	return Array.from(matched);
}

