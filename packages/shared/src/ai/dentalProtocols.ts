/**
 * Поиск протоколов по коду МКБ-10.
 */
export function findProtocolsByIcd10(code: string): DentalProtocolDefinition[] {
	if (!code) return [];
	const clean = code.trim().toUpperCase();
	return DENTAL_PROTOCOLS.filter((p) => p.codeIcd10.toUpperCase().startsWith(clean));
}

/**
 * Поиск протоколов по коду номенклатуры медицинских услуг (Приказ Минздрава РФ 804н).
 */
export function findProtocolsByNomenclatura(code: string): DentalProtocolDefinition[] {
	if (!code) return [];
	const clean = code.trim().toUpperCase();
	return DENTAL_PROTOCOLS.filter((p) => p.codeNomenclatura804n.toUpperCase().includes(clean));
}

/**
 * Поиск протоколов по специальности стоматолога.
 */
export function findProtocolsBySpecialty(specialty: DentalProtocolSpecialty): DentalProtocolDefinition[] {
	return DENTAL_PROTOCOLS.filter((p) => p.specialty === specialty);
}

/**
 * Полнотекстовый поиск по реестру клинических протоколов.
 */
export function searchProtocols(query: string): DentalProtocolDefinition[] {
	if (!query || !query.trim()) return [...DENTAL_PROTOCOLS];
	const q = query.toLowerCase().trim();
	const stem = q.length >= 5 ? q.slice(0, q.length - 2) : q;

	return DENTAL_PROTOCOLS.filter((p) => {
		const haystack = [
			p.titleRu,
			p.indicationRu,
			p.codeIcd10,
			p.codeNomenclatura804n,
			...p.materialsAndMedications,
			...p.equipmentAndInstruments
		].join(" ").toLowerCase();

		return haystack.includes(q) || haystack.includes(stem);
	});
}

export const CLINICAL_PROTOCOLS = DENTAL_PROTOCOLS;
export const searchClinicalProtocols = searchProtocols;

