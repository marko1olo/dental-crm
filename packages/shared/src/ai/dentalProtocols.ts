export interface EndoGeometryResult {
	readonly tipIso: number;
	readonly taper: number;
	readonly d0Mm: number;
	readonly d3Mm: number;
	readonly d5Mm: number;
	readonly d8Mm: number;
	readonly d12Mm: number;
	readonly d16Mm: number;
	readonly dangerZoneWarning?: string;
	readonly formulaText: string;
}

/**
 * Расчет геометрии эндодонтического инструмента и диаметров на критических уровнях:
 * Формула ISO: D_x = D_0 + (Taper * x)
 */
export function calculateEndoGeometry(tipIso: number, taper: number): EndoGeometryResult {
	const validTip = Math.max(6, Math.min(140, tipIso));
	const validTaper = taper > 0.15 ? taper / 100 : taper; // поддержка ввода .04 или 4

	const d0 = validTip / 100;
	const d3 = Number((d0 + validTaper * 3).toFixed(2));
	const d5 = Number((d0 + validTaper * 5).toFixed(2));
	const d8 = Number((d0 + validTaper * 8).toFixed(2));
	const d12 = Number((d0 + validTaper * 12).toFixed(2));
	const d16 = Number((d0 + validTaper * 16).toFixed(2));

	let dangerWarning: string | undefined;
	if (validTaper >= 0.06) {
		dangerWarning =
			`⚠️ Предупреждение по опасной зоне (Danger Zone): при конусности .${Math.round(validTaper * 100).toString().padStart(2, "0")} ` +
			`на уровне D8 диаметр инструмента составляет ${d8.toFixed(2)} мм. ` +
			`В тонких мезиальных корнях нижних моляров остаточная толщина дентина (RDT) может снизиться до критических < 0.5 мм, ` +
			`создавая высокий риск ленточной перфорации (Strip perforation). Рекомендуется ограничить апикальную конусность до .04.`;
	}

	return {
		tipIso: validTip,
		taper: validTaper,
		d0Mm: Number(d0.toFixed(2)),
		d3Mm: d3,
		d5Mm: d5,
		d8Mm: d8,
		d12Mm: d12,
		d16Mm: d16,
		...(dangerWarning ? { dangerZoneWarning: dangerWarning } : {}),
		formulaText: `D_x = ${d0.toFixed(2)} + (${validTaper.toFixed(2)} × x)`
	};
}

