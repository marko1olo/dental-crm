export const spokenAnatomicToothMap: Array<[RegExp, string]> =
	spokenAnatomicToothQuadrants.flatMap(
		({ archPattern, sidePattern, quadrant }) =>
			spokenAnatomicToothPositions.flatMap(([position, positionPattern]) => {
				const replacement = `зуб ${quadrant}${position}`;
				return [
					[
						dentalTermPattern(
							String.raw`${archPattern}\s+${sidePattern}\s+(?:${positionPattern})`,
						),
						replacement,
					],
					[
						dentalTermPattern(
							String.raw`${sidePattern}\s+${archPattern}\s+(?:${positionPattern})`,
						),
						replacement,
					],
					[
						dentalTermPattern(
							String.raw`(?:${positionPattern})\s+${archPattern}\s+${sidePattern}`,
						),
						replacement,
					],
				] as Array<[RegExp, string]>;
			}),
	);
